type OclSections = {
  definition?: string | null;
  precondition: string;
  postcondition: string;
};

type EvalParams = {
  project: keyof typeof project;
  useCase: string;
  operation: string;
  contract?: string;
  ocl: OclSections;
  generatedSubsetValidation?: boolean;
  oracleProfile?: OracleProfile;
};

const toPlainErrors = (errors: unknown[]) =>
  errors.map((e) => {
    if (e && typeof e === 'object') {
      return e;
    }
    return {msg: String(e)};
  });

const runOperationTests = async (
  key: keyof typeof project,
  uc: string,
  op: string,
  typescriptCode: Awaited<ReturnType<typeof createEntryCode>>,
  oracleProfile?: OracleProfile
) => {
  const p = project[key];
  const useCase = p.useCase[uc as keyof typeof p.useCase] as UseCase;
  const service = useCase.relatedService;
  const operation = service.operations.find((o) => o.name === op)!;
  const serviceName = service.name;
  const operationName = operation.name;
  const testDir = path.resolve(process.cwd(), 'test');
  const folder = path.resolve(testDir, 'tmp');
  fs.ensureDirSync(folder);
  const fileName = `${key}${serviceName}${operationName}${randomUUID().replaceAll('-', '')}`;
  const testFileName = `${fileName}.test.ts`;
  const testFilePath = path.resolve(folder, testFileName);
  const filePath = path.resolve(folder, `${fileName}.ts`);
  const originTestFilePath = historicalOraclePath(
    oracleProfile,
    key,
    uc,
    op,
    path.resolve(testDir, `${key}-${serviceName}-${operationName}/index.test.ts`)
  );
  const originTestFileAst = babel.parse(fs.readFileSync(originTestFilePath, 'utf-8'), {
    filename: 'test.ts',
    presets: [presetTypescript],
  })!;
  babel.traverse(originTestFileAst, {
    enter(path) {
      if (path.isStringLiteral({value: './entry'})) {
        path.node.value = `./${fileName}`;
      }
      if (path.isIdentifier({name: serviceName})) {
        path.node.name = `${serviceName}_AutoGenerated`;
      }
    },
  });
  fs.writeFileSync(testFilePath, generate(originTestFileAst).code, 'utf-8');
  const boundarySource = boundaryOraclePath(oracleProfile, key, uc, op);
  const boundaryTestFileName = `${fileName}.boundary.test.ts`;
  const boundaryTestFilePath = path.resolve(folder, boundaryTestFileName);
  if (boundarySource) {
    writeCandidateBoundaryOracle({
      source: boundarySource,
      output: boundaryTestFilePath,
      candidateModule: `./${fileName}`,
      serviceName,
    });
  }
  const runtime = await createIsolatedTestRuntime();
  try {
    fs.writeFileSync(filePath, buildEntryCode({service: typescriptCode.originalService,
      entity: typescriptCode.originalEntity, runtimeModule: `./${path.basename(runtime.path, '.ts')}`}));
    const res = await jestRunner.runCLI(
      {
        _: [
          `test/tmp/${testFileName}`,
          ...(boundarySource ? [`test/tmp/${boundaryTestFileName}`] : []),
        ],
        $0: '',
        // Raw matcher details may contain cyclic domain objects. Use the sanitized summary below.
        json: false,
        runInBand: true,
        coverage: true,
        runTestsByPath: true,
        config: runtime.config,
      },
      [process.cwd()]
    );
    const result = summarizeJestResults(res.results, boundarySource ? 2 : 1);
    return {
      passing: result.numPassingTests,
      failing: result.numFailingTests,
      pending: result.numPendingTests,
      success: result.success,
      status: result.status,
      message: result.message,
      summaryVersion: result.summaryVersion,
    };
  } finally {
    runtime.dispose();
    fs.removeSync(testFilePath);
    if (boundarySource) fs.removeSync(boundaryTestFilePath);
    fs.removeSync(filePath);
  }
};

export const evaluateContract = async ({
  project: key,
  useCase: uc,
  operation: op,
  contract,
  ocl,
  generatedSubsetValidation = false,
  oracleProfile,
}: EvalParams) => {
  const contractParse = contract ? parse(contract) : null;
  const contractErrors = contractParse ? toPlainErrors(contractParse.errors) : [];
  if (contractParse && contractErrors.length > 0) {
    return {
      contract_parse_ok: false,
      contract_errors: contractErrors,
      typescript_generation_ok: false,
      typescript_parse_ok: false,
      typescript_errors: [],
      test_execution_ok: false,
      test_passing_count: 0,
      test_failing_count: 0,
    };
  }
  if (generatedSubsetValidation && contractParse?.tree) {
    const projectModel = project[key];
    const useCaseModel = projectModel?.useCase[uc as keyof typeof projectModel.useCase] as
      | UseCase
      | undefined;
    const operationModel = useCaseModel?.relatedService.operations.find((item) => item.name === op);
    if (!operationModel) {
      throw new Error(`Unknown operation for generated-subset validation: ${key}/${uc}/${op}`);
    }
    const subsetErrors = validateGeneratedContractSemantics({
      tree: contractParse.tree,
      hasReturnValue: Boolean(operationModel.returnType?.type),
    });
    if (subsetErrors.length > 0) {
      return {
        contract_parse_ok: true,
        generated_subset_ok: false,
        generated_subset_errors: subsetErrors,
        contract_errors: [],
        typescript_generation_ok: false,
        typescript_parse_ok: false,
        typescript_errors: [],
        test_execution_ok: false,
        test_passing_count: 0,
        test_failing_count: 0,
      };
    }
    const modelRuleValidation = validateModelGroundedContract({
      tree: contractParse.tree,
      context: createOperationModelGrounding({project: key, useCase: uc, operation: op}),
    });
    if (modelRuleValidation.diagnostics.length) return {
      contract_parse_ok: true, generated_subset_ok: false,
      generated_subset_errors: modelRuleValidation.diagnostics,
      model_rule_validation: modelRuleValidation,
      contract_errors: [], typescript_generation_ok: false, typescript_parse_ok: false,
      typescript_errors: [], test_execution_ok: false, test_passing_count: 0, test_failing_count: 0,
    };
  }
  let typescriptCode: Awaited<ReturnType<typeof createEntryCode>>;
  try {
    typescriptCode = await createEntryCode({
      project: key,
      useCase: uc as never,
      operation: op,
      ocl: {
        definition: ocl.definition || undefined,
        precondition: ocl.precondition,
        postcondition: ocl.postcondition,
      },
    });
  } catch (error) {
    return {
      contract_parse_ok: true,
      contract: contractParse
        ? formatContract(contractParse.tree!, contractParse.tokens)
        : contract,
      contract_errors: [],
      typescript_generation_ok: false,
      typescript_generation_error: (error as Error).message,
      typescript_parse_ok: false,
      typescript_errors: [],
      test_execution_ok: false,
      test_passing_count: 0,
      test_failing_count: 0,
    };
  }
  const typescriptErrors = parseTypescriptEntry(typescriptCode.entry);
  if (typescriptErrors.length > 0) {
    return {
      contract_parse_ok: true,
      contract: contractParse
        ? formatContract(contractParse.tree!, contractParse.tokens)
        : contract,
      contract_errors: [],
      typescript_generation_ok: true,
      typescript_parse_ok: false,
      typescript_errors: typescriptErrors,
      test_execution_ok: false,
      test_passing_count: 0,
      test_failing_count: 0,
    };
  }
  try {
    const testResult = await runOperationTests(key, uc, op, typescriptCode, oracleProfile);
    return {
      contract_parse_ok: true,
      contract: contractParse
        ? formatContract(contractParse.tree!, contractParse.tokens)
        : contract,
      contract_errors: [],
      typescript_generation_ok: true,
      typescript_parse_ok: true,
      typescript_errors: [],
      test_execution_ok: testResult.success,
      test_result_status: testResult.status,
      test_result_summary_version: testResult.summaryVersion,
      test_execution_error: testResult.message,
      test_passing_count: testResult.passing,
      test_failing_count: testResult.failing,
      test_pending_count: testResult.pending,
    };
  } catch (error) {
    return {
      contract_parse_ok: true,
      contract: contractParse
        ? formatContract(contractParse.tree!, contractParse.tokens)
        : contract,
      contract_errors: [],
      typescript_generation_ok: true,
      typescript_parse_ok: true,
      typescript_errors: [],
      test_execution_ok: false,
      test_execution_error: (error as Error).message,
      test_passing_count: 0,
      test_failing_count: 0,
    };
  }
};
