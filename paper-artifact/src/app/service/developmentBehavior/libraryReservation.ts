import dayjs from 'dayjs';
import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {librarySearchSources} from './librarySearchSpecification';
import {runFiniteScenarios} from './finiteScenarioReport';
import type {DevelopmentObligation, DevelopmentRegistration} from './types';

type Operation = 'makeReservation' | 'cancelReservation';
type Obj = Record<string, unknown>;
type Module = {User: new () => Obj; BookCopy: new () => Obj; Reserve: new () => Obj;
  CopyStatus: Obj; getRepository(c: new () => Obj): Obj[];
  LibraryManagementSystemSystem_AutoGenerated: new () => Record<Operation, (uid: string, barcode: string) => unknown>};
type Rule = [string, ...string[]];
export function reservationRegistration(operation: Operation): DevelopmentRegistration {
  const make = operation === 'makeReservation';
  const id = 'LibraryManagementSystem_' + operation + '_' + operation;
  const schemaVersion = 'development-library-' + operation + '-v1';
  const pre: Rule[] = [['The selected User exists.', 'User.UserID', '$parameter.uid'],
    ['The selected copy exists.', 'BookCopy.Barcode', '$parameter.barcode'], ['The copy is loaned.', 'BookCopy.Status'],
    [make ? 'The copy is not reserved.' : 'The copy is reserved.', 'BookCopy.IsReserved']];
  if (!make) pre.push(['A reservation matches both objects.', 'Reserve.ReservedUser', 'Reserve.ReservedCopy'],
    ['The matching reservation is open.', 'Reserve.IsReserveClosed']);
  const post: Rule[] = make ? [
    ['Create a fresh Reserve.', 'Reserve'], ['Mark the copy reserved.', 'BookCopy.IsReserved'],
    ['Keep the new reservation open.', 'Reserve.IsReserveClosed'], ['Set the reservation date to today.', 'Reserve.ReserveDate'],
    ['Link to the selected user.', 'Reserve.ReservedUser'], ['Link to the selected copy.', 'Reserve.ReservedCopy'],
    ['Include the reservation in the user association.', 'User.ReservedBook'],
    ['Include the reservation in the copy association.', 'BookCopy.ReservationRecord'],
    ['Store the new reservation.', 'Reserve'], ['Return true.', '$result'],
  ] : [['Clear the selected copy reservation flag.', 'BookCopy.IsReserved'],
    ['Close the matching reservation.', 'Reserve.IsReserveClosed'], ['Return true.', '$result']];
  const rules = (rows: Rule[], prefix: string, doc: number, model: number): DevelopmentObligation[] =>
    rows.map(([requirement, ...modelFeatures], i) => ({id: prefix + String(i + 1).padStart(2, '0'),
      clause: prefix === 'P' ? 'precondition' : 'postcondition', requirement, modelFeatures,
      documentLine: doc + i, modelLines: [model + i, model + i]}));
  const obligations = [...rules(pre, 'P', make ? 2211 : 2312, make ? 291 : 352),
    ...rules(post, 'Q', make ? 2231 : 2325, make ? 312 : 366)];
  const scenarios = ['valid', 'empty-identifiers', ...obligations.filter(o => o.clause === 'precondition').map(o => o.id)]
    .map(key => ({key, id: 'dev-' + operation + '-' + key, rejectObligation: key.startsWith('P') ? key : undefined,
      obligationIds: key.startsWith('P') ? [key] : obligations.map(o => o.id)}));
  return {id, schemaVersion, operation, useCase: operation, project: 'LibraryManagementSystem',
    reviewStatus: 'pending-user-review', fixedClock: '2026-01-15T12:00:00+08:00',
    sources: librarySearchSources.map(source => ({...source, note: 'Active reservation clauses; document and remodel share a source lineage.'})),
    requirementSourceId: 'requirement-document', modelSourceId: 'upstream-model', obligations, scenarios,
    moduleExports: {User: 'function', BookCopy: 'function', Reserve: 'function', getRepository: 'function',
      CopyStatus: 'object', LibraryManagementSystemSystem_AutoGenerated: 'function'},
    run(candidate, {requirementText}) {
      const requirement = formatStructuredRequirement(getBenchmarkRequirement('LibraryManagementSystem', operation, operation));
      if (requirementText.replaceAll('\r\n', '\n').trim() !== requirement.replaceAll('\r\n', '\n').trim())
        throw new Error('Reservation requirement differs from registered input');
      const m = candidate as Module;
      return runFiniteScenarios({id, schemaVersion, obligations}, scenarios, base => {
        const {key} = scenarios.find(s => s.id === base.id)!;
        const users = m.getRepository(m.User), copies = m.getRepository(m.BookCopy), records = m.getRepository(m.Reserve);
        users.splice(0); copies.splice(0); records.splice(0);
        const uid = key === 'empty-identifiers' ? '' : 'dev-user', barcode = key === 'empty-identifiers' ? '' : 'dev-copy';
        const user = Object.assign(new m.User(), {UserID: uid, ReservedBook: [] as Obj[]});
        const copy = Object.assign(new m.BookCopy(), {Barcode: barcode, Status: key === 'P03' ? m.CopyStatus.AVAILABLE : m.CopyStatus.LOANED,
          IsReserved: key === 'P04' ? make : !make, ReservationRecord: [] as Obj[]});
        const otherUser = Object.assign(new m.User(), {UserID: 'other', ReservedBook: []});
        const otherCopy = Object.assign(new m.BookCopy(), {Barcode: 'other', ReservationRecord: []});
        users.push(otherUser); copies.push(otherCopy);
        if (key !== 'P01') users.push(user);
        if (key !== 'P02') copies.push(copy);
        const record = (u: Obj, c: Obj, closed: boolean) => Object.assign(new m.Reserve(), {ReservedUser: u, ReservedCopy: c, IsReserveClosed: closed});
        const target = record(user, copy, key === 'P06');
        records.push(record(otherUser, copy, false), record(user, otherCopy, false));
        if (!make && key !== 'P05') records.push(target);
        const before = new Set(records), today = dayjs();
        const admission = [users.includes(user), copies.includes(copy), copy.Status === m.CopyStatus.LOANED,
          copy.IsReserved === !make, records.includes(target), !target.IsReserveClosed];
        const state = () => {
          const effects = (r?: Obj) => [!!r, copy.IsReserved === true, r?.IsReserveClosed === false,
            !!r && dayjs.isDayjs(r.ReserveDate) && r.ReserveDate.isSame(today, 'day'),
            r?.ReservedUser === user, r?.ReservedCopy === copy, !!r && user.ReservedBook.includes(r),
            !!r && copy.ReservationRecord.includes(r), !!r && records.includes(r)];
          // All creation obligations refer to one fresh witness, not one object per assertion.
          const witnesses = [...records, ...user.ReservedBook, ...copy.ReservationRecord].filter(r => r instanceof m.Reserve && !before.has(r));
          const valid = make ? effects(witnesses.find(r => effects(r).every(Boolean)) ?? witnesses[0]) :
            [copy.IsReserved === false, target.IsReserveClosed === true];
          return valid.map((passed, i) => ({obligationId: obligations[pre.length + i].id, passed, expected: post[i][0], observed: passed}));
        };
        return {invoke: () => new m.LibraryManagementSystemSystem_AutoGenerated()[operation](uid, barcode),
          observePrecondition: code => ({satisfied: admission[Number(code.slice(1)) - 1],
            expected: pre[Number(code.slice(1)) - 1][0], observed: admission[Number(code.slice(1)) - 1]}),
          observeAfterPostcheckFailure: state,
          observe: result => [...obligations.slice(0, pre.length).map(o => ({obligationId: o.id, passed: true, expected: 'accepted', observed: 'completed'})),
            ...state(), {obligationId: obligations[obligations.length - 1].id, passed: result === true, expected: true, observed: result}]};
      });
    }};
}
