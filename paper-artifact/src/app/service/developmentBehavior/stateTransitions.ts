import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import type {DevelopmentBehaviorReport, DevelopmentDiagnostic} from './types';
import {narrativeDevelopmentProfile} from './narrativeDevelopmentProfiles';
import {
  stateTransitionSpecifications,
  transitionScenarios,
  type StateTransitionOperation,
} from './stateTransitionSpecification';

type Data = Record<string, unknown>;
type Constructor = new () => Data;
export type TransitionModule = Record<string, unknown> & {
  getRepository: (type: Constructor) => Data[];
};

export function runStateTransitionDevelopment(
  m: TransitionModule,
  options: {requirementText: string},
  operation: StateTransitionOperation
): DevelopmentBehaviorReport {
  const spec = stateTransitionSpecifications[operation];
  const expected = formatStructuredRequirement(
    getBenchmarkRequirement(spec.project, spec.useCase, operation)
  );
  const normalize = (text: string) => text.replaceAll('\r\n', '\n').trim();
  if (!narrativeDevelopmentProfile(spec.id,options.requirementText)&&normalize(options.requirementText) !== normalize(expected))
    throw new Error(
      'State transition requirement differs from the registered input; review alignment'
    );
  const Entity = m[spec.entity] as Constructor;
  const Service = m[`${spec.service}_AutoGenerated`] as Constructor;
  const enumValues = m.LoanStatus as Data | undefined;
  if (
    spec.entity === 'Loan' &&
    (!enumValues ||
      enumValues.LSOPEN === undefined ||
      enumValues.CLOSED === undefined ||
      enumValues.LSOPEN === enumValues.CLOSED)
  )
    throw new Error('Missing distinct declared loan status values');
  const resolveState = (value: boolean | string) =>
    typeof value === 'string' ? enumValues![value] : value;
  const scenarios = transitionScenarios(spec);
  const checks: DevelopmentBehaviorReport['checks'] = [];
  const diagnostics: DevelopmentDiagnostic[] = [];
  const observations: DevelopmentBehaviorReport['executionObservations'] = [];
  for (const scenario of scenarios) {
    const repository = m.getRepository(Entity);
    repository.splice(0);
    if (spec.parentStore) m.getRepository(m.Store as Constructor).splice(0);
    const target = Object.assign(new Entity(), {
      [spec.identifier]: scenario.identifier,
      [spec.feature]: resolveState(
        scenario.correctState
          ? spec.before
          : typeof spec.before === 'boolean'
            ? !spec.before
            : 'CLOSED'
      ),
      // OP24 specifies no balance guard; a nonzero amount is deliberate.
      ...(spec.entity === 'Loan' ? {RemainAmountToPay: 125.5} : {}),
    });
    if (scenario.neighbors)
      repository.push(
        Object.assign(new Entity(), {
          [spec.identifier]: 981999,
          [spec.feature]: resolveState(spec.before),
        })
      );
    if (scenario.exists) repository.push(target);
    const service = new Service();
    if (spec.current)
      service[spec.current] = Object.assign(new Entity(), {[spec.identifier]: 982999});
    if (spec.parentStore)
      service.CurrentStore = scenario.parentExists
        ? Object.assign(new (m.Store as Constructor)(), {Id: 983001, IsOpened: scenario.parentOpen})
        : undefined;
    const check = (id: string, passed: boolean | null, wanted: unknown, observed: unknown) => {
      checks.push({scenarioId: scenario.id, obligationId: id, passed, expected: wanted, observed});
      if (passed === false)
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: 'OBLIGATION_MISMATCH',
          obligationIds: [id],
          expected: wanted,
          observed,
          message: spec.obligations.find((item) => item.id === id)!.requirement,
        });
    };
    let result: unknown;
    const admissionFacts=[
      {obligationId:'P01',satisfied:repository.includes(target)},
      {obligationId:'P02',satisfied:target[spec.feature]===resolveState(spec.before)},
      ...(spec.parentStore?[
        {obligationId:'P03',satisfied:service.CurrentStore!==undefined&&service.CurrentStore!==null},
        {obligationId:'P04',satisfied:(service.CurrentStore as Data|undefined)?.IsOpened===true},
      ]:[]),
    ];
    const admissionEvidence=admissionFacts.every(f=>f.satisfied)?{
      basis:'independent-source-precondition-observation',timing:'before-invocation',allSatisfied:true,
      obligationIds:admissionFacts.map(f=>f.obligationId),observations:admissionFacts,
      targetSelection:{basis:'registered-source-identifier-selection',entity:spec.entity,
        identifier:spec.identifier,parameter:spec.parameter,
        ...(spec.current?{currentReference:spec.current,currentMatchesSelectedTarget:service[spec.current]===target}:{}),
      },
    }:undefined;
    let failure: {name: string; message: string;oclOrigin?:unknown} | undefined;
    try {
      const method = service[operation];
      if (typeof method !== 'function') throw new Error('Candidate service method missing');
      result = method.call(service, scenario.identifier);
    } catch (error) {
      failure =
        error instanceof Error
          ? {name: error.name, message: error.message,...('oclOrigin' in error?{oclOrigin:error.oclOrigin}:{})}
          : {name: 'Error', message: String(error)};
    }
    if (failure) {
      const definitionFailure =
        failure.name === 'PreconditionError' &&
        failure.message.includes('definition binding could not be evaluated');
      const rejected = failure.name === 'PreconditionError' && !definitionFailure;
      observations.push({
        scenarioId: scenario.id,
        classification: definitionFailure
          ? 'definition-failure-unresolved'
          : rejected
            ? 'explicit-rejection'
            : 'runtime-error',
        conventionStatus: definitionFailure ? 'inconclusive' : rejected ? 'matched' : 'mismatched',
      });
      if (rejected && scenario.rejectObligation)
        check(scenario.rejectObligation, true, 'request rejected', failure.name);
      else
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: definitionFailure&&admissionEvidence?'UNEXPECTED_REJECTION':definitionFailure
            ? 'REJECTION_UNRESOLVED'
            : rejected
              ? 'UNEXPECTED_REJECTION'
              : 'EXECUTION_ERROR',
          obligationIds:
            (rejected||definitionFailure&&admissionEvidence) && !scenario.rejectObligation
              ? ['P01', 'P02', ...(spec.parentStore ? ['P03', 'P04'] : [])]
              : [],
          expected: scenario.rejectObligation ? 'request rejected' : 'successful transition',
          observed: {...failure,...(admissionEvidence?{admissibilityEvidence:admissionEvidence}:{})},
          message:
            'Execution did not reach the expected outcome; an arbitrary exception is not a proven source-obligation violation.',
        });
      if(admissionEvidence&&(failure.name==='PostconditionError'||
        (failure.oclOrigin as {clause?:string}|undefined)?.clause==='postcondition')){
        // Independent state witnesses, not the exception message, support effect diagnostics.
        if(target[spec.feature]!==resolveState(spec.after))
          check('Q01',false,resolveState(spec.after),target[spec.feature]??null);
        if(spec.current&&service[spec.current]!==target)
          check('Q02',false,'current object is selected target','other or undefined');
      }
      continue;
    }
    if (scenario.rejectObligation) {
      observations.push({
        scenarioId: scenario.id,
        classification: 'return-without-rejection-signal',
        conventionStatus: 'mismatched',
      });
      if (result === true)
        check(
          scenario.rejectObligation,
          false,
          'no successful operation for an ineligible state',
          true
        );
      else {
        check(scenario.rejectObligation, null, 'recognized rejection', result ?? null);
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: 'REJECTION_UNRESOLVED',
          obligationIds: [],
          expected: 'recognized rejection',
          observed: result ?? null,
          message: 'A non-success return alone does not establish source-aligned rejection.',
        });
      }
      continue;
    }
    observations.push({
      scenarioId: scenario.id,
      classification: 'completed',
      conventionStatus: 'matched',
    });
    check('P01', true, 'existing target accepted', 'accepted');
    check('P02', true, 'required target state accepted', 'accepted');
    if (spec.parentStore) {
      check('P03', true, 'defined current Store accepted', 'accepted');
      check('P04', true, 'open current Store accepted', 'accepted');
    }
    check(
      'Q01',
      target[spec.feature] === resolveState(spec.after),
      resolveState(spec.after),
      target[spec.feature] ?? null
    );
    if (spec.current)
      check(
        'Q02',
        service[spec.current] === target,
        'current object is selected target',
        service[spec.current] === target ? 'selected target' : 'other or undefined'
      );
    check('Q03', result === true, true, result ?? null);
  }
  const businessStatus = diagnostics.some((item) =>
    ['OBLIGATION_MISMATCH', 'UNEXPECTED_REJECTION', 'SPECIFICATION_DETAIL_MISMATCH'].includes(
      item.code
    )
  )
    ? 'mismatched'
    : diagnostics.length
      ? 'inconclusive'
      : 'matched';
  const executionConventionStatus = observations.some(
    (item) => item.conventionStatus === 'mismatched'
  )
    ? 'mismatched'
    : observations.some((item) => item.conventionStatus === 'inconclusive')
      ? 'inconclusive'
      : 'matched';
  const observed = new Set(
    checks.filter((item) => item.passed !== null).map((item) => item.obligationId)
  );
  return {
    schemaVersion: spec.schemaVersion,
    operationId: spec.id,
    role: 'development_only',
    reviewStatus: 'pending-user-review',
    hiddenEvaluationUsed: false,
    dynamicRepairEnabled: false,
    coverageScope: 'finite-development-scenarios',
    businessAssessmentBasis: 'cited-upstream-operation-specification-and-aligned-current-input',
    assessmentPolicy: {
      frame:
        'No unrelated attribute, repository, rollback or association preservation is inferred.',
      context:
        'The cash-desk parent Store need only be defined and open; repository membership and cash-desk/store association are not inferred.',
      balance: 'No zero-balance guard is added to loan closure.',
    },
    businessStatus,
    executionConventionStatus,
    scenarioCount: scenarios.length,
    executionObservations: observations,
    scenarioResults: scenarios.map((scenario) => ({
      id: scenario.id,
      passed: !diagnostics.some((item) => item.scenarioId === scenario.id),
      checkCount: checks.filter((item) => item.scenarioId === scenario.id).length,
    })),
    checks,
    diagnostics,
    unobservedObligationIds: spec.obligations
      .filter((item) => !observed.has(item.id))
      .map((item) => item.id),
    passed:
      businessStatus === 'matched' && executionConventionStatus === 'matched' && checks.length > 0,
  };
}
