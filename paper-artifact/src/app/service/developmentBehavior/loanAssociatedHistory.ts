import {formatStructuredRequirement,getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios} from './finiteScenarioReport';
import {submittedRequestsSources} from './submittedLoanRequestsSpecification';
import type {DevelopmentRegistration,DevelopmentObligation} from './types';

type Request={RequestID:number;RequestedCreditHistory?:object;RequestedCAHistory?:object};
type Service={CurrentLoanRequest?:Request;checkCreditHistory:()=>unknown;reviewCheckingAccount:()=>unknown};
type Module={LoanRequest:new()=>Request;CreditHistory:new()=>object;CheckingAccount:new()=>object;
  EvaluateLoanRequestModule_AutoGenerated:new()=>Service;getRepository:(ctor:new()=>Request)=>Request[]};
export function loanAssociatedHistoryRegistration(operation:'checkCreditHistory'|'reviewCheckingAccount'):DevelopmentRegistration{
  const credit=operation==='checkCreditHistory',field=credit?'RequestedCreditHistory':'RequestedCAHistory';
  const type=credit?'CreditHistory':'CheckingAccount',id='LoanProcessingSystem_evaluateLoanRequest_'+operation;
  const lines=credit?{doc:[1867,1868,1874],model:[520,521,528]}:{doc:[1924,1925,1931],model:[540,541,548]};
  const obligations:DevelopmentObligation[]=[
    {id:'P01',clause:'precondition',requirement:'A current LoanRequest exists.',
      documentLine:lines.doc[0],modelLines:[lines.model[0],lines.model[0]],modelFeatures:['self.CurrentLoanRequest']},
    {id:'P02',clause:'precondition',requirement:'The current request has an attached '+type+'.',
      documentLine:lines.doc[1],modelLines:[lines.model[1],lines.model[1]],modelFeatures:['LoanRequest.'+field]},
    {id:'Q01',clause:'postcondition',requirement:'Return the attached '+type+' instance.',
      documentLine:lines.doc[2],modelLines:[lines.model[2],lines.model[2]],modelFeatures:['LoanRequest.'+field,'$result']},
  ];
  const cases=[{key:'second',ids:['P01','P02','Q01']},{key:'first',ids:['P01','P02','Q01']},
    {key:'no-current',ids:['P01'],reject:'P01'},{key:'no-link',ids:['P02'],reject:'P02'}];
  const scenarios=cases.map(c=>({id:'dev-loan-'+operation+'-'+c.key,obligationIds:c.ids,rejectObligation:c.reject}));
  return {id,project:'LoanProcessingSystem',useCase:'evaluateLoanRequest',operation,schemaVersion:'development-loan-history-v1',
    reviewStatus:'pending-user-review',fixedClock:'2026-01-15T12:00:00+08:00',
    sources:submittedRequestsSources.map(source=>({...source,note:source.id==='requirement-document'
      ? 'Active '+operation+' requirement lines '+lines.doc.join(', ')+'.'
      : 'Active '+operation+' model contract lines '+lines.model.join(', ')+'.'})),
    requirementSourceId:'requirement-document',modelSourceId:'upstream-model',obligations,scenarios,
    moduleExports:{LoanRequest:'function',CreditHistory:'function',CheckingAccount:'function',
      EvaluateLoanRequestModule_AutoGenerated:'function',getRepository:'function'},
    run(candidate,{requirementText}){
      const expected=formatStructuredRequirement(getBenchmarkRequirement('LoanProcessingSystem','evaluateLoanRequest',operation));
      if(requirementText.replaceAll('\r\n','\n').trim()!==expected.replaceAll('\r\n','\n').trim())
        throw new Error('Loan history input differs from frozen requirement');
      const m=candidate as Module;
      return runFiniteScenarios({id,schemaVersion:'development-loan-history-v1',obligations},scenarios,scenario=>{
        const key=cases.find(c=>'dev-loan-'+operation+'-'+c.key===scenario.id)!.key;
        const repo=m.getRepository(m.LoanRequest);repo.splice(0);
        const first=Object.assign(new m.LoanRequest(),{RequestID:11});
        const second=Object.assign(new m.LoanRequest(),{RequestID:22});
        const firstHistory=new m[type](),secondHistory=new m[type]();
        first[field]=firstHistory; if(key!=='no-link')second[field]=secondHistory;
        repo.push(first,second);
        const service=new m.EvaluateLoanRequestModule_AutoGenerated();
        if(key!=='no-current')service.CurrentLoanRequest=key==='first'?first:second;
        const selected=key==='first'?firstHistory:secondHistory;
        const admitted=key!=='no-current',linked=key!=='no-link';
        return {invoke:()=>service[operation](),
          observePrecondition:code=>({satisfied:code==='P01'?admitted:linked,
            expected:obligations.find(o=>o.id===code)!.requirement,observed:code==='P01'?admitted:linked}),
          observe:result=>[
            {obligationId:'P01',passed:admitted,expected:true,observed:admitted},
            {obligationId:'P02',passed:linked,expected:true,observed:linked},
            {obligationId:'Q01',passed:result===selected,expected:selected,observed:result},
          ]};
      });
    },
  };
}
