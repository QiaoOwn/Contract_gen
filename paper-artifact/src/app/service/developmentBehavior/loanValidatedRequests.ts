import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios} from './finiteScenarioReport';
import {narrativeDevelopmentProfile} from './narrativeDevelopmentProfiles';
import {submittedRequestsSources} from './submittedLoanRequestsSpecification';
import type {DevelopmentRegistration, DevelopmentObligation} from './types';

type Request = {RequestID: number; Status: unknown};
type Module = {
  LoanRequest: new () => Request;
  LoanRequestStatus: Record<string, unknown>;
  getRepository: (ctor: new () => Request) => Request[];
  EvaluateLoanRequestModule_AutoGenerated: new () => {
    CurrentLoanRequests: Request[];
    listTenLoanRequest: () => unknown;
    listApprovalRequest: () => unknown;
  };
  GenerateLoanLetterAndAgreementModule_AutoGenerated: Module['EvaluateLoanRequestModule_AutoGenerated'];
};
const scenarios = ['mixed','more-than-ten','empty'] as const;
const sameMembers = (actual: unknown, expected: Request[]) => Array.isArray(actual) &&
  actual.length === expected.length && expected.every(item => actual.includes(item));
export function loanStatusListRegistration(operation:'listTenLoanRequest'|'listApprovalRequest'):DevelopmentRegistration {
const approved=operation==='listApprovalRequest';
const useCase=approved?'generateLoanLetterAndAgreement':'evaluateLoanRequest';
const serviceName=approved?'GenerateLoanLetterAndAgreementModule_AutoGenerated':'EvaluateLoanRequestModule_AutoGenerated';
const statusName=approved?'APPROVED':'REFERENCESVALIDATED';
const id='LoanProcessingSystem_'+useCase+'_'+operation;
const obligations: DevelopmentObligation[] = [
  {id:'P01',clause:'precondition',requirement:'The selection collection is defined, including when empty.',
    documentLine:approved?2173:1741,modelLines:[approved?636:471,approved?636:471],modelFeatures:['LoanRequest']},
  {id:'Q01',clause:'postcondition',requirement:'CurrentLoanRequests contains all and only '+statusName+' requests.',
    documentLine:approved?2180:1748,modelLines:[approved?644:479,approved?644:479],
    modelFeatures:['LoanRequest.Status','self.CurrentLoanRequests']},
  {id:'Q02',clause:'postcondition',requirement:'Return the same selected request set.',
    documentLine:approved?2181:1749,modelLines:[approved?645:480,approved?645:480],
    modelFeatures:['$result','LoanRequest.Status']},
];
return {
  id,project:'LoanProcessingSystem',useCase,operation,
  schemaVersion:'development-loan-validated-v1',reviewStatus:'pending-user-review',
  fixedClock:'2026-01-15T12:00:00+08:00',
  sources:submittedRequestsSources.map(source => ({...source,
    note:source.id==='requirement-document'
      ? (approved?'OP15, lines 2160-2181: filter all APPROVED requests, state and result.'
        :'OP8, lines 1728-1749: filter all REFERENCESVALIDATED requests; defined collection; state and result.')
      : (approved?'Active contract lines 621-645: select APPROVED requests, state and result.'
        :'Active contract lines 456-480: all-instance selection, defined collection, state and result.')})),
  requirementSourceId:'requirement-document',modelSourceId:'upstream-model',obligations,
  scenarios:scenarios.map(key=>({id:'dev-loan-list-'+operation+'-'+key,obligationIds:obligations.map(item=>item.id)})),
  moduleExports:{LoanRequest:'function',LoanRequestStatus:'object',
    [serviceName]:'function',getRepository:'function'},
  run(candidate,{requirementText}) {
    const expected=formatStructuredRequirement(getBenchmarkRequirement('LoanProcessingSystem',
      useCase,operation));
    if(!narrativeDevelopmentProfile(id,requirementText)&&requirementText.replaceAll('\r\n','\n').trim()!==expected.replaceAll('\r\n','\n').trim())
      throw new Error('Validated requests input differs from frozen requirement');
    const m=candidate as Module;
    const defined=scenarios.map(key=>({key,id:'dev-loan-list-'+operation+'-'+key,obligationIds:obligations.map(item=>item.id)}));
    return runFiniteScenarios({id,schemaVersion:'development-loan-validated-v1',obligations},
      defined,scenario=>{
        const key=defined.find(item=>item.id===scenario.id)!.key;
        const repo=m.getRepository(m.LoanRequest);repo.splice(0);
        const count=key==='more-than-ten'?13:key==='empty'?0:3;
        for(let i=0;i<count;i++)repo.push(Object.assign(new m.LoanRequest(),
          {RequestID:i+1,Status:key==='mixed'&&i===1?m.LoanRequestStatus.SUBMITTED:
            m.LoanRequestStatus[statusName]}));
        if(key==='empty')repo.push(Object.assign(new m.LoanRequest(),
          {RequestID:99,Status:m.LoanRequestStatus.SUBMITTED}));
        const selected=repo.filter(request=>request.Status===m.LoanRequestStatus[statusName]);
        const service=new m[serviceName]();
        service.CurrentLoanRequests=[Object.assign(new m.LoanRequest(),
          {RequestID:100,Status:m.LoanRequestStatus.SUBMITTED})];
        const state=()=>[{obligationId:'Q01',passed:sameMembers(service.CurrentLoanRequests,selected),
          expected:selected.map(r=>r.RequestID),observed:service.CurrentLoanRequests?.map(r=>r.RequestID)}];
        return {invoke:()=>service[operation](),observeAfterPostcheckFailure:state,
          observe:result=>[
            {obligationId:'P01',passed:true,expected:'defined selection',observed:'defined selection'},
            ...state(),
            {obligationId:'Q02',passed:sameMembers(result,selected),expected:selected.map(r=>r.RequestID),
              observed:Array.isArray(result)?result.map(r=>r?.RequestID):result},
          ]};
      });
  },
};
}
export const loanValidatedRequests=loanStatusListRegistration('listTenLoanRequest');
