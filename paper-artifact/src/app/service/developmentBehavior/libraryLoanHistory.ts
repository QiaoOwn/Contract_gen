import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios, type FiniteScenario} from './finiteScenarioReport';
import type {DevelopmentObligation, DevelopmentRegistration} from './types';
import {librarySearchSources} from './librarySearchSpecification';

export const LIBRARY_LOAN_HISTORY_OPERATIONS = ['listBorrowHistory', 'listHodingBook'] as const;
export type LibraryLoanHistoryOperation = typeof LIBRARY_LOAN_HISTORY_OPERATIONS[number];
export const libraryLoanHistorySpecifications = Object.fromEntries(LIBRARY_LOAN_HISTORY_OPERATIONS.map(operation => {
  const holding = operation === 'listHodingBook';
  const obligations: DevelopmentObligation[] = [
    {id: 'P01', clause: 'precondition', requirement: 'The referenced User exists.',
      documentLine: holding ? 3214 : 3147, modelLines: holding ? [894, 894] : [867, 867],
      modelFeatures: ['User.UserID', '$parameter.uid']},
    {id: 'Q01', clause: 'postcondition', requirement: holding
      ? 'Return exactly the Loan identities linked to the selected User whose IsReturned value is false.'
      : 'Return exactly all Loan identities linked to the selected User, including returned records.',
      documentLine: holding ? 3221 : 3154, modelLines: holding ? [902, 902] : [875, 875],
      modelFeatures: ['User.LoanedBook', ...(holding ? ['Loan.IsReturned'] : []), '$result']},
  ];
  return [operation, {id: `LibraryManagementSystem_listBookHistory_${operation}`,
    schemaVersion: `development-library-loan-history-${operation}-v1`, holding, obligations}];
})) as Record<LibraryLoanHistoryOperation, {id: string; schemaVersion: string; holding: boolean; obligations: DevelopmentObligation[]}>;

type Fact = FiniteScenario & {returned: boolean[]; fees: number[]; wanted: number[]; uid: string;
  missingUser?: boolean; registerLoans?: boolean; equalAttributes?: boolean};
export function libraryLoanHistoryScenarios(operation: LibraryLoanHistoryOperation): Fact[] {
  const holding = libraryLoanHistorySpecifications[operation].holding;
  const fact = (name: string, returned: boolean[], wanted: number[], extra: Partial<Fact> = {}): Fact => ({
    id: `dev-${operation}-${name}`, obligationIds: ['P01', 'Q01'], uid: 'dev-history-owner', returned,
    fees: returned.map(() => 0), wanted, ...extra,
  });
  return [
    fact('empty-history', [], []),
    fact('nonfirst-user-mixed-history', [true, false, true, false], holding ? [1, 3] : [0, 1, 2, 3]),
    fact('only-returned', [true, true], holding ? [] : [0, 1]),
    fact('all-unreturned', [false, false, false], [0, 1, 2]),
    fact('equal-attributes-distinct-identities', [false, false], [0, 1], {equalAttributes: true}),
    fact('association-only-loans', [true, false, false], holding ? [1, 2] : [0, 1, 2], {registerLoans: false}),
    fact('no-overdue-fee-filter', [false, false, false], [0, 1, 2], {fees: [-7, 0, 5]}),
    fact('empty-user-id', [true, false], holding ? [1] : [0, 1], {uid: ''}),
    fact('missing-user', [], [], {missingUser: true, rejectObligation: 'P01', obligationIds: ['P01']}),
  ];
}
type Value = Record<string, unknown>;
export type LibraryLoanHistoryModule = Record<string, unknown> & {getRepository: (ctor: new () => object) => object[]};
export function runLibraryLoanHistoryDevelopment(m: LibraryLoanHistoryModule, requirement: string, operation: LibraryLoanHistoryOperation) {
  const expected = formatStructuredRequirement(getBenchmarkRequirement('LibraryManagementSystem', 'listBookHistory', operation));
  if (requirement.replaceAll('\r\n', '\n').trim() !== expected.replaceAll('\r\n', '\n').trim())
    throw new Error('Library loan-history requirement differs from the frozen input');
  const spec = libraryLoanHistorySpecifications[operation], scenarios = libraryLoanHistoryScenarios(operation);
  return runFiniteScenarios(spec, scenarios, base => {
    const fact = scenarios.find(item => item.id === base.id)!;
    const User = m.User as new () => Value, Loan = m.Loan as new () => Value;
    const Service = m.ListBookHistory_AutoGenerated as new () => Value;
    const users = m.getRepository(User), repository = m.getRepository(Loan);
    users.splice(0); repository.splice(0);
    const loans = fact.returned.map((returned, index) => Object.assign(new Loan(), {
      IsReturned: returned, OverDueFee: fact.fees[index], LoanDate: fact.equalAttributes ? '2025-06-01' : `dev-date-${index}`,
    }));
    const foreign = Object.assign(new Loan(), {IsReturned: false, OverDueFee: 41});
    users.push(Object.assign(new User(), {UserID: 'dev-other-owner', LoanedBook: [foreign]}));
    if (!fact.missingUser) users.push(Object.assign(new User(), {UserID: fact.uid, LoanedBook: loans}));
    if (fact.registerLoans !== false) repository.push(foreign, ...loans);
    const wanted = fact.wanted.map(index => loans[index]), service = new Service();
    return {
      invoke: () => (service[operation] as (id: string) => unknown).call(service, fact.uid),
      observePrecondition: () => ({satisfied: !fact.missingUser, expected: spec.obligations[0].requirement,
        observed: {uid: fact.uid, userExists: !fact.missingUser}}),
      observe: result => [
        {obligationId: 'P01', passed: true, expected: 'existing User accepted', observed: 'completed'},
        {obligationId: 'Q01', passed: Array.isArray(result) && result.length === wanted.length &&
          new Set(result).size === wanted.length && wanted.every(loan => result.includes(loan)),
          expected: {loanIdentityIndices: fact.wanted}, observed: {isArray: Array.isArray(result),
            loanIdentityIndices: Array.isArray(result) ? result.map(item => loans.indexOf(item)) : []}},
      ],
    };
  });
}
export function libraryLoanHistoryRegistration(operation: LibraryLoanHistoryOperation): DevelopmentRegistration {
  const spec = libraryLoanHistorySpecifications[operation];
  return {...spec, project: 'LibraryManagementSystem', useCase: 'listBookHistory', operation,
    reviewStatus: 'pending-user-review', fixedClock: '2026-01-15T12:00:00+08:00',
    sources: librarySearchSources.map(source => ({...source,
      note: 'ListBookHistory active source clauses for Loan results; no added collection-existence, fee, nonempty-ID or repository-membership guard. Document and model share a source lineage.'})),
    requirementSourceId: 'requirement-document', modelSourceId: 'upstream-model',
    scenarios: libraryLoanHistoryScenarios(operation).map(({id, obligationIds}) => ({id, obligationIds})),
    moduleExports: {User: 'function', Loan: 'function', ListBookHistory_AutoGenerated: 'function', getRepository: 'function'},
    run: (candidate, options) => runLibraryLoanHistoryDevelopment(candidate as LibraryLoanHistoryModule, options.requirementText, operation)};
}
