import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios} from './finiteScenarioReport';
import {narrativeDevelopmentProfile} from './narrativeDevelopmentProfiles';
import {submittedRequestsSources} from './submittedLoanRequestsSpecification';
import type {DevelopmentRegistration, DevelopmentObligation} from './types';

type Request = {RequestID: number; Status: unknown};
type Module = {
  LoanRequest: new () => Request;
  LoanRequestStatus: Record<string, unknown>;
  getRepository: (ctor: new () => Request) => Request[];
  EnterValidatedCreditReferencesModule_AutoGenerated: new () => {
    CurrentLoanRequests: Request[];
    CurrentLoanRequest: Request;
    chooseLoanRequest: (id: number) => unknown;
    chooseOneForReview: (id: number) => unknown;
    markRequestValid: () => unknown;
    approveLoanRequest: () => unknown;
  };
  EvaluateLoanRequestModule_AutoGenerated: Module['EnterValidatedCreditReferencesModule_AutoGenerated'];
};
const project = 'LoanProcessingSystem';
const obligation = (id: string, clause: DevelopmentObligation['clause'], requirement: string,
  documentLine: number, modelLine: number, modelFeatures: string[]): DevelopmentObligation => ({
  id, clause, requirement, documentLine, modelLines: [modelLine, modelLine], modelFeatures,
});

export function loanRequestSelectionRegistration(operation: 'chooseLoanRequest' | 'markRequestValid' | 'chooseOneForReview' | 'approveLoanRequest'): DevelopmentRegistration {
  const selecting = operation === 'chooseLoanRequest' || operation === 'chooseOneForReview';
  const approved = operation === 'approveLoanRequest';
  const useCase = operation === 'chooseOneForReview' || approved ? 'evaluateLoanRequest' : 'enterValidatedCreditReferences';
  const serviceName = useCase === 'evaluateLoanRequest'
    ? 'EvaluateLoanRequestModule_AutoGenerated' : 'EnterValidatedCreditReferencesModule_AutoGenerated';
  const id = [project, useCase, operation].join('_');
  const obligations = selecting ? [
    obligation('P01', 'precondition', 'The identifier selects a request from CurrentLoanRequests.',
      operation === 'chooseOneForReview' ? 1809 : 1616, operation === 'chooseOneForReview' ? 499 : 423,
      ['self.CurrentLoanRequests', 'LoanRequest.RequestID', '$parameter.requestid']),
    obligation('Q01', 'postcondition', 'The selected request becomes CurrentLoanRequest.',
      operation === 'chooseOneForReview' ? 1816 : 1623, operation === 'chooseOneForReview' ? 507 : 431,
      ['self.CurrentLoanRequest']),
    obligation('Q02', 'postcondition', 'Return the selected request.',
      operation === 'chooseOneForReview' ? 1817 : 1624, operation === 'chooseOneForReview' ? 508 : 432, ['$result']),
  ] : [
    obligation('P01', 'precondition', 'CurrentLoanRequest exists.', approved ? 2105 : 1673,
      approved ? 608 : 443, ['self.CurrentLoanRequest']),
    obligation('Q01', 'postcondition', 'The current request status becomes '+
      (approved ? 'APPROVED.' : 'REFERENCESVALIDATED.'), approved ? 2112 : 1680,
      approved ? 616 : 451, ['self.CurrentLoanRequest', 'LoanRequest.Status',
        approved ? 'LoanRequestStatus.APPROVED' : 'LoanRequestStatus.REFERENCESVALIDATED']),
    obligation('Q02', 'postcondition', 'Return true.', approved ? 2113 : 1681,
      approved ? 617 : 452, ['$result']),
  ];
  const cases = selecting
    ? [['second', false], ['first', false], ['outside-list', true], ['absent-id', true]] as const
    : [['second', false], ['first', false], ['no-current', true]] as const;
  const scenarios = cases.map(([key, reject]) => ({
    key, id: 'dev-loan-' + operation + '-' + key, rejectObligation: reject ? 'P01' : undefined,
    obligationIds: reject ? ['P01'] : obligations.map(item => item.id),
  }));
  return {
    id, schemaVersion: 'development-loan-selection-v1', project, useCase, operation,
    reviewStatus: 'pending-user-review', fixedClock: '2026-01-15T12:00:00+08:00',
    sources: submittedRequestsSources.map(source => ({
      ...source,
      note: source.id === 'requirement-document'
        ? (approved ? 'OP14, lines 2099-2113: current-request guard, APPROVED status and true result.'
          : operation === 'chooseOneForReview' ? 'OP9, lines 1796-1817: current-list selection, state assignment and result.'
          : selecting ? 'OP6, lines 1602-1624: current-list selection, state assignment and result.'
          : 'OP7, lines 1667-1681: current-request guard, status transition and result.')
        : (approved ? 'Active contract lines 601-617: current-request guard, APPROVED status and true result.'
          : operation === 'chooseOneForReview' ? 'Active contract lines 484-508: scoped selection, guard, state assignment and result.'
          : selecting ? 'Active contract lines 408-432: scoped selection, guard, state assignment and result.'
          : 'Active contract lines 436-452: current-request guard, status transition and result.'),
    })), requirementSourceId: 'requirement-document',
    modelSourceId: 'upstream-model', obligations, scenarios,
    moduleExports: {LoanRequest: 'function', LoanRequestStatus: 'object',
      [serviceName]: 'function', getRepository: 'function'},
    run(candidate, {requirementText}) {
      const expected = formatStructuredRequirement(getBenchmarkRequirement(project, useCase, operation));
      if (!narrativeDevelopmentProfile(id,requirementText)&&requirementText.replaceAll('\r\n', '\n').trim() !== expected.replaceAll('\r\n', '\n').trim())
        throw new Error('Loan request selection input differs from frozen requirement');
      const m = candidate as Module;
      return runFiniteScenarios({id, schemaVersion: 'development-loan-selection-v1', obligations},
        scenarios, scenario => {
          const key = scenarios.find(item => item.id === scenario.id)!.key;
          const repo = m.getRepository(m.LoanRequest);
          repo.splice(0);
          const first = Object.assign(new m.LoanRequest(), {RequestID: 11, Status: m.LoanRequestStatus.SUBMITTED});
          const second = Object.assign(new m.LoanRequest(), {RequestID: 22, Status: m.LoanRequestStatus.SUBMITTED});
          repo.push(first, second);
          const service = new m[serviceName]();
          service.CurrentLoanRequests = key === 'outside-list' ? [first] : [first, second];
          if (key !== 'no-current') service.CurrentLoanRequest = selecting
            ? (key === 'first' ? second : first) : (key === 'first' ? first : second);
          const target = key === 'first' ? first : second;
          const chosenId = key === 'first' ? 11 : key === 'absent-id' ? 99 : 22;
          const admitted = selecting ? service.CurrentLoanRequests.some(r => r.RequestID === chosenId)
            : key !== 'no-current';
          const state = () => [{obligationId: 'Q01',
            passed: selecting ? service.CurrentLoanRequest === target
              : target.Status === m.LoanRequestStatus[approved ? 'APPROVED' : 'REFERENCESVALIDATED'],
            expected: selecting ? target.RequestID : m.LoanRequestStatus[approved ? 'APPROVED' : 'REFERENCESVALIDATED'],
            observed: selecting ? service.CurrentLoanRequest?.RequestID : target.Status}];
          return {
            invoke: () => selecting
              ? (operation === 'chooseOneForReview' ? service.chooseOneForReview(chosenId) : service.chooseLoanRequest(chosenId))
              : approved ? service.approveLoanRequest() : service.markRequestValid(),
            observePrecondition: () => ({satisfied: admitted, expected: obligations[0].requirement, observed: admitted}),
            observeAfterPostcheckFailure: state,
            observe: result => [
              {obligationId: 'P01', passed: admitted, expected: true, observed: admitted},
              ...state(),
              {obligationId: 'Q02', passed: selecting ? result === target : result === true,
                expected: selecting ? target.RequestID : true,
                observed: selecting ? (result as Request | undefined)?.RequestID : result},
            ],
          };
        });
    },
  };
}
