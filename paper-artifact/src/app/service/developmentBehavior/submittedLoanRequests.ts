import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import type {DevelopmentBehaviorReport, DevelopmentDiagnostic} from './types';
import {
  SUBMITTED_REQUESTS_ID,
  SUBMITTED_REQUESTS_VERSION,
  submittedRequestsObligations,
  submittedRequestsScenarios,
} from './submittedLoanRequestsSpecification';

type LoanRequest = {RequestID?: number; Status?: unknown};
export type SubmittedRequestsModule = {
  LoanRequest: new () => LoanRequest;
  LoanRequestStatus: Record<string, unknown>;
  EnterValidatedCreditReferencesModule_AutoGenerated: new () => {
    CurrentLoanRequests?: LoanRequest[];
    listSubmitedLoanRequest: () => unknown;
  };
  getRepository: (type: new () => object) => object[];
};
export function runSubmittedRequestsDevelopment(
  m: SubmittedRequestsModule,
  options: {requirementText: string}
): DevelopmentBehaviorReport {
  const expectedRequirement = formatStructuredRequirement(
    getBenchmarkRequirement(
      'LoanProcessingSystem',
      'enterValidatedCreditReferences',
      'listSubmitedLoanRequest'
    )
  );
  const normalize = (text: string) => text.replaceAll('\r\n', '\n').trim();
  if (normalize(options.requirementText) !== normalize(expectedRequirement))
    throw new Error('Submitted requests development requirement differs from the registered input');
  const literals = [
    'SUBMITTED',
    'APPROVED',
    'REFERENCESVALIDATED',
    'READYFORREVIEW',
    'INCOMPLETEINFORMATION',
  ];
  const values = literals.map((name) => m.LoanRequestStatus[name]);
  if (values.some((value) => value === undefined) || new Set(values).size !== values.length)
    throw new Error('Candidate module is missing distinct declared LoanRequestStatus literals');
  const checks: DevelopmentBehaviorReport['checks'] = [];
  const diagnostics: DevelopmentDiagnostic[] = [];
  const executionObservations: DevelopmentBehaviorReport['executionObservations'] = [];
  for (const scenario of submittedRequestsScenarios) {
    const repository = m.getRepository(m.LoanRequest);
    repository.splice(0);
    const requests = scenario.statuses.map((status, index) =>
      Object.assign(new m.LoanRequest(), {
        RequestID: 981000 + index,
        Status: m.LoanRequestStatus[status],
      })
    );
    repository.push(...requests);
    // Capture expected identities before candidate code can change the repository or statuses.
    const expected = requests.filter((request) => request.Status === m.LoanRequestStatus.SUBMITTED);
    const service = new m.EnterValidatedCreditReferencesModule_AutoGenerated();
    if (scenario.staleCurrent)
      service.CurrentLoanRequests = [
        Object.assign(new m.LoanRequest(), {
          RequestID: 982999,
          Status: m.LoanRequestStatus.APPROVED,
        }),
      ];
    const check = (id: string, passed: boolean | null, wanted: unknown, observed: unknown) => {
      checks.push({scenarioId: scenario.id, obligationId: id, passed, expected: wanted, observed});
      if (passed === false)
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: 'OBLIGATION_MISMATCH',
          obligationIds: [id],
          expected: wanted,
          observed,
          message: submittedRequestsObligations.find((item) => item.id === id)!.requirement,
        });
    };
    let result: unknown;
    let failure: {name: string; message: string} | undefined;
    try {
      result = service.listSubmitedLoanRequest();
    } catch (error) {
      failure =
        error instanceof Error
          ? {name: error.name, message: error.message}
          : {name: 'Error', message: String(error)};
    }
    if (failure) {
      const definitionFailure =
        failure.name === 'PreconditionError' &&
        failure.message.includes('definition binding could not be evaluated');
      const rejected = failure.name === 'PreconditionError' && !definitionFailure;
      executionObservations.push({
        scenarioId: scenario.id,
        classification: definitionFailure
          ? 'definition-failure-unresolved'
          : rejected
            ? 'explicit-rejection'
            : 'runtime-error',
        conventionStatus: definitionFailure ? 'inconclusive' : rejected ? 'matched' : 'mismatched',
      });
      if (scenario.rejectObligation && rejected)
        check('P01', true, 'request rejected', failure.name);
      else
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: definitionFailure
            ? 'REJECTION_UNRESOLVED'
            : rejected
              ? 'UNEXPECTED_REJECTION'
              : 'EXECUTION_ERROR',
          obligationIds: rejected && !scenario.rejectObligation ? ['P01'] : [],
          expected: scenario.rejectObligation
            ? 'request rejected'
            : 'successful submitted request selection',
          observed: failure,
          message:
            'Explicit precondition rejection is distinguished from unresolved definition, runtime and postcondition-check exceptions.',
        });
      continue;
    }
    if (scenario.rejectObligation) {
      executionObservations.push({
        scenarioId: scenario.id,
        classification: 'return-without-rejection-signal',
        conventionStatus: 'mismatched',
      });
      if (Array.isArray(result))
        check('P01', false, 'reject when no submitted request exists', result);
      else {
        check('P01', null, 'a recognized rejection', result ?? null);
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: 'REJECTION_UNRESOLVED',
          obligationIds: [],
          expected: 'a recognized rejection',
          observed: result ?? null,
          message: 'A non-collection return alone does not establish a recognized rejection.',
        });
      }
      continue;
    }
    executionObservations.push({
      scenarioId: scenario.id,
      classification: 'completed',
      conventionStatus: 'matched',
    });
    check('P01', true, 'accept when submitted requests exist', 'accepted');
    const membership = (value: unknown) =>
      Array.isArray(value) &&
      new Set(value).size === new Set(expected).size &&
      expected.every((request) => value.includes(request));
    const describe = (value: unknown) =>
      Array.isArray(value)
        ? {
            requestIds: value.map((request) => request?.RequestID ?? null),
            expectedObjectPositions: value.map((request) => expected.indexOf(request)),
          }
        : value === undefined
          ? null
          : {representation: typeof value};
    check(
      'Q01',
      membership(service.CurrentLoanRequests),
      describe(expected),
      describe(service.CurrentLoanRequests)
    );
    check('Q02', membership(result), describe(expected), describe(result));
  }
  const businessStatus = diagnostics.some((item) =>
    ['OBLIGATION_MISMATCH', 'UNEXPECTED_REJECTION'].includes(item.code)
  )
    ? 'mismatched'
    : diagnostics.length
      ? 'inconclusive'
      : 'matched';
  const executionConventionStatus = executionObservations.some(
    (item) => item.conventionStatus === 'mismatched'
  )
    ? 'mismatched'
    : executionObservations.some((item) => item.conventionStatus === 'inconclusive')
      ? 'inconclusive'
      : 'matched';
  const observed = new Set(
    checks.filter((item) => item.passed !== null).map((item) => item.obligationId)
  );
  return {
    schemaVersion: SUBMITTED_REQUESTS_VERSION,
    operationId: SUBMITTED_REQUESTS_ID,
    role: 'development_only',
    reviewStatus: 'pending-user-review',
    hiddenEvaluationUsed: false,
    dynamicRepairEnabled: false,
    coverageScope: 'finite-development-scenarios',
    businessAssessmentBasis: 'cited-upstream-operation-specification-and-aligned-current-input',
    assessmentPolicy: {
      selection:
        'Expected membership is captured before execution using the source SUBMITTED filter.',
      equality:
        'Compare extensional sets of object identities; do not require array order, shared container identity, or duplicate-free array storage.',
      representation:
        'Arrays are the current lowered Set representation, not an additional source business rule.',
      frame:
        'No unstated status preservation, repository preservation, rollback or other service-state frame is asserted.',
      rejection:
        'PreconditionError is the registered convention. Definition failure and arbitrary runtime exceptions do not authorize business repair.',
    },
    businessStatus,
    executionConventionStatus,
    executionObservations,
    scenarioCount: submittedRequestsScenarios.length,
    scenarioResults: submittedRequestsScenarios.map((scenario) => ({
      id: scenario.id,
      passed: !diagnostics.some((item) => item.scenarioId === scenario.id),
      checkCount: checks.filter((item) => item.scenarioId === scenario.id).length,
    })),
    checks,
    diagnostics,
    passed:
      businessStatus === 'matched' && executionConventionStatus === 'matched' && checks.length > 0,
    unobservedObligationIds: submittedRequestsObligations
      .filter((item) => !observed.has(item.id))
      .map((item) => item.id),
  };
}
