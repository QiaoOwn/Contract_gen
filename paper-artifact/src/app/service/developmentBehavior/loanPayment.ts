import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import type {DevelopmentBehaviorReport, DevelopmentDiagnostic} from './types';
import {narrativeDevelopmentProfile} from './narrativeDevelopmentProfiles';
import {
  LOAN_PAYMENT_ID,
  LOAN_PAYMENT_VERSION,
  loanPaymentObligations,
  loanPaymentScenarios,
} from './loanPaymentSpecification';

type Loan = {
  LoanID?: number;
  Status?: unknown;
  RemainAmountToPay?: number;
  RepaymentAmount?: number;
};
export type LoanPaymentModule = {
  Loan: new () => Loan;
  LoanStatus: Record<string, unknown>;
  LoanProcessingSystemSystem_AutoGenerated: new () => {loanPayment: (loanid: number) => unknown};
  getRepository: (type: new () => object) => object[];
};
export function runLoanPaymentDevelopment(
  m: LoanPaymentModule,
  options: {requirementText: string}
): DevelopmentBehaviorReport {
  const expectedRequirement = formatStructuredRequirement(
    getBenchmarkRequirement('LoanProcessingSystem', 'loanPayment', 'loanPayment')
  );
  const normalize = (text: string) => text.replaceAll('\r\n', '\n').trim();
  const narrativeProfile=narrativeDevelopmentProfile(LOAN_PAYMENT_ID,options.requirementText);
  if (!narrativeProfile && normalize(options.requirementText) !== normalize(expectedRequirement))
    throw new Error(
      'loanPayment development requirement differs from the current registered input; review alignment before repairing business conditions.'
    );
  if (
    m.LoanStatus.LSOPEN === undefined ||
    m.LoanStatus.CLOSED === undefined ||
    m.LoanStatus.LSOPEN === m.LoanStatus.CLOSED
  )
    throw new Error('Candidate module is missing distinct declared LoanStatus literals');
  const diagnostics: DevelopmentDiagnostic[] = [];
  const checks: DevelopmentBehaviorReport['checks'] = [];
  const executionObservations: DevelopmentBehaviorReport['executionObservations'] = [];
  for (const scenario of loanPaymentScenarios) {
    const repository = m.getRepository(m.Loan);
    repository.splice(0);
    const target = Object.assign(new m.Loan(), {
      LoanID: scenario.loanId,
      Status: m.LoanStatus[scenario.status],
      RemainAmountToPay: scenario.remaining,
      RepaymentAmount: scenario.repayment,
    });
    if (scenario.neighbors)
      repository.push(
        Object.assign(new m.Loan(), {
          LoanID: 978999,
          Status: m.LoanStatus.LSOPEN,
          RemainAmountToPay: 230.5,
          RepaymentAmount: 50,
        })
      );
    if (scenario.exists) repository.push(target);
    const beforeRemaining = target.RemainAmountToPay;
    const service = new m.LoanProcessingSystemSystem_AutoGenerated();
    const check = (id: string, passed: boolean | null, expected: unknown, observed: unknown) => {
      checks.push({scenarioId: scenario.id, obligationId: id, passed, expected, observed});
      if (passed === false)
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: 'OBLIGATION_MISMATCH',
          obligationIds: [id],
          expected,
          observed,
          message: loanPaymentObligations.find((item) => item.id === id)!.requirement,
        });
    };
    let result: unknown;
    let failure: {name: string; message: string} | undefined;
    try {
      result = service.loanPayment(scenario.loanId);
    } catch (error) {
      failure =
        error instanceof Error
          ? {name: error.name, message: error.message}
          : {name: 'Error', message: String(error)};
    }
    if (failure) {
      const definitionFailure =
        failure.name === 'PreconditionError' &&
        failure.message.includes('definition binding could not be evaluated');
      const rejected = failure.name === 'PreconditionError' && !definitionFailure;
      executionObservations.push({
        scenarioId: scenario.id,
        classification: definitionFailure
          ? 'definition-failure-unresolved'
          : rejected
            ? 'explicit-rejection'
            : 'runtime-error',
        conventionStatus: definitionFailure ? 'inconclusive' : rejected ? 'matched' : 'mismatched',
      });
      if (scenario.rejectObligation && rejected)
        check(scenario.rejectObligation, true, 'request rejected', failure.name);
      else
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: definitionFailure
            ? 'REJECTION_UNRESOLVED'
            : rejected
              ? 'UNEXPECTED_REJECTION'
              : 'EXECUTION_ERROR',
          obligationIds: rejected && !scenario.rejectObligation ? ['P01', 'P02'] : [],
          expected: scenario.rejectObligation
            ? 'request rejected'
            : 'successful scheduled repayment',
          observed: failure,
          message: definitionFailure
            ? 'A definition binding failed; its cause is unresolved.'
            : 'Execution did not reach the expected outcome. A runtime or postcondition-check exception alone does not prove a source-obligation mismatch.',
        });
      continue;
    }
    if (scenario.rejectObligation) {
      executionObservations.push({
        scenarioId: scenario.id,
        classification: 'return-without-rejection-signal',
        conventionStatus: 'mismatched',
      });
      if (result === true)
        check(
          scenario.rejectObligation,
          false,
          'no successful repayment for an ineligible request',
          true
        );
      else {
        check(scenario.rejectObligation, null, 'a recognized rejection', result ?? null);
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: 'REJECTION_UNRESOLVED',
          obligationIds: [],
          expected: 'a recognized rejection',
          observed: result ?? null,
          message:
            'A non-success return alone does not establish the intended rejection convention.',
        });
      }
      continue;
    }
    executionObservations.push({
      scenarioId: scenario.id,
      classification: 'completed',
      conventionStatus: 'matched',
    });
    check('P01', true, 'accept this existing loan', 'accepted');
    check('P02', true, 'accept this open loan', 'accepted');
    const afterRepayment = target.RepaymentAmount;
    const observed = target.RemainAmountToPay;
    const expected = beforeRemaining - (afterRepayment ?? NaN);
    const tolerance =
      16 *
      Number.EPSILON *
      Math.max(1, Math.abs(beforeRemaining), Math.abs(afterRepayment ?? NaN), Math.abs(expected));
    const matched =
      typeof observed === 'number' &&
      Number.isFinite(observed) &&
      Number.isFinite(expected) &&
      Math.abs(observed - expected) <= tolerance;
    check(
      'Q01',
      matched,
      {
        remainingBefore: beforeRemaining,
        repaymentAfter: afterRepayment ?? null,
        remainingAfter: Number.isFinite(expected) ? expected : null,
      },
      observed ?? null
    );
    check('Q02', result === true, true, result ?? null);
  }
  const businessStatus = diagnostics.some((item) =>
    ['OBLIGATION_MISMATCH', 'UNEXPECTED_REJECTION'].includes(item.code)
  )
    ? 'mismatched'
    : diagnostics.length
      ? 'inconclusive'
      : 'matched';
  const executionConventionStatus = executionObservations.some(
    (item) => item.conventionStatus === 'mismatched'
  )
    ? 'mismatched'
    : executionObservations.some((item) => item.conventionStatus === 'inconclusive')
      ? 'inconclusive'
      : 'matched';
  const observed = new Set(
    checks.filter((item) => item.passed !== null).map((item) => item.obligationId)
  );
  return {
    ...(narrativeProfile?{inputProfile:narrativeProfile}:{}),
    schemaVersion: LOAN_PAYMENT_VERSION,
    operationId: LOAN_PAYMENT_ID,
    role: 'development_only',
    reviewStatus: 'pending-user-review',
    hiddenEvaluationUsed: false,
    dynamicRepairEnabled: false,
    coverageScope: 'finite-development-scenarios',
    businessAssessmentBasis: 'cited-upstream-operation-specification-and-aligned-current-input',
    assessmentPolicy: {
      arithmetic:
        'Capture RemainAmountToPay before this invocation; subtract the post-state RepaymentAmount exactly as the source marks only the former with @pre.',
      numericComparison:
        'A magnitude-scaled binary floating-point tolerance handles the current number representation; it is not a business threshold or exact Real proof.',
      frame:
        'No preservation constraint for RepaymentAmount, Loan.Status, associations, repositories or rollback is inferred.',
      bounds: 'No positive-payment, nonnegative-remaining or clamp-to-zero requirement is added.',
      rejection:
        'PreconditionError is the current execution convention. Arbitrary runtime and PostconditionError observations remain unresolved for business repair.',
    },
    businessStatus,
    executionConventionStatus,
    executionObservations,
    scenarioCount: loanPaymentScenarios.length,
    scenarioResults: loanPaymentScenarios.map((scenario) => ({
      id: scenario.id,
      passed: !diagnostics.some((item) => item.scenarioId === scenario.id),
      checkCount: checks.filter((item) => item.scenarioId === scenario.id).length,
    })),
    checks,
    diagnostics,
    passed:
      businessStatus === 'matched' && executionConventionStatus === 'matched' && checks.length > 0,
    unobservedObligationIds: loanPaymentObligations
      .filter((item) => !observed.has(item.id))
      .map((item) => item.id),
  };
}
