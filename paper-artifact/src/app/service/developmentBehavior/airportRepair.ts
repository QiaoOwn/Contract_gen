import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import fs from 'node:fs';
import {narrativeDevelopmentProfile} from './narrativeDevelopmentProfiles';
import {runFiniteScenarios, type FiniteObservation} from './finiteScenarioReport';
import {airportRepairScenarios, airportRepairSpecifications, type AirportRepairOperation} from './airportRepairSpecification';

type Staff = {Id?: number; Role?: number};
type History = {Reject?: boolean; Suggestion?: string};
type Device = {Id?: number; Name?: string; Location?: string; Contacts?: Staff};
type Repair = {Id?: number; Process?: number; Score?: number; Close?: boolean; Description?: string; RaiseStaff?: Staff; History?: History[]};
type Service = Partial<Record<AirportRepairOperation, (...args: unknown[]) => unknown>>;
export type AirportRepairModule = {
  Staff: new () => Staff; Device: new () => Device; Repair: new () => Repair;
  ApprovalHistory: new () => History;
  AirportSystem_AutoGenerated?: new () => Service; RepairService_AutoGenerated?: new () => Service;
  getRepository: (ctor: new () => object) => object[];
};
export function runAirportRepairDevelopment(m: AirportRepairModule, options: {requirementText: string}, operation: AirportRepairOperation) {
  const spec = airportRepairSpecifications[operation];
  const expected = operation === 'finishRepair'
    ? fs.readFileSync('data/benchmark/rm2pt_authoritative_114_v4/operations.jsonl', 'utf8')
      .split(/\r?\n/).filter(Boolean).map(line => JSON.parse(line))
      .find(row => row.id === spec.id)?.description
    : formatStructuredRequirement(getBenchmarkRequirement('Airport', spec.useCase, operation));
  const normalized = (text: string) => text.replaceAll('\r\n', '\n').trim();
  if (!narrativeDevelopmentProfile(spec.id,options.requirementText)&&normalized(options.requirementText) !== normalized(expected))
    throw new Error('Airport development requirement differs from the current input');
  return runFiniteScenarios(spec, airportRepairScenarios[operation], base => {
    const scenario = airportRepairScenarios[operation].find(item => item.id === base.id)!;
    for (const ctor of [m.Staff, m.Device, m.Repair, m.ApprovalHistory]) m.getRepository(ctor).splice(0);
    const sid = 735103, rid = 735207, did = scenario.value ?? 735309;
    const staff = Object.assign(new m.Staff(), {Id: sid, Role: scenario.role ?? (operation === 'finishRepair' ? 3 : 0)});
    const otherStaff = Object.assign(new m.Staff(), {Id: sid + 12, Role: 1});
    const device = Object.assign(new m.Device(), {Id: did, Name: 'Development device', Location: 'West gate', Contacts: staff});
    const repair = Object.assign(new m.Repair(), {Id: rid, Process: scenario.stage ?? 7,
      Score: 91, Close: operation === 'feedback', Description: 'Before feedback', RaiseStaff: staff, History: [] as History[]});
    const otherRepair = Object.assign(new m.Repair(), {Id: rid + 17, Process: 0, History: [] as History[]});
    if (scenario.id !== 'missing-contact' && scenario.id !== 'missing-staff')
      m.getRepository(m.Staff).push(...(scenario.targetLast ? [otherStaff, staff] : [staff, otherStaff]));
    else m.getRepository(m.Staff).push(otherStaff);
    if (scenario.id !== 'missing-repair')
      m.getRepository(m.Repair).push(...(scenario.targetLast ? [otherRepair, repair] : [repair, otherRepair]));
    else m.getRepository(m.Repair).push(otherRepair);
    if (operation !== 'createDevice' || scenario.id === 'duplicate-device') m.getRepository(m.Device).push(device);
    const existingDevice = Object.assign(new m.Device(), {Id: 735991, Name: 'Other device', Location: 'North gate', Contacts: otherStaff});
    m.getRepository(m.Device).push(existingDevice);
    if (scenario.id === 'wrong-contact') device.Contacts = otherStaff;
    if (scenario.id === 'wrong-worker-role') staff.Role = 2;
    if (scenario.id === 'different-raiser') repair.RaiseStaff = otherStaff;
    if (scenario.id === 'wrong-ground-role') staff.Role = 1;
    if (scenario.id === 'not-finished') repair.Process = 3;
    const beforeDevices = [...m.getRepository(m.Device)];
    const beforeHistories = [...m.getRepository(m.ApprovalHistory)];
    const text = `Development note ${scenario.id}`;
    const args = operation === 'createDevice' ? [did, text, 'South maintenance room', sid]
      : operation === 'approve' ? [sid, rid, scenario.decision ?? true, text]
        : operation === 'finishRepair' ? [rid, sid, did, text] : [rid, sid, scenario.value ?? 3, text];
    const ServiceClass = operation === 'createDevice' ? m.AirportSystem_AutoGenerated : m.RepairService_AutoGenerated;
    if (!ServiceClass) throw new Error('Missing Airport candidate service');
    const service = new ServiceClass();
    const method = service[operation];
    if (typeof method !== 'function') throw new Error(`Missing Airport candidate operation: ${operation}`);
    return {invoke: () => method.apply(service, args),
      ...(operation === 'createDevice' ? {observeAfterPostcheckFailure: (): FiniteObservation[] => {
        const d = (m.getRepository(m.Device) as Device[]).find(item => item != null && !beforeDevices.includes(item) && item.Id === did);
        return [{obligationId: 'Q02', passed: Boolean(d) && d!.Contacts === staff,
          expected: 'new Device stored with the selected Staff contact',
          observed: {newDeviceStored: Boolean(d), contactMatches: Boolean(d) && d!.Contacts === staff}}];
      }} : {}),
      observe: result => {
      const observations: FiniteObservation[] = scenario.obligationIds.filter(id => id.startsWith('P')).map(id =>
        ({obligationId: id, passed: true, expected: 'accept source-valid scenario', observed: 'accepted'}));
      const add = (id: string, passed: boolean, expectation: string) => {
        if (scenario.obligationIds.includes(id)) observations.push({obligationId: id, passed,
          expected: expectation, observed: passed ? 'matched' : 'mismatched'});
      };
      if (operation === 'createDevice') {
        const created = (m.getRepository(m.Device) as Device[]).filter(item => !beforeDevices.includes(item));
        const d = created.find(item => item.Id === did);
        add('Q01', created.length === 1 && Boolean(d) && d!.Name === text && d!.Location === args[2], 'one new Device with supplied scalar fields');
        add('Q02', Boolean(d) && d!.Contacts === staff, 'new Device stored with exact selected Staff contact');
        add('Q03', result === true, 'true');
      } else if (operation === 'approve') {
        const created = (m.getRepository(m.ApprovalHistory) as History[]).filter(item => !beforeHistories.includes(item));
        const history = created[0];
        add('Q01', created.length === 1 && history.Reject === args[2] && history.Suggestion === text && repair.History!.includes(history),
          'new stored decision/suggestion record included in Repair.History');
        add('Q02', repair.Process === (scenario.stage ?? 0) + 1, 'one source-prescribed approval-stage transition');
        add('Q03', repair.Process === 5, 'rejected stage 5');
        add('Q04', Boolean(history) && result === history, 'exact newly created ApprovalHistory');
      } else if (operation === 'finishRepair') {
        add('Q01', repair.Process === 7, 'finished stage 7');
        add('Q02', result === true, 'true');
      } else {
        add('Q01', repair.Score === args[2], 'supplied score');
        add('Q02', repair.Close === true, 'closed at/above threshold 3');
        add('Q03', repair.Close === false && repair.Description === text && repair.Process === 0, 'open with supplied description and stage 0');
        add('Q04', result === true, 'true');
      }
      return observations;
    }};
  });
}
