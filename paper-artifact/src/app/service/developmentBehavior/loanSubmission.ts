import {formatStructuredRequirement,getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios} from './finiteScenarioReport';
import {submittedRequestsSources} from './submittedLoanRequestsSpecification';
import type {DevelopmentRegistration,DevelopmentObligation} from './types';
import {narrativeDevelopmentProfile} from './narrativeDevelopmentProfiles';
type Request=Record<string,unknown>;
type Module={LoanRequest:new()=>Request;CreditHistory:new()=>object;CheckingAccount:new()=>object;
  LoanRequestStatus:Record<string,unknown>;getRepository:(ctor:new()=>Request)=>Request[];
  SubmitLoanRequestModule_AutoGenerated:new()=>{CurrentLoanRequest?:Request;
    enterLoanInformation:(...args:unknown[])=>unknown;calculateScore:()=>unknown}};
const fields=['RequestID','Name','LoanAmount','LoanPurpose','Income','PhoneNumber','PostalAddress',
  'ZipCode','Email','WorkReferences','CreditReferences','CheckingAccountNumber','SecurityNumber'] as const;
const values=[173,'Alice',5100.75,'Equipment',8400.25,15400001,'Main Street',50311,
  'alice@example.org','Employer One','Bank Two',20731,87019] as const;
export function loanSubmissionRegistration(operation:'enterLoanInformation'|'calculateScore'):DevelopmentRegistration{
  const create=operation==='enterLoanInformation',id='LoanProcessingSystem_submitLoanRequest_'+operation;
  const o=(key:string,clause:DevelopmentObligation['clause'],requirement:string,
    doc:number,model:number,features:string[]):DevelopmentObligation=>({id:key,clause,requirement,
    documentLine:doc,modelLines:[model,model],modelFeatures:features});
  const obligations=create?[
    o('P01','precondition','The request ID is unused.',1254,251,['LoanRequest.RequestID','$parameter.requestid']),
    ...fields.map((field,i)=>o('Q'+String(i+1).padStart(2,'0'),'postcondition',
      'The new request stores the supplied '+field+'.',1279+i,277+i,
      ['LoanRequest.'+field,'$parameter.'+field.toLowerCase()])),
    o('Q14','postcondition','Create and store one new LoanRequest.',1292,290,['LoanRequest']),
    o('Q15','postcondition','Set CurrentLoanRequest to the new request.',1293,291,['self.CurrentLoanRequest']),
    o('Q16','postcondition','Return true.',1294,292,['$result']),
  ]:[
    o('P01','precondition','CurrentLoanRequest exists.',1475,361,['self.CurrentLoanRequest']),
    o('P02','precondition','The current request has a checking-account history.',1476,362,
      ['LoanRequest.RequestedCAHistory']),
    o('P03','precondition','The current request has a credit history.',1477,363,
      ['LoanRequest.RequestedCreditHistory']),
    o('Q01','postcondition','Set the current request credit score to 100.',1486,373,
      ['LoanRequest.CreditScore']),
    o('Q02','postcondition','Set the current request status to SUBMITTED.',1487,374,
      ['LoanRequest.Status','LoanRequestStatus.SUBMITTED']),
    o('Q03','postcondition','Return the current request credit score.',1488,375,
      ['LoanRequest.CreditScore','$result']),
  ];
  const cases=create?['new','second-id','duplicate']:['approved','submitted','no-current','no-checking','no-credit'];
  const scenarios=cases.map(key=>({id:'dev-loan-submit-'+operation+'-'+key,
    rejectObligation:key==='duplicate'||key==='no-current'?'P01'
      :key==='no-checking'?'P02':key==='no-credit'?'P03':undefined,
    obligationIds:key==='duplicate'||key==='no-current'?['P01']
      :key==='no-checking'?['P02']:key==='no-credit'?['P03']:obligations.map(item=>item.id)}));
  return {id,project:'LoanProcessingSystem',useCase:'submitLoanRequest',operation,
    schemaVersion:'development-loan-submission-v1',reviewStatus:'pending-user-review',
    fixedClock:'2026-01-15T12:00:00+08:00',
    sources:submittedRequestsSources.map(source=>({...source,note:source.id==='requirement-document'
      ? 'Active '+operation+' requirement contract at lines '+(create?'1241-1294':'1464-1488')+'.'
      : 'Active '+operation+' model contract at lines '+(create?'236-293':'352-376')+'.'})),
    requirementSourceId:'requirement-document',modelSourceId:'upstream-model',obligations,scenarios,
    moduleExports:{LoanRequest:'function',CreditHistory:'function',CheckingAccount:'function',
      LoanRequestStatus:'object',getRepository:'function',SubmitLoanRequestModule_AutoGenerated:'function'},
    run(candidate,{requirementText}){
      const expected=formatStructuredRequirement(getBenchmarkRequirement('LoanProcessingSystem','submitLoanRequest',operation));
      if(!narrativeDevelopmentProfile(id,requirementText)&&requirementText.replaceAll('\r\n','\n').trim()!==expected.replaceAll('\r\n','\n').trim())
        throw new Error('Loan submission input differs from frozen requirement');
      const m=candidate as Module;
      return runFiniteScenarios({id,schemaVersion:'development-loan-submission-v1',obligations},scenarios,scenario=>{
        const key=cases.find(item=>scenario.id.endsWith('-'+item))!;
        const repo=m.getRepository(m.LoanRequest);repo.splice(0);
        const service=new m.SubmitLoanRequestModule_AutoGenerated();
        if(create){
          const args:unknown[]=[...values]; if(key==='second-id')args[0]=174;
          const existing=Object.assign(new m.LoanRequest(),{RequestID:key==='duplicate'?args[0]:999});
          repo.push(existing);
          const admission=key!=='duplicate';
          const created=()=>repo.find(item=>item!==existing&&item.RequestID===args[0]);
          const state=()=>[
            ...fields.map((field,i)=>({obligationId:'Q'+String(i+1).padStart(2,'0'),
              passed:created()?.[field]===args[i],expected:args[i],observed:created()?.[field]})),
            {obligationId:'Q14',passed:repo.length===2&&Boolean(created()),expected:'one new request',
              observed:{count:repo.length,created:Boolean(created())}},
            {obligationId:'Q15',passed:service.CurrentLoanRequest===created(),expected:args[0],
              observed:service.CurrentLoanRequest?.RequestID},
          ];
          return {invoke:()=>service.enterLoanInformation(...args),
            observePrecondition:()=>({satisfied:admission,expected:obligations[0].requirement,observed:admission}),
            observeAfterPostcheckFailure:state,
            observe:result=>[
              {obligationId:'P01',passed:admission,expected:true,observed:admission},
              ...state(),{obligationId:'Q16',passed:result===true,expected:true,observed:result},
            ]};
        }
        const request=Object.assign(new m.LoanRequest(),{RequestID:173,CreditScore:9,
          Status:m.LoanRequestStatus.APPROVED});
        repo.push(request);
        if(key!=='no-current')service.CurrentLoanRequest=request;
        if(key!=='no-checking')request.RequestedCAHistory=new m.CheckingAccount();
        if(key!=='no-credit')request.RequestedCreditHistory=new m.CreditHistory();
        const admission=[key!=='no-current',key!=='no-checking',key!=='no-credit'];
        const state=()=>[
          {obligationId:'Q01',passed:request.CreditScore===100,expected:100,observed:request.CreditScore},
          {obligationId:'Q02',passed:request.Status===m.LoanRequestStatus.SUBMITTED,
            expected:m.LoanRequestStatus.SUBMITTED,observed:request.Status},
        ];
        return {invoke:()=>service.calculateScore(),
          observePrecondition:code=>({satisfied:admission[Number(code.slice(1))-1],
            expected:obligations[Number(code.slice(1))-1].requirement,
            observed:admission[Number(code.slice(1))-1]}),
          observeAfterPostcheckFailure:state,
          observe:result=>[
            ...obligations.slice(0,3).map((item,i)=>({obligationId:item.id,
              passed:admission[i],expected:true,observed:admission[i]})),
            ...state(),{obligationId:'Q03',passed:result===request.CreditScore&&result===100,
              expected:100,observed:result},
          ]};
      });
    },
  };
}
