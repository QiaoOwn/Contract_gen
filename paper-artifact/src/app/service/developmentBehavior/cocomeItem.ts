import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import type {DevelopmentBehaviorReport, DevelopmentDiagnostic} from './types';
import {
  cocomeItemScenarios,
  cocomeItemSpecifications,
  type CocomeItemOperation,
} from './cocomeItemSpecification';

type Item = {
  Barcode?: number;
  Name?: string;
  Price?: number;
  StockNumber?: number;
  OrderPrice?: number;
};
export type CocomeItemModule = {
  Item: new () => Item;
  ManageItemCRUDService_AutoGenerated: new () => Partial<
    Record<CocomeItemOperation, (barcode: number) => unknown>
  >;
  getRepository: (type: new () => object) => object[];
};

export function runCocomeItemDevelopment(
  m: CocomeItemModule,
  options: {requirementText: string},
  operation: CocomeItemOperation
): DevelopmentBehaviorReport {
  const specification = cocomeItemSpecifications[operation];
  const expectedRequirement = formatStructuredRequirement(
    getBenchmarkRequirement('CoCoME', 'manageItem', operation)
  );
  const normalize = (text: string) => text.replaceAll('\r\n', '\n').trim();
  if (normalize(options.requirementText) !== normalize(expectedRequirement))
    throw new Error(
      `CoCoME ${operation} development requirement differs from the current registered input; review alignment before repairing business conditions.`
    );
  const diagnostics: DevelopmentDiagnostic[] = [];
  const checks: DevelopmentBehaviorReport['checks'] = [];
  const executionObservations: DevelopmentBehaviorReport['executionObservations'] = [];
  for (const scenario of cocomeItemScenarios) {
    const repository = m.getRepository(m.Item) as Item[];
    repository.splice(0);
    const makeItem = (barcode: number) =>
      Object.assign(new m.Item(), {
        Barcode: barcode,
        Name: `Development item ${barcode}`,
        Price: 17.25,
        StockNumber: 6,
        OrderPrice: 12.5,
      });
    const target = makeItem(scenario.barcode);
    const neighbors = scenario.otherBarcodes.map(makeItem);
    repository.push(
      ...(scenario.targetFirst
        ? [...(scenario.hasTarget ? [target] : []), ...neighbors]
        : [...neighbors, ...(scenario.hasTarget ? [target] : [])])
    );
    const service = new m.ManageItemCRUDService_AutoGenerated();
    if (typeof service[operation] !== 'function')
      throw new Error(`Candidate is missing ${operation}`);
    const check = (id: string, passed: boolean | null, expected: unknown, observed: unknown) => {
      checks.push({scenarioId: scenario.id, obligationId: id, passed, expected, observed});
      if (passed === false)
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: 'OBLIGATION_MISMATCH',
          obligationIds: [id],
          expected,
          observed,
          message: specification.obligations.find((item) => item.id === id)!.requirement,
        });
    };
    let result: unknown;
    let failure: {name: string; message: string} | undefined;
    try {
      result = service[operation]!(scenario.barcode);
    } catch (error) {
      failure =
        error instanceof Error
          ? {name: error.name, message: error.message}
          : {name: 'Error', message: String(error)};
    }
    if (failure) {
      const definitionFailure =
        failure.name === 'PreconditionError' &&
        failure.message.includes('definition binding could not be evaluated');
      const rejected = failure.name === 'PreconditionError' && !definitionFailure;
      executionObservations.push({
        scenarioId: scenario.id,
        classification: definitionFailure
          ? 'definition-failure-unresolved'
          : rejected
            ? 'explicit-rejection'
            : 'runtime-error',
        conventionStatus: definitionFailure ? 'inconclusive' : rejected ? 'matched' : 'mismatched',
      });
      if (!scenario.hasTarget && rejected) check('P01', true, 'request rejected', failure.name);
      else
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: definitionFailure
            ? 'REJECTION_UNRESOLVED'
            : rejected
              ? 'UNEXPECTED_REJECTION'
              : 'EXECUTION_ERROR',
          obligationIds: rejected && scenario.hasTarget ? ['P01'] : [],
          expected: scenario.hasTarget ? `successful ${operation}` : 'request rejected',
          observed: failure,
          message: definitionFailure
            ? 'A definition binding failed; its cause is unresolved.'
            : 'Execution did not reach the expected outcome; arbitrary exceptions do not establish a business root cause.',
        });
      continue;
    }
    if (!scenario.hasTarget) {
      executionObservations.push({
        scenarioId: scenario.id,
        classification: 'return-without-rejection-signal',
        conventionStatus: 'mismatched',
      });
      if (result === true || result instanceof m.Item)
        check(
          'P01',
          false,
          'no successful operation for a missing Item',
          operation === 'queryItem' ? 'returned an Item' : result
        );
      else {
        check('P01', null, 'a recognized rejection', result ?? null);
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: 'REJECTION_UNRESOLVED',
          obligationIds: [],
          expected: 'a recognized rejection',
          observed: result ?? null,
          message:
            'A non-success return alone does not establish the intended rejection convention.',
        });
      }
      continue;
    }
    executionObservations.push({
      scenarioId: scenario.id,
      classification: 'completed',
      conventionStatus: 'matched',
    });
    check('P01', true, 'accept the existing referenced Item', 'accepted');
    if (operation === 'queryItem') {
      check(
        'Q01',
        result === target,
        'the exact referenced Item object',
        result === target ? 'matched object identity' : result == null ? null : 'different result'
      );
    } else {
      const after = m.getRepository(m.Item) as Item[];
      check(
        'Q01',
        !after.includes(target),
        'the referenced Item is absent from the repository',
        after.includes(target) ? 'target remains present' : 'target removed'
      );
      check('Q02', result === true, true, result ?? null);
    }
  }
  const businessStatus = diagnostics.some((item) =>
    ['OBLIGATION_MISMATCH', 'UNEXPECTED_REJECTION'].includes(item.code)
  )
    ? 'mismatched'
    : diagnostics.length
      ? 'inconclusive'
      : 'matched';
  const executionConventionStatus = executionObservations.some(
    (item) => item.conventionStatus === 'mismatched'
  )
    ? 'mismatched'
    : executionObservations.some((item) => item.conventionStatus === 'inconclusive')
      ? 'inconclusive'
      : 'matched';
  const observed = new Set(
    checks.filter((item) => item.passed !== null).map((item) => item.obligationId)
  );
  return {
    schemaVersion: specification.schemaVersion,
    operationId: specification.id,
    role: 'development_only',
    reviewStatus: 'pending-user-review',
    hiddenEvaluationUsed: false,
    dynamicRepairEnabled: false,
    coverageScope: 'finite-development-scenarios',
    businessAssessmentBasis: 'cited-upstream-operation-specification-and-aligned-current-input',
    assessmentPolicy: {
      queryIdentity:
        'queryItem must return the referenced pre-existing object, not merely an equal copy.',
      deletion:
        'deleteItem removes the referenced object from the repository; no cascade deletion is inferred.',
      frame:
        'No general frame, inverse association maintenance or rollback assertion is added without an explicit source obligation.',
      rejection:
        'PreconditionError is the current execution convention, not a source-prescribed exception class.',
      scope:
        'Only the explicitly registered queryItem/deleteItem operations; createItem/modifyItem are not registered by this adapter.',
    },
    businessStatus,
    executionConventionStatus,
    executionObservations,
    scenarioCount: cocomeItemScenarios.length,
    scenarioResults: cocomeItemScenarios.map((scenario) => ({
      id: scenario.id,
      passed: !diagnostics.some((item) => item.scenarioId === scenario.id),
      checkCount: checks.filter((item) => item.scenarioId === scenario.id).length,
    })),
    checks,
    diagnostics,
    passed:
      businessStatus === 'matched' && executionConventionStatus === 'matched' && checks.length > 0,
    unobservedObligationIds: specification.obligations
      .filter((item) => !observed.has(item.id))
      .map((item) => item.id),
  };
}
