import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios, type FiniteObservation} from './finiteScenarioReport';
import {atmSessionSpecifications, atmSessionScenarios, atmSessionSources, type AtmSessionKey} from './atmSessionSpecification';
import type {DevelopmentRegistration} from './types';

type Value = Record<string, unknown>;
export type AtmSessionModule = Record<string, unknown> & {getRepository: (ctor: new () => object) => object[]};
export function runAtmSessionDevelopment(m: AtmSessionModule, requirement: string, key: AtmSessionKey) {
  const spec = atmSessionSpecifications[key];
  const expected = formatStructuredRequirement(getBenchmarkRequirement('AutomatedTellerMachine', spec.useCase, spec.operation));
  const normalize = (value: string) => value.replaceAll('\r\n', '\n').trim();
  if (normalize(requirement) !== normalize(expected)) throw new Error('ATM session requirement differs from the registered input');
  const scenarios = atmSessionScenarios(key);
  return runFiniteScenarios({...spec, obligations: [...spec.obligations], schemaVersion: `development-atm-session-${key}-v1`}, scenarios, base => {
    const fact = scenarios.find(item => item.id === base.id)!;
    const Card = m.BankCard as new () => Value;
    const Service = m.AutomatedTellerMachineSystem_AutoGenerated as new () => Value;
    m.getRepository(Card).splice(0);
    const password = fact.password ?? 976031, entered = fact.entered ?? password;
    const balance = fact.balance ?? 427.75, quantity = fact.quantity ?? 125;
    const card = Object.assign(new Card(), {CardID: 976005, Password: password, Balance: balance});
    const service = Object.assign(new Service(), {CardIDValidated: fact.cardValidated ?? true,
      PasswordValidated: fact.passwordValidated ?? true, InputCard: fact.missingCard ? undefined : card,
      IsDeposit: false, DepositedNumber: 911});
    const observation = (obligationId: string, observed: unknown, wanted: unknown): FiniteObservation =>
      ({obligationId, passed: Object.is(observed, wanted), expected: wanted, observed});
    const state = (): FiniteObservation[] => spec.operation === 'inputPassword'
      ? [observation(password === entered ? 'Q01' : 'Q03', service.PasswordValidated, password === entered)]
      : spec.operation === 'depositFunds' ? [observation('Q01', card.Balance, balance + quantity),
        observation('Q02', service.IsDeposit, true), observation('Q03', service.DepositedNumber, quantity)] : [];
    return {
      invoke: () => (service[spec.operation] as (...values: number[]) => unknown).apply(service,
        spec.operation === 'inputPassword' ? [entered] : spec.operation === 'depositFunds' ? [quantity] : []),
      observePrecondition: id => ({satisfied: id === 'P04' ? quantity >= 100 :
        id === (spec.operation === 'inputPassword' ? 'P02' : 'P03') ? !fact.missingCard :
          id === 'P01' && spec.operation !== 'inputPassword' ? fact.passwordValidated !== false : fact.cardValidated !== false,
        expected: spec.obligations.find(item => item.id === id)!.requirement,
        observed: {cardValidated: fact.cardValidated ?? true, passwordValidated: fact.passwordValidated ?? true,
          hasCard: !fact.missingCard, quantity}}),
      observeAfterPostcheckFailure: state,
      observe: result => [
        ...base.obligationIds.filter(id => id.startsWith('P')).map(id => observation(id, true, true)),
        ...(spec.operation === 'checkBalance' ? [observation('Q01', result, balance)]
          : spec.operation === 'inputPassword' ? [...state(), observation(password === entered ? 'Q02' : 'Q04', result, password === entered)]
            : [...state(), observation('Q04', result, true)]),
      ],
    };
  });
}
export function atmSessionRegistration(key: AtmSessionKey): DevelopmentRegistration {
  const spec = atmSessionSpecifications[key];
  return {id: spec.id, project: 'AutomatedTellerMachine', useCase: spec.useCase, operation: spec.operation,
    schemaVersion: `development-atm-session-${key}-v1`, reviewStatus: 'pending-user-review',
    fixedClock: '2026-01-15T12:00:00+08:00', sources: atmSessionSources,
    requirementSourceId: 'requirement-document', modelSourceId: 'upstream-model', obligations: spec.obligations,
    scenarios: atmSessionScenarios(key).map(({id, obligationIds}) => ({id, obligationIds})),
    moduleExports: {BankCard: 'function', AutomatedTellerMachineSystem_AutoGenerated: 'function', getRepository: 'function'},
    run: (candidate, options) => runAtmSessionDevelopment(candidate as AtmSessionModule, options.requirementText, key)};
}
