import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios} from './finiteScenarioReport';
import {librarySearchSpecifications, librarySearchScenarios, librarySearchSources, type LibrarySearchOperation} from './librarySearchSpecification';
import type {DevelopmentRegistration} from './types';

type Value = Record<string, unknown>;
export type LibrarySearchModule = Record<string, unknown> & {getRepository: (ctor: new () => object) => object[]};
export function runLibrarySearchDevelopment(m: LibrarySearchModule, requirement: string, operation: LibrarySearchOperation) {
  const spec = librarySearchSpecifications[operation];
  const expected = formatStructuredRequirement(getBenchmarkRequirement('LibraryManagementSystem', 'searchBook', operation));
  const normalize = (text: string) => text.replaceAll('\r\n', '\n').trim();
  if (normalize(requirement) !== normalize(expected)) throw new Error('Library search requirement differs from registered input');
  const scenarios = librarySearchScenarios(operation);
  return runFiniteScenarios({id: spec.id, obligations: spec.obligations, schemaVersion: `development-library-search-${operation}-v1`}, scenarios, base => {
    const fact = scenarios.find(item => item.id === base.id)!;
    const Book = m.Book as new () => Value, Service = m.SearchBook_AutoGenerated as new () => Value;
    const repository = m.getRepository(Book); repository.splice(0);
    if (spec.entity) m.getRepository(m[spec.entity] as new () => Value).splice(0);
    const books = fact.values.map((values, index) => {
      const book: Value = Object.assign(new Book(), {CallNo: fact.equalAttributes ? 'same' : `dev-${index}`,
        Title: 'Unrelated title', Author: 'Unrelated author', ISBn: 'Unrelated ISBN', Copys: [], Subject: []});
      if (spec.association && spec.entity) {
        const Related = m[spec.entity] as new () => Value;
        book[spec.association] = values.map(value => Object.assign(new Related(), {[spec.field]: value}));
      } else book[spec.field] = values[0] ?? 'Unrelated';
      return book;
    });
    repository.push(...books);
    const wanted = fact.wanted.map(index => books[index]), service = new Service();
    return {invoke: () => (service[operation] as (value: unknown) => unknown).call(service, fact.value),
      observePrecondition: () => ({satisfied: spec.nonempty ? fact.value !== '' : typeof fact.value === 'string',
        expected: spec.obligations[0].requirement, observed: {value: fact.value, type: typeof fact.value}}),
      observe: result => [
        {obligationId: 'P01', passed: true, expected: 'admissible invocation', observed: 'completed'},
        {obligationId: 'Q01', passed: Array.isArray(result) && result.length === wanted.length &&
          new Set(result).size === wanted.length && wanted.every(book => result.includes(book)),
          expected: {bookIdentityIndices: fact.wanted}, observed: {isArray: Array.isArray(result),
            length: Array.isArray(result) ? result.length : null,
            bookIdentityIndices: Array.isArray(result) ? result.map(book => books.indexOf(book as typeof books[number])) : []}},
      ]};
  });
}
export function librarySearchRegistration(operation: LibrarySearchOperation): DevelopmentRegistration {
  const spec = librarySearchSpecifications[operation];
  return {id: spec.id, project: 'LibraryManagementSystem', useCase: 'searchBook', operation,
    schemaVersion: `development-library-search-${operation}-v1`, reviewStatus: 'pending-user-review', fixedClock: '2026-01-15T12:00:00+08:00',
    sources: librarySearchSources, requirementSourceId: 'requirement-document', modelSourceId: 'upstream-model', obligations: spec.obligations,
    scenarios: librarySearchScenarios(operation).map(({id, obligationIds}) => ({id, obligationIds})),
    moduleExports: {Book: 'function', SearchBook_AutoGenerated: 'function', getRepository: 'function',
      ...(spec.entity ? {[spec.entity]: 'function' as const} : {})},
    run: (candidate, options) => runLibrarySearchDevelopment(candidate as LibrarySearchModule, options.requirementText, operation)};
}
