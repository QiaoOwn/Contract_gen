import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios, type FiniteObservation} from './finiteScenarioReport';
import {cocomeStockSpecifications, cocomeStockScenarios, cocomeStockSources, type CocomeStockOperation} from './cocomeStockSpecification';
import type {DevelopmentRegistration} from './types';

type Value = Record<string, unknown>;
export type CocomeStockModule = Record<string, unknown> & {getRepository: (ctor: new () => object) => object[]};
export function runCocomeStockDevelopment(m: CocomeStockModule, requirement: string, operation: CocomeStockOperation) {
  const spec = cocomeStockSpecifications[operation];
  const expected = formatStructuredRequirement(getBenchmarkRequirement('CoCoME', spec.useCase, operation));
  const normalize = (text: string) => text.replaceAll('\r\n', '\n').trim();
  if (normalize(requirement) !== normalize(expected)) throw new Error('CoCoME stock/supplier requirement differs from registered input');
  const scenarios = cocomeStockScenarios(operation);
  return runFiniteScenarios({id: spec.id, obligations: [...spec.obligations], schemaVersion: `development-cocome-stock-${operation}-v1`}, scenarios, base => {
    const fact = scenarios.find(item => item.id === base.id)!;
    const Entity = m[spec.entity] as new () => Value;
    const Service = m[`${spec.service}_AutoGenerated`] as new () => Value;
    const repository = m.getRepository(Entity); repository.splice(0);
    const service = new Service(), identifier = fact.identifier ?? 815;
    const item = (id: string, observed: unknown, wanted: unknown): FiniteObservation =>
      ({obligationId: id, passed: Object.is(observed, wanted), expected: wanted, observed});
    if (operation !== 'changePrice' && operation !== 'chooseSupplier') {
      const objects = (fact.values ?? []).map((value, index) => Object.assign(new Entity(),
        spec.entity === 'Supplier' ? {Id: value, Name: `Supplier ${fact.equalAttributes ? 0 : index}`}
          : {Barcode: fact.equalAttributes ? 771 : 771 + index, StockNumber: value, Price: 32.25, OrderPrice: 7.25}));
      repository.push(...objects);
      const wanted = operation === 'listAllOutOfStoreProducts' ? objects.filter(object => object.StockNumber === 0) : [...objects];
      return {invoke: () => (service[operation] as () => unknown).call(service), observe: result => [
        item('P01', true, true), {obligationId: 'Q01', passed: Array.isArray(result) && result.length === wanted.length &&
          new Set(result).size === wanted.length && wanted.every(object => result.includes(object)),
        expected: {identityMembers: wanted.length}, observed: {isArray: Array.isArray(result), length: Array.isArray(result) ? result.length : null,
          matchedIdentityMembers: Array.isArray(result) ? wanted.filter(object => result.includes(object)).length : 0}},
      ]};
    }
    const target = Object.assign(new Entity(), operation === 'changePrice'
      ? {Barcode: identifier, Price: 181.25, OrderPrice: 11.5, StockNumber: 13} : {Id: identifier, Name: 'Selected Supplier'});
    const other = Object.assign(new Entity(), operation === 'changePrice'
      ? {Barcode: identifier + 9, Price: 41.5, OrderPrice: 11.5, StockNumber: 0} : {Id: identifier + 9, Name: 'Other Supplier'});
    if (!fact.emptyRepository) repository.push(other, ...(!fact.missingTarget ? [target] : []));
    const Order = m.OrderProduct as new () => Value;
    const order = operation === 'chooseSupplier' ? Object.assign(new Order(), {Id: 884, Supplier: fact.previousSupplier ? other : undefined}) : undefined;
    if (operation === 'chooseSupplier') {m.getRepository(Order).splice(0); service.CurrentOrderProduct = fact.missingOrder ? undefined : order;}
    const state = () => [item('Q01', operation === 'changePrice' ? target.Price : order!.Supplier,
      operation === 'changePrice' ? fact.price : target)];
    return {invoke: () => (service[operation] as (...args: number[]) => unknown).apply(service,
      operation === 'changePrice' ? [identifier, fact.price!] : [identifier]),
    observePrecondition: id => ({satisfied: id === 'P02' ? !fact.missingOrder : !fact.missingTarget,
      expected: spec.obligations.find(item => item.id === id)!.requirement,
      observed: {hasTarget: !fact.missingTarget, hasCurrentOrder: !fact.missingOrder}}),
    observeAfterPostcheckFailure: state,
    observe: result => [...base.obligationIds.filter(id => id.startsWith('P')).map(id => item(id, true, true)),
      ...state(), item('Q02', result, true)]};
  });
}
export function cocomeStockRegistration(operation: CocomeStockOperation): DevelopmentRegistration {
  const spec = cocomeStockSpecifications[operation];
  return {id: spec.id, project: 'CoCoME', useCase: spec.useCase, operation,
    schemaVersion: `development-cocome-stock-${operation}-v1`, reviewStatus: 'pending-user-review', fixedClock: '2026-01-15T12:00:00+08:00',
    sources: cocomeStockSources, requirementSourceId: 'requirement-document', modelSourceId: 'upstream-model',
    obligations: spec.obligations, scenarios: cocomeStockScenarios(operation).map(({id, obligationIds}) => ({id, obligationIds})),
    moduleExports: {[spec.entity]: 'function', [`${spec.service}_AutoGenerated`]: 'function', getRepository: 'function',
      ...(operation === 'chooseSupplier' ? {OrderProduct: 'function' as const} : {})},
    run: (candidate, options) => runCocomeStockDevelopment(candidate as CocomeStockModule, options.requirementText, operation)};
}
