import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import type {DevelopmentBehaviorReport, DevelopmentDiagnostic} from './types';
import {
  ATM_EJECT_CARD_ID,
  ATM_EJECT_CARD_VERSION,
  atmEjectCardObligations,
  atmEjectCardScenarios,
} from './atmEjectCardSpecification';

type AccountUser = {UserID?: number; Name?: string; Address?: string; OwnedCard?: Card};
type Card = {
  CardID?: number;
  Balance?: number;
  Password?: number;
  CardStatus?: unknown;
  Catalog?: unknown;
  BelongedUser?: AccountUser;
};
type Session = {
  PasswordValidated: boolean;
  CardIDValidated: boolean;
  InputCard: Card | null | undefined;
  IsWithdraw: boolean;
  IsDeposit: boolean;
  WithdrawedNumber: number;
  DepositedNumber: number;
  ejectCard: () => unknown;
};
export type AtmEjectCardModule = {
  BankCard: new () => Card;
  User: new () => AccountUser;
  CardStatus: Record<string, unknown>;
  CardCatalog: Record<string, unknown>;
  AutomatedTellerMachineSystem_AutoGenerated: new () => Session;
  getRepository: (type: new () => object) => object[];
};

export function runAtmEjectCardDevelopment(
  m: AtmEjectCardModule,
  options: {requirementText: string}
): DevelopmentBehaviorReport {
  const expectedRequirement = formatStructuredRequirement(
    getBenchmarkRequirement('AutomatedTellerMachine', 'checkBalance', 'ejectCard')
  );
  const normalize = (text: string) => text.replaceAll('\r\n', '\n').trim();
  if (normalize(options.requirementText) !== normalize(expectedRequirement))
    throw new Error(
      'ATM ejectCard development requirement differs from the current registered input; review alignment before repairing business conditions.'
    );
  const diagnostics: DevelopmentDiagnostic[] = [];
  const checks: DevelopmentBehaviorReport['checks'] = [];
  const executionObservations: DevelopmentBehaviorReport['executionObservations'] = [];
  for (const scenario of atmEjectCardScenarios) {
    const repository = m.getRepository(m.BankCard);
    repository.splice(0);
    const users = m.getRepository(m.User);
    users.splice(0);
    const user = Object.assign(new m.User(), {
      UserID: 951203,
      Name: 'Development account',
      Address: 'Development address',
    });
    const card = Object.assign(new m.BankCard(), {
      CardID: 951207,
      Balance: 746.3,
      Password: 6971,
      CardStatus: m.CardStatus.NORMAL,
      Catalog: m.CardCatalog.CREDIT,
      BelongedUser: user,
    });
    user.OwnedCard = card;
    users.push(user);
    if (scenario.hasCard) repository.push(card);
    const service = Object.assign(new m.AutomatedTellerMachineSystem_AutoGenerated(), {
      PasswordValidated: scenario.passwordValidated,
      CardIDValidated: scenario.cardIdValidated,
      InputCard: scenario.hasCard ? card : undefined,
      IsWithdraw: scenario.isWithdraw,
      IsDeposit: scenario.isDeposit,
      WithdrawedNumber: scenario.withdrawn,
      DepositedNumber: scenario.deposited,
    });
    const check = (id: string, passed: boolean | null, expected: unknown, observed: unknown) => {
      checks.push({scenarioId: scenario.id, obligationId: id, passed, expected, observed});
      if (passed === false)
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: 'OBLIGATION_MISMATCH',
          obligationIds: [id],
          expected,
          observed,
          message: atmEjectCardObligations.find((item) => item.id === id)!.requirement,
        });
    };
    let result: unknown;
    let failure: {name: string; message: string} | undefined;
    try {
      result = service.ejectCard();
    } catch (error) {
      failure =
        error instanceof Error
          ? {name: error.name, message: error.message}
          : {name: 'Error', message: String(error)};
    }
    if (failure) {
      const definitionFailure =
        failure.name === 'PreconditionError' &&
        failure.message.includes('definition binding could not be evaluated');
      const rejected = failure.name === 'PreconditionError' && !definitionFailure;
      executionObservations.push({
        scenarioId: scenario.id,
        classification: definitionFailure
          ? 'definition-failure-unresolved'
          : rejected
            ? 'explicit-rejection'
            : 'runtime-error',
        conventionStatus: definitionFailure ? 'inconclusive' : rejected ? 'matched' : 'mismatched',
      });
      if (scenario.rejectObligation && rejected)
        check(scenario.rejectObligation, true, 'request rejected', failure.name);
      else
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: definitionFailure
            ? 'REJECTION_UNRESOLVED'
            : rejected
              ? 'UNEXPECTED_REJECTION'
              : 'EXECUTION_ERROR',
          obligationIds: rejected && !scenario.rejectObligation ? ['P01', 'P02', 'P03'] : [],
          expected: scenario.rejectObligation ? 'request rejected' : 'successful session reset',
          observed: failure,
          message: definitionFailure
            ? 'A definition binding failed; its cause is unresolved.'
            : 'The observed execution did not reach the expected outcome; an arbitrary exception is not a confirmed business root cause.',
        });
      continue;
    }
    if (scenario.rejectObligation) {
      executionObservations.push({
        scenarioId: scenario.id,
        classification: 'return-without-rejection-signal',
        conventionStatus: 'mismatched',
      });
      if (result === true)
        check(
          scenario.rejectObligation,
          false,
          'no successful reset for this ineligible request',
          true
        );
      else {
        check(scenario.rejectObligation, null, 'a recognized rejection', result ?? null);
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: 'REJECTION_UNRESOLVED',
          obligationIds: [],
          expected: 'a recognized rejection',
          observed: result ?? null,
          message:
            'A non-success return alone does not establish the intended rejection convention.',
        });
      }
      continue;
    }
    executionObservations.push({
      scenarioId: scenario.id,
      classification: 'completed',
      conventionStatus: 'matched',
    });
    for (const id of ['P01', 'P02', 'P03'])
      check(id, true, 'accept this eligible session', 'accepted');
    check(
      'Q01',
      service.InputCard == null,
      'no current card',
      service.InputCard == null ? null : 'card remains present'
    );
    check('Q02', service.PasswordValidated === false, false, service.PasswordValidated);
    check('Q03', service.CardIDValidated === false, false, service.CardIDValidated);
    check('Q04', service.IsWithdraw === false, false, service.IsWithdraw);
    check('Q05', service.IsDeposit === false, false, service.IsDeposit);
    check('Q06', service.WithdrawedNumber === 0, 0, service.WithdrawedNumber);
    check('Q07', service.DepositedNumber === 0, 0, service.DepositedNumber);
    check('Q08', result === true, true, result ?? null);
  }
  const businessStatus = diagnostics.some((item) =>
    ['OBLIGATION_MISMATCH', 'UNEXPECTED_REJECTION'].includes(item.code)
  )
    ? 'mismatched'
    : diagnostics.length
      ? 'inconclusive'
      : 'matched';
  const executionConventionStatus = executionObservations.some(
    (item) => item.conventionStatus === 'mismatched'
  )
    ? 'mismatched'
    : executionObservations.some((item) => item.conventionStatus === 'inconclusive')
      ? 'inconclusive'
      : 'matched';
  const observed = new Set(
    checks.filter((item) => item.passed !== null).map((item) => item.obligationId)
  );
  return {
    schemaVersion: ATM_EJECT_CARD_VERSION,
    operationId: ATM_EJECT_CARD_ID,
    role: 'development_only',
    reviewStatus: 'pending-user-review',
    hiddenEvaluationUsed: false,
    dynamicRepairEnabled: false,
    coverageScope: 'finite-development-scenarios',
    businessAssessmentBasis: 'cited-upstream-operation-specification-and-aligned-current-input',
    assessmentPolicy: {
      scope:
        'Only checkBalance/ejectCard; sibling use-case operations are not implicitly registered.',
      rejection:
        'Business preconditions come from the source; PreconditionError is the current adapter rejection convention, not a source-prescribed exception class.',
      clearedReference:
        'The source requires no current card. The OCLTSVM null literal lowers to undefined; the business observation accepts an absent reference, not a particular JavaScript spelling.',
      unaffectedState:
        'No assertions are added for unrelated account fields, repositories or unspecified rollback behavior.',
    },
    businessStatus,
    executionConventionStatus,
    executionObservations,
    scenarioCount: atmEjectCardScenarios.length,
    scenarioResults: atmEjectCardScenarios.map((scenario) => ({
      id: scenario.id,
      passed: !diagnostics.some((item) => item.scenarioId === scenario.id),
      checkCount: checks.filter((item) => item.scenarioId === scenario.id).length,
    })),
    checks,
    diagnostics,
    passed:
      businessStatus === 'matched' && executionConventionStatus === 'matched' && checks.length > 0,
    unobservedObligationIds: atmEjectCardObligations
      .filter((item) => !observed.has(item.id))
      .map((item) => item.id),
  };
}
