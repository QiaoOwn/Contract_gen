import fs from 'node:fs';
import type {DevelopmentBehaviorReport, DevelopmentDiagnostic} from './types';
import {
  AIRPORT_CREATE_STAFF_ID,
  AIRPORT_CREATE_STAFF_VERSION,
  airportCreateStaffObligations,
  airportCreateStaffScenarios,
} from './airportCreateStaffSpecification';

type Staff = {
  Id?: number;
  Name?: string;
  Password?: string;
  Phone?: string;
  Role?: number;
  Boss?: Staff | null;
};
export type AirportCreateStaffModule = {
  Staff: new () => Staff;
  AirportSystem_AutoGenerated: new () => {
    createStaff: (
      id: number,
      name: string,
      pswd: string,
      phone: string,
      role: number,
      bossid: number
    ) => unknown;
  };
  getRepository: (type: new () => object) => object[];
};

export function runAirportCreateStaffDevelopment(
  m: AirportCreateStaffModule,
  options: {requirementText: string}
): DevelopmentBehaviorReport {
  const expectedRequirement = fs.readFileSync(
    'data/benchmark/rm2pt_authoritative_114_v4/operations.jsonl', 'utf8'
  ).split(/\r?\n/).filter(Boolean).map(line => JSON.parse(line)).find(
    row => row.id === AIRPORT_CREATE_STAFF_ID
  )?.description;
  const normalize = (text: string) => text.replaceAll('\r\n', '\n').trim();
  if (normalize(options.requirementText) !== normalize(expectedRequirement))
    throw new Error(
      'Airport createStaff development requirement differs from the current registered input; review alignment before repairing business conditions.'
    );
  const diagnostics: DevelopmentDiagnostic[] = [];
  const checks: DevelopmentBehaviorReport['checks'] = [];
  const executionObservations: DevelopmentBehaviorReport['executionObservations'] = [];
  for (const scenario of airportCreateStaffScenarios) {
    const repository = m.getRepository(m.Staff) as Staff[];
    repository.splice(0);
    const boss = Object.assign(new m.Staff(), {
      Id: scenario.bossId,
      Name: 'Development supervisor',
      Password: 'dev-boss-password',
      Phone: 'dev-boss-phone',
      Role: 8,
    });
    if (scenario.existingBoss) repository.push(boss);
    if (scenario.duplicate)
      repository.push(Object.assign(new m.Staff(), {Id: scenario.staffId, Name: 'Existing staff'}));
    const before = new Set(repository);
    const service = new m.AirportSystem_AutoGenerated();
    const check = (id: string, passed: boolean | null, expected: unknown, observed: unknown) => {
      checks.push({scenarioId: scenario.id, obligationId: id, passed, expected, observed});
      if (passed === false)
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: 'OBLIGATION_MISMATCH',
          obligationIds: [id],
          expected,
          observed,
          message: airportCreateStaffObligations.find((item) => item.id === id)!.requirement,
        });
    };
    let result: unknown;
    let failure: {name: string; message: string} | undefined;
    try {
      result = service.createStaff(
        scenario.staffId,
        scenario.name,
        scenario.password,
        scenario.phone,
        scenario.role,
        scenario.bossId
      );
    } catch (error) {
      failure =
        error instanceof Error
          ? {name: error.name, message: error.message}
          : {name: 'Error', message: String(error)};
    }
    if (failure) {
      const definitionFailure =
        failure.name === 'PreconditionError' &&
        failure.message.includes('definition binding could not be evaluated');
      const rejected = failure.name === 'PreconditionError' && !definitionFailure;
      executionObservations.push({
        scenarioId: scenario.id,
        classification: definitionFailure
          ? 'definition-failure-unresolved'
          : rejected
            ? 'explicit-rejection'
            : 'runtime-error',
        conventionStatus: definitionFailure ? 'inconclusive' : rejected ? 'matched' : 'mismatched',
      });
      if (scenario.duplicate && rejected) check('P01', true, 'request rejected', failure.name);
      else
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: definitionFailure
            ? 'REJECTION_UNRESOLVED'
            : rejected
              ? 'UNEXPECTED_REJECTION'
              : 'EXECUTION_ERROR',
          obligationIds: rejected && !scenario.duplicate ? ['P01'] : [],
          expected: scenario.duplicate ? 'request rejected' : 'successful staff creation',
          observed: failure,
          message: definitionFailure
            ? 'A definition binding failed; its cause is unresolved.'
            : 'Execution did not reach the expected outcome; an arbitrary exception is not a confirmed business root cause.',
        });
      continue;
    }
    if (scenario.duplicate) {
      executionObservations.push({
        scenarioId: scenario.id,
        classification: 'return-without-rejection-signal',
        conventionStatus: 'mismatched',
      });
      if (result === true)
        check('P01', false, 'no successful registration with an existing identifier', true);
      else {
        check('P01', null, 'a recognized rejection', result ?? null);
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: 'REJECTION_UNRESOLVED',
          obligationIds: [],
          expected: 'a recognized rejection',
          observed: result ?? null,
          message:
            'A non-success return alone does not establish the intended rejection convention.',
        });
      }
      continue;
    }
    executionObservations.push({
      scenarioId: scenario.id,
      classification: 'completed',
      conventionStatus: 'matched',
    });
    const after = m.getRepository(m.Staff) as Staff[];
    const fresh = after.filter((staff) => !before.has(staff));
    const created =
      fresh.find((staff) => staff.Id === scenario.staffId) ??
      (fresh.length === 1 ? fresh[0] : undefined);
    check('P01', true, 'accept this unused staff identifier', 'accepted');
    check(
      'Q01',
      created instanceof m.Staff,
      'a fresh Staff object observable in the repository',
      created ? 'fresh Staff' : 'not observed'
    );
    check(
      'Q02',
      Boolean(created) && created!.Id === scenario.staffId,
      scenario.staffId,
      created?.Id ?? null
    );
    check(
      'Q03',
      Boolean(created) && created!.Name === scenario.name,
      scenario.name,
      created?.Name ?? null
    );
    check(
      'Q04',
      Boolean(created) && created!.Password === scenario.password,
      scenario.password,
      created?.Password ?? null
    );
    check(
      'Q05',
      Boolean(created) && created!.Phone === scenario.phone,
      scenario.phone,
      created?.Phone ?? null
    );
    check(
      'Q06',
      Boolean(created) && created!.Role === scenario.role,
      scenario.role,
      created?.Role ?? null
    );
    if (scenario.existingBoss)
      check(
        'Q07',
        Boolean(created) && created!.Boss === boss,
        'the existing Staff object selected by bossid',
        created?.Boss === boss
          ? 'matched existing object'
          : created?.Boss == null
            ? null
            : 'different object'
      );
    check(
      'Q09',
      Boolean(created) && after.includes(created!),
      'the fresh Staff is registered',
      Boolean(created) && after.includes(created!)
    );
    check('Q10', result === true, true, result ?? null);
  }
  const businessStatus = diagnostics.some((item) =>
    ['OBLIGATION_MISMATCH', 'UNEXPECTED_REJECTION'].includes(item.code)
  )
    ? 'mismatched'
    : diagnostics.length
      ? 'inconclusive'
      : 'matched';
  const executionConventionStatus = executionObservations.some(
    (item) => item.conventionStatus === 'mismatched'
  )
    ? 'mismatched'
    : executionObservations.some((item) => item.conventionStatus === 'inconclusive')
      ? 'inconclusive'
      : 'matched';
  const observed = new Set(
    checks.filter((item) => item.passed !== null).map((item) => item.obligationId)
  );
  return {
    schemaVersion: AIRPORT_CREATE_STAFF_VERSION,
    operationId: AIRPORT_CREATE_STAFF_ID,
    role: 'development_only',
    reviewStatus: 'pending-user-review',
    hiddenEvaluationUsed: false,
    dynamicRepairEnabled: false,
    coverageScope: 'finite-development-scenarios',
    businessAssessmentBasis: 'cited-upstream-operation-specification-and-aligned-current-input',
    assessmentPolicy: {
      absentBoss:
        'The upstream conditional has no else obligation; no absent-Boss value is asserted.',
      creation:
        'Creation and repository membership share a repository observation; an unregistered new object is not separately observable. These checks do not prove a unique fault cause.',
      rejection:
        'PreconditionError is the current execution convention, not a source-prescribed exception class.',
      scope:
        'No role range, password policy, inverse relationship, exact allocation count, unrelated frame or rollback constraint is inferred.',
    },
    businessStatus,
    executionConventionStatus,
    executionObservations,
    scenarioCount: airportCreateStaffScenarios.length,
    scenarioResults: airportCreateStaffScenarios.map((scenario) => ({
      id: scenario.id,
      passed: !diagnostics.some((item) => item.scenarioId === scenario.id),
      checkCount: checks.filter((item) => item.scenarioId === scenario.id).length,
    })),
    checks,
    diagnostics,
    passed:
      businessStatus === 'matched' && executionConventionStatus === 'matched' && checks.length > 0,
    unobservedObligationIds: airportCreateStaffObligations
      .filter((item) => !observed.has(item.id))
      .map((item) => item.id),
  };
}
