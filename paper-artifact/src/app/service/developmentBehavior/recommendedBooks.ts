import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios} from './finiteScenarioReport';
import {recommendationId, recommendationService, recommendationSources, recommendationMappingSource,
  recommendationObligations, recommendationScenarios, RECOMMENDATION_VERSION, type RecommendationView} from './recommendedBooksSpecification';
import type {DevelopmentRegistration} from './types';
import {narrativeDevelopmentProfile} from './narrativeDevelopmentProfiles';

type User = {UserID?: string; RecommendedBook?: object[]};
export type RecommendationModule = Record<string, unknown> & {User: new () => User; RecommendBook: new () => object;
  getRepository: (ctor: new () => object) => object[]};
export function runRecommendedBooksDevelopment(m: RecommendationModule, requirement: string, view: RecommendationView) {
  const expected = formatStructuredRequirement(getBenchmarkRequirement('LibraryManagementSystem', view, 'listRecommendBook'));
  const normalize = (text: string) => text.replaceAll('\r\n', '\n').trim();
  if (!narrativeDevelopmentProfile(recommendationId(view),requirement)&&normalize(requirement) !== normalize(expected)) throw new Error('Recommendation requirement differs from its source-aligned registration');
  return runFiniteScenarios({id: recommendationId(view), schemaVersion: RECOMMENDATION_VERSION,
    obligations: recommendationObligations}, recommendationScenarios, base => {
    const scenario = recommendationScenarios.find(item => item.id === base.id)!;
    const users = m.getRepository(m.User), recommendations = m.getRepository(m.RecommendBook);
    users.splice(0); recommendations.splice(0);
    const uid = scenario.emptyId ? '' : 'development-target-653';
    const wanted = Array.from({length: scenario.count}, () => Object.assign(new m.RecommendBook(), {Title: 'Same attributes'}));
    const unrelated = new m.RecommendBook();
    const target = Object.assign(new m.User(), {UserID: uid,
      RecommendedBook: scenario.missingCollection ? undefined : wanted});
    const neighbor = Object.assign(new m.User(), {UserID: 'development-neighbor', RecommendedBook: [unrelated]});
    users.push(neighbor);
    if (!scenario.missingUser) users.push(target);
    recommendations.push(unrelated, ...wanted);
    const Service = m[`${recommendationService(view)}_AutoGenerated`] as new () => {listRecommendBook: (id: string) => unknown};
    const service = new Service();
    const sourcePreconditions = {P01: users.includes(target), P02: users.includes(target) && target.RecommendedBook != null};
    return {invoke: () => service.listRecommendBook(uid),
      observePrecondition: id => ({satisfied: sourcePreconditions[id as keyof typeof sourcePreconditions],
        expected: id === 'P01' ? 'referenced User exists before invocation' : 'recommendation collection resolves before invocation',
        observed: sourcePreconditions[id as keyof typeof sourcePreconditions]}),
      observe: result => [
      {obligationId: 'P01', passed: true, expected: 'accept existing User', observed: 'accepted'},
      {obligationId: 'P02', passed: true, expected: 'accept resolved collection, including empty', observed: 'accepted'},
      {obligationId: 'Q01', passed: Array.isArray(result) && result.length === wanted.length &&
        new Set(result).size === result.length && wanted.every(item => result.includes(item)),
      expected: 'exact set of selected User recommendation identities, not collection-array identity',
      observed: Array.isArray(result) ? `${result.length} records` : typeof result},
    ]};
  });
}
export function recommendationRegistration(view: RecommendationView): DevelopmentRegistration {
  return {id: recommendationId(view), project: 'LibraryManagementSystem', useCase: view, operation: 'listRecommendBook',
    schemaVersion: RECOMMENDATION_VERSION, reviewStatus: 'pending-user-review', fixedClock: '2026-01-15T12:00:00+08:00',
    sources: view === 'listRecommendBook' ? [...recommendationSources, recommendationMappingSource] : recommendationSources,
    requirementSourceId: 'requirement-document', modelSourceId: 'upstream-model', obligations: recommendationObligations,
    scenarios: recommendationScenarios.map(({id, obligationIds}) => ({id, obligationIds})),
    moduleExports: {User: 'function', RecommendBook: 'function', [`${recommendationService(view)}_AutoGenerated`]: 'function', getRepository: 'function'},
    run: (candidate, options) => runRecommendedBooksDevelopment(candidate as RecommendationModule, options.requirementText, view)};
}
