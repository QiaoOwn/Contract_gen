import {formatStructuredRequirement,getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios} from './finiteScenarioReport';
import {submittedRequestsSources} from './submittedLoanRequestsSpecification';
import type {DevelopmentRegistration,DevelopmentObligation} from './types';
type Term={ItemID:number};
type Module={LoanTerm:new()=>Term;getRepository:(type:new()=>Term)=>Term[];
  EvaluateLoanRequestModule_AutoGenerated:new()=>{listAvaiableLoanTerm:()=>unknown}};
const id='LoanProcessingSystem_evaluateLoanRequest_listAvaiableLoanTerm';
const obligations:DevelopmentObligation[]=[{id:'Q01',clause:'postcondition',
  requirement:'Return the complete LoanTerm instance set, including an empty set.',
  documentLine:1986,modelLines:[567,567],modelFeatures:['LoanTerm','$result']}];
const cases=[0,1,13];
const scenarios=cases.map(n=>({id:'dev-loan-terms-'+n,obligationIds:['Q01']}));
export const loanAvailableTerms:DevelopmentRegistration={
  id,project:'LoanProcessingSystem',useCase:'evaluateLoanRequest',operation:'listAvaiableLoanTerm',
  schemaVersion:'development-loan-terms-v1',reviewStatus:'pending-user-review',
  fixedClock:'2026-01-15T12:00:00+08:00',
  sources:submittedRequestsSources.map(source=>({...source,note:source.id==='requirement-document'
    ? 'OP12, lines 1974-1986: no business precondition; return all LoanTerm instances.'
    : 'Active contract lines 553-568: return LoanTerm.allInstance().'})),
  requirementSourceId:'requirement-document',modelSourceId:'upstream-model',
  obligations,scenarios,moduleExports:{LoanTerm:'function',getRepository:'function',
    EvaluateLoanRequestModule_AutoGenerated:'function'},
  run(candidate,{requirementText}){
    const expected=formatStructuredRequirement(getBenchmarkRequirement('LoanProcessingSystem','evaluateLoanRequest','listAvaiableLoanTerm'));
    if(requirementText.replaceAll('\r\n','\n').trim()!==expected.replaceAll('\r\n','\n').trim())
      throw new Error('Loan term input differs from frozen requirement');
    const m=candidate as Module;
    return runFiniteScenarios({id,schemaVersion:'development-loan-terms-v1',obligations},scenarios,scenario=>{
      const count=Number(scenario.id.split('-').at(-1));
      const repo=m.getRepository(m.LoanTerm);repo.splice(0);
      for(let i=0;i<count;i++)repo.push(Object.assign(new m.LoanTerm(),{ItemID:i+1}));
      const selected=[...repo],service=new m.EvaluateLoanRequestModule_AutoGenerated();
      return {invoke:()=>service.listAvaiableLoanTerm(),observe:result=>[
        {obligationId:'Q01',passed:Array.isArray(result)&&result.length===selected.length&&
          selected.every(term=>result.includes(term)),expected:selected.map(term=>term.ItemID),
        observed:Array.isArray(result)?result.map(term=>term?.ItemID):result},
      ]};
    });
  },
};
