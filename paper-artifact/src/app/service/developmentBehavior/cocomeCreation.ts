import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios, type FiniteObservation} from './finiteScenarioReport';
import {cocomeCreationSpecifications, cocomeCreationScenarios, cocomeCreationSources, type CocomeCreationOperation} from './cocomeCreationSpecification';
import type {DevelopmentRegistration} from './types';

type Value = Record<string, unknown>;
export type CocomeCreationModule = Record<string, unknown> & {getRepository: (ctor: new () => object) => object[]};
export function runCocomeCreationDevelopment(m: CocomeCreationModule, requirement: string, operation: CocomeCreationOperation) {
  const spec = cocomeCreationSpecifications[operation];
  const expected = formatStructuredRequirement(getBenchmarkRequirement('CoCoME', spec.useCase, operation));
  const normalize = (text: string) => text.replaceAll('\r\n', '\n').trim();
  if (normalize(requirement) !== normalize(expected)) throw new Error('CoCoME creation requirement differs from registered input');
  const scenarios = cocomeCreationScenarios(operation);
  return runFiniteScenarios({id: spec.id, schemaVersion: `development-cocome-creation-${operation}-v1`, obligations: [...spec.obligations]}, scenarios, base => {
    const fact = scenarios.find(item => item.id === base.id)!;
    const Entity = m[spec.entity] as new () => Value;
    const Service = m[`${spec.service}_AutoGenerated`] as new () => Value;
    const repository = m.getRepository(Entity); repository.splice(0);
    const service = new Service(), identifier = fact.identifier ?? 827;
    const previous = Object.assign(new Entity(), operation === 'makeNewOrder'
      ? {Id: identifier + 101, OrderStatus: (m.OrderStatus as Value).NEW} : {IsComplete: !fact.incompleteSale, IsReadytoPay: fact.oldReady ?? false});
    const neighbor = Object.assign(new Entity(), {Id: identifier + 301});
    const current = operation === 'makeNewOrder' ? 'CurrentOrderProduct' : 'CurrentSale';
    if (fact.previous || fact.incompleteSale) {service[current] = previous; repository.push(previous);}
    if (fact.neighbors) repository.push(neighbor);
    if (fact.duplicate) repository.push(Object.assign(new Entity(), {Id: identifier}));
    let desk: Value | undefined;
    if (operation === 'makeNewSale') {
      const Desk = m.CashDesk as new () => Value;
      m.getRepository(Desk).splice(0);
      desk = Object.assign(new Desk(), {Id: 733, IsOpened: !fact.closedDesk, ContainedSales: fact.neighbors ? [neighbor] : []});
      service.CurrentCashDesk = fact.missingDesk ? undefined : desk;
    }
    const before = new Set<object>([...repository, previous, neighbor]);
    const started = Date.now();
    let ended = started;
    const created = () => (repository.find(item => item instanceof Entity && !before.has(item)) ??
      (service[current] instanceof Entity && !before.has(service[current] as object) ? service[current] : undefined)) as Value | undefined;
    const check = (id: string, passed: boolean, wanted: unknown, observed: unknown): FiniteObservation =>
      ({obligationId: id, passed, expected: wanted, observed});
    const state = (): FiniteObservation[] => {
      const object = created(), fresh = !!object && object instanceof Entity && !before.has(object);
      if (operation === 'makeNewOrder') {
        const time = object?.Time == null ? NaN : Number((object.Time as {valueOf: () => unknown}).valueOf());
        return [check('Q01', fresh, 'fresh OrderProduct identity', fresh),
          check('Q02', object?.OrderStatus === (m.OrderStatus as Value).NEW, 'NEW', object?.OrderStatus),
          check('Q03', object?.Id === identifier, identifier, object?.Id),
          check('Q04', Number.isFinite(time) && time >= started && time <= ended, {operationTime: [started, ended]}, time),
          check('Q05', !!object && repository.includes(object), 'new order stored', !!object && repository.includes(object)),
          check('Q06', !!object && service[current] === object, 'current order is created order', !!object && service[current] === object)];
      }
      return [check('Q01', fresh, 'fresh Sale identity', fresh),
        check('Q02', !!object && object.BelongedCashDesk === desk, 'selected CashDesk identity', !!object && object.BelongedCashDesk === desk),
        check('Q03', !!object && Array.isArray(desk?.ContainedSales) && desk.ContainedSales.includes(object), 'new sale linked in desk', !!object && Array.isArray(desk?.ContainedSales) && desk.ContainedSales.includes(object)),
        check('Q04', object?.IsComplete === false, false, object?.IsComplete),
        check('Q05', object?.IsReadytoPay === false, false, object?.IsReadytoPay),
        check('Q06', !!object && repository.includes(object), 'new sale stored', !!object && repository.includes(object)),
        check('Q07', !!object && service[current] === object, 'current sale is created sale', !!object && service[current] === object)];
    };
    return {invoke: () => {try {return (service[operation] as (...args: number[]) => unknown).apply(service, operation === 'makeNewOrder' ? [identifier] : []);} finally {ended = Date.now();}},
      observePrecondition: id => ({satisfied: operation === 'makeNewOrder' ? !fact.duplicate : id === 'P01' ? !fact.missingDesk : id === 'P02' ? !fact.closedDesk : !fact.incompleteSale,
        expected: spec.obligations.find(item => item.id === id)!.requirement,
        observed: {duplicate: !!fact.duplicate, hasDesk: !fact.missingDesk, deskOpen: !fact.closedDesk, currentSaleComplete: !fact.incompleteSale}}),
      observeAfterPostcheckFailure: state,
      observe: result => [...base.obligationIds.filter(id => id.startsWith('P')).map(id => check(id, true, true, true)), ...state(),
        check(operation === 'makeNewOrder' ? 'Q07' : 'Q08', result === true, true, result)]};
  });
}
export function cocomeCreationRegistration(operation: CocomeCreationOperation): DevelopmentRegistration {
  const spec = cocomeCreationSpecifications[operation];
  return {id: spec.id, project: 'CoCoME', useCase: spec.useCase, operation,
    schemaVersion: `development-cocome-creation-${operation}-v1`, reviewStatus: 'pending-user-review', fixedClock: '2026-01-15T12:00:00+08:00',
    sources: cocomeCreationSources, requirementSourceId: 'requirement-document', modelSourceId: 'upstream-model',
    obligations: spec.obligations, scenarios: cocomeCreationScenarios(operation).map(({id, obligationIds}) => ({id, obligationIds})),
    moduleExports: {[spec.entity]: 'function', [`${spec.service}_AutoGenerated`]: 'function', getRepository: 'function',
      ...(operation === 'makeNewOrder' ? {OrderStatus: 'object' as const} : {CashDesk: 'function' as const})},
    run: (candidate, options) => runCocomeCreationDevelopment(candidate as CocomeCreationModule, options.requirementText, operation)};
}
