import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import type {DevelopmentBehaviorReport, DevelopmentDiagnostic} from './types';
import {narrativeDevelopmentProfile} from './narrativeDevelopmentProfiles';
import {
  cocomeDeletionSpecifications,
  cocomeDeletionScenarios,
  type CocomeDeletionOperation,
} from './cocomeDeletionsSpecification';

type StoredObject = {Id?: number};
export type CocomeDeletionsModule = Record<string, unknown> & {
  getRepository: (type: new () => object) => object[];
};
export function runCocomeDeletionDevelopment(
  m: CocomeDeletionsModule,
  options: {requirementText: string},
  operation: CocomeDeletionOperation
): DevelopmentBehaviorReport {
  if (!Object.hasOwn(cocomeDeletionSpecifications, operation))
    throw new Error('Unknown registered CoCoME deletion');
  const spec = cocomeDeletionSpecifications[operation];
  const expected = formatStructuredRequirement(
    getBenchmarkRequirement('CoCoME', spec.useCase, operation)
  );
  const normalize = (text: string) => text.replaceAll('\r\n', '\n').trim();
  if (!narrativeDevelopmentProfile(spec.id,options.requirementText)&&normalize(options.requirementText) !== normalize(expected))
    throw new Error(`CoCoME ${operation} requirement differs from the registered input`);
  const Entity = m[spec.entity] as new () => StoredObject;
  const Service = m[`${spec.service}_AutoGenerated`] as new () => Record<string, unknown>;
  if (
    typeof Entity !== 'function' ||
    typeof Service !== 'function' ||
    typeof m.getRepository !== 'function'
  )
    throw new Error('Candidate is missing the registered entity, service or repository function');
  const diagnostics: DevelopmentDiagnostic[] = [];
  const checks: DevelopmentBehaviorReport['checks'] = [];
  const executionObservations: DevelopmentBehaviorReport['executionObservations'] = [];
  for (const scenario of cocomeDeletionScenarios) {
    const repository = m.getRepository(Entity);
    repository.splice(0);
    const make = (id: number) => Object.assign(new Entity(), {Id: id});
    const target = make(scenario.identifier);
    const neighbors = scenario.neighbors.map(make);
    repository.push(
      ...(scenario.targetFirst
        ? [...(scenario.hasTarget ? [target] : []), ...neighbors]
        : [...neighbors, ...(scenario.hasTarget ? [target] : [])])
    );
    const service = new Service();
    const admissibleAtEntry=repository.includes(target);
    const method = service[operation];
    if (typeof method !== 'function') throw new Error(`Candidate is missing ${operation}`);
    const check = (id: string, passed: boolean | null, expected: unknown, observed: unknown) => {
      checks.push({scenarioId: scenario.id, obligationId: id, passed, expected, observed});
      if (passed === false)
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: 'OBLIGATION_MISMATCH',
          obligationIds: [id],
          expected,
          observed,
          message: spec.obligations.find((item) => item.id === id)!.requirement,
        });
    };
    let result: unknown;
    let failure: {name: string; message: string; oclOrigin?:unknown} | undefined;
    try {
      result = method.call(service, scenario.identifier);
    } catch (error) {
      failure =
        error instanceof Error
          ? {name: error.name, message: error.message,...('oclOrigin' in error?{oclOrigin:error.oclOrigin}:{})}
          : {name: 'Error', message: String(error)};
    }
    if (failure) {
      const definitionFailure =
        failure.name === 'PreconditionError' &&
        failure.message.includes('definition binding could not be evaluated');
      const rejected = failure.name === 'PreconditionError' && !definitionFailure;
      const origin=failure.oclOrigin as {clause?:string;phase?:string}|undefined;
      const witnessedAdmissionFailure=admissibleAtEntry&&origin?.clause==='precondition'&&origin.phase==='admission';
      if(admissibleAtEntry&&origin?.clause==='postcondition'&&origin.phase==='effect'&&m.getRepository(Entity).includes(target)){
        executionObservations.push({scenarioId:scenario.id,classification:'runtime-error',conventionStatus:'mismatched'});
        check('Q01',false,'the source-selected target must be removed',
          {targetStillPresent:true,failure,observationTiming:'after-effect-phase-failure',rootCauseEstablished:false});
        continue;
      }
      executionObservations.push({
        scenarioId: scenario.id,
        classification: definitionFailure
          ? 'definition-failure-unresolved'
          : rejected
            ? 'explicit-rejection'
            : 'runtime-error',
        conventionStatus: definitionFailure ? 'inconclusive' : rejected ? 'matched' : 'mismatched',
      });
      if (!admissibleAtEntry && (rejected||definitionFailure)) {
        check('P01', true, 'reject an independently confirmed absent target', failure.name);
        if(definitionFailure){
          executionObservations[executionObservations.length-1].conventionStatus='matched';
          executionObservations[executionObservations.length-1].rejectionEvidence={obligationId:'P01',preconditionSatisfied:false,basis:'independent-source-precondition-observation',rootCauseEstablished:false,expected:'target exists',observed:false};
        }
      }
      else
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: witnessedAdmissionFailure||definitionFailure&&admissibleAtEntry ? 'UNEXPECTED_REJECTION' : definitionFailure
            ? 'REJECTION_UNRESOLVED'
            : rejected
              ? 'UNEXPECTED_REJECTION'
              : 'EXECUTION_ERROR',
          obligationIds: (rejected||definitionFailure||witnessedAdmissionFailure) && admissibleAtEntry ? ['P01'] : [],
          expected: scenario.hasTarget ? `successful ${operation}` : 'request rejected',
          observed: {...failure,...(admissibleAtEntry?{admissibilityEvidence:{basis:'independent-source-precondition-observation',timing:'before-invocation',allSatisfied:true,obligationIds:['P01'],observations:[{obligationId:'P01',satisfied:true,expected:'target exists in the source repository',observed:true}]}}:{})},
          message:
            'Explicit rejection is separated from unresolved definition, runtime and postcondition-check failures before business repair.',
        });
      continue;
    }
    if (!scenario.hasTarget) {
      executionObservations.push({
        scenarioId: scenario.id,
        classification: 'return-without-rejection-signal',
        conventionStatus: 'mismatched',
      });
      if (result === true) check('P01', false, 'no successful deletion for a missing target', true);
      else {
        check('P01', null, 'a recognized rejection', result == null ? null : typeof result);
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: 'REJECTION_UNRESOLVED',
          obligationIds: [],
          expected: 'a recognized rejection',
          observed: result == null ? null : typeof result,
          message: 'A false or unrecognized return does not establish the rejection convention.',
        });
      }
      continue;
    }
    executionObservations.push({
      scenarioId: scenario.id,
      classification: 'completed',
      conventionStatus: 'matched',
    });
    check('P01', true, `accept this existing ${spec.entity}`, 'accepted');
    const present = m.getRepository(Entity).includes(target);
    check(
      'Q01',
      !present,
      `the referenced ${spec.entity} is absent from the repository`,
      present ? 'target remains present' : 'target removed'
    );
    check(
      'Q02',
      result === true,
      true,
      result == null ? null : typeof result === 'object' ? 'non-Boolean result' : result
    );
  }
  const businessStatus = diagnostics.some((item) =>
    ['OBLIGATION_MISMATCH', 'UNEXPECTED_REJECTION'].includes(item.code)
  )
    ? 'mismatched'
    : diagnostics.length
      ? 'inconclusive'
      : 'matched';
  const executionConventionStatus = executionObservations.some(
    (item) => item.conventionStatus === 'mismatched'
  )
    ? 'mismatched'
    : executionObservations.some((item) => item.conventionStatus === 'inconclusive')
      ? 'inconclusive'
      : 'matched';
  const observed = new Set(
    checks.filter((item) => item.passed !== null).map((item) => item.obligationId)
  );
  return {
    schemaVersion: spec.schemaVersion,
    operationId: spec.id,
    role: 'development_only',
    reviewStatus: 'pending-user-review',
    hiddenEvaluationUsed: false,
    dynamicRepairEnabled: false,
    coverageScope: 'finite-development-scenarios',
    businessAssessmentBasis: 'cited-upstream-operation-specification-and-aligned-current-input',
    assessmentPolicy: {
      target:
        'Capture the target identity at entry, then inspect its absence from the entity repository; changing its Id without removing it cannot satisfy deletion.',
      frame:
        'No cascade, inverse association, unrelated-object preservation or rollback assertion is inferred.',
      inputs:
        'Nonpositive Integer identifiers are legal when they identify a target. Distinct fixture IDs disambiguate objects without adding a uniqueness precondition.',
      rejection:
        'PreconditionError is the execution convention, not a source-prescribed exception class; arbitrary errors remain unresolved.',
    },
    businessStatus,
    executionConventionStatus,
    executionObservations,
    scenarioCount: cocomeDeletionScenarios.length,
    scenarioResults: cocomeDeletionScenarios.map((scenario) => ({
      id: scenario.id,
      passed: !diagnostics.some((item) => item.scenarioId === scenario.id),
      checkCount: checks.filter((item) => item.scenarioId === scenario.id).length,
    })),
    checks,
    diagnostics,
    passed:
      businessStatus === 'matched' && executionConventionStatus === 'matched' && checks.length > 0,
    unobservedObligationIds: spec.obligations
      .filter((item) => !observed.has(item.id))
      .map((item) => item.id),
  };
}
