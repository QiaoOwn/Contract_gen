import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios, type FiniteObservation} from './finiteScenarioReport';
import {atmTransactionSpecifications, atmTransactionScenarios, atmTransactionSources, type AtmTransactionKey} from './atmTransactionSpecification';
import type {DevelopmentRegistration} from './types';

type Value = Record<string, unknown>;
export type AtmTransactionModule = Record<string, unknown> & {getRepository: (ctor: new () => object) => object[]};
export function runAtmTransactionDevelopment(m: AtmTransactionModule, requirement: string, key: AtmTransactionKey) {
  const spec = atmTransactionSpecifications[key];
  const expected = formatStructuredRequirement(getBenchmarkRequirement('AutomatedTellerMachine', spec.useCase, spec.operation));
  const normalize = (text: string) => text.replaceAll('\r\n', '\n').trim();
  if (normalize(requirement) !== normalize(expected)) throw new Error('ATM transaction requirement differs from registered input');
  const scenarios = atmTransactionScenarios(key);
  return runFiniteScenarios({...spec, obligations: [...spec.obligations], schemaVersion: `development-atm-transaction-${key}-v1`}, scenarios, base => {
    const fact = scenarios.find(item => item.id === base.id)!;
    const Card = m.BankCard as new () => Value, Service = m.AutomatedTellerMachineSystem_AutoGenerated as new () => Value;
    m.getRepository(Card).splice(0);
    const balance = fact.balance ?? 791.25, quantity = fact.quantity ?? 100;
    const card = Object.assign(new Card(), {CardID: 977031, Password: 977041, Balance: balance});
    const service = Object.assign(new Service(), {CardIDValidated: fact.cardValidated ?? true,
      PasswordValidated: fact.passwordValidated ?? true, InputCard: fact.missingCard ? undefined : card,
      IsWithdraw: fact.isWithdraw ?? false, IsDeposit: fact.isDeposit ?? false,
      WithdrawedNumber: fact.withdrawn ?? 887, DepositedNumber: fact.deposited ?? 993.25});
    const item = (id: string, observed: unknown, wanted: unknown): FiniteObservation =>
      ({obligationId: id, passed: Object.is(observed, wanted), expected: wanted, observed});
    const state = (): FiniteObservation[] => spec.operation === 'ejectCard'
      ? [item('Q01', service.InputCard == null, true), item('Q02', service.PasswordValidated, false),
        item('Q03', service.CardIDValidated, false), item('Q04', service.IsWithdraw, false),
        item('Q05', service.IsDeposit, false), item('Q06', service.WithdrawedNumber, 0), item('Q07', service.DepositedNumber, 0)]
      : spec.operation === 'withdrawCash' ? [item('Q01', card.Balance, balance - quantity),
        item('Q02', service.WithdrawedNumber, quantity), item('Q03', service.IsWithdraw, true)] : [];
    return {
      invoke: () => (service[spec.operation] as (...args: number[]) => unknown).apply(service, spec.operation === 'withdrawCash' ? [quantity] : []),
      observePrecondition: id => ({satisfied: id === 'P04' ? balance >= quantity : id === 'P03' ? !fact.missingCard
        : spec.operation === 'printReceipt' ? id === 'P01' ? fact.cardValidated !== false : fact.passwordValidated !== false
          : id === 'P01' ? fact.passwordValidated !== false : fact.cardValidated !== false,
        expected: spec.obligations.find(item => item.id === id)!.requirement,
        observed: {hasCard: !fact.missingCard, balance, quantity, cardValidated: fact.cardValidated ?? true, passwordValidated: fact.passwordValidated ?? true}}),
      observeAfterPostcheckFailure: state,
      observe: result => [
        ...base.obligationIds.filter(id => id.startsWith('P')).map(id => item(id, true, true)),
        ...(spec.operation === 'printReceipt' ? [item(fact.isWithdraw ? 'Q01' : fact.isDeposit ? 'Q02' : 'Q03', result,
          fact.isWithdraw ? fact.withdrawn : fact.isDeposit ? fact.deposited : 0)]
          : [...state(), item(spec.operation === 'ejectCard' ? 'Q08' : 'Q04', result, true)]),
      ],
    };
  });
}
export function atmTransactionRegistration(key: AtmTransactionKey): DevelopmentRegistration {
  const spec = atmTransactionSpecifications[key];
  return {id: spec.id, project: 'AutomatedTellerMachine', useCase: spec.useCase, operation: spec.operation,
    schemaVersion: `development-atm-transaction-${key}-v1`, reviewStatus: 'pending-user-review',
    fixedClock: '2026-01-15T12:00:00+08:00', sources: atmTransactionSources,
    requirementSourceId: 'requirement-document', modelSourceId: 'upstream-model', obligations: spec.obligations,
    scenarios: atmTransactionScenarios(key).map(({id, obligationIds}) => ({id, obligationIds})),
    moduleExports: {BankCard: 'function', AutomatedTellerMachineSystem_AutoGenerated: 'function', getRepository: 'function'},
    run: (candidate, options) => runAtmTransactionDevelopment(candidate as AtmTransactionModule, options.requirementText, key)};
}
