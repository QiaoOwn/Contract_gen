import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios, type FiniteObservation} from './finiteScenarioReport';
import {
  libraryAlignmentSpecifications,
  libraryAlignmentScenarios,
  type LibraryAlignmentOperation,
} from './libraryAlignmentSpecification';
import type {DevelopmentRegistration} from './types';

type Entity = Record<string, unknown>;
export type LibraryAlignmentModule = Record<string, unknown> & {
  getRepository: (ctor: new () => object) => object[];
};
export function runLibraryAlignmentDevelopment(
  m: LibraryAlignmentModule,
  requirement: string,
  operation: LibraryAlignmentOperation
) {
  const spec = libraryAlignmentSpecifications[operation];
  const expected = formatStructuredRequirement(
    getBenchmarkRequirement('LibraryManagementSystem', spec.useCase, operation)
  );
  const normalize = (text: string) => text.replaceAll('\r\n', '\n').trim();
  if (normalize(requirement) !== normalize(expected))
    throw new Error('Library alignment requirement differs from the approved input');
  const Constructor = (name: string) => m[name] as new () => Entity;
  const create = (name: string, values: Entity) => Object.assign(new (Constructor(name))(), values);
  return runFiniteScenarios(spec, libraryAlignmentScenarios[operation], (base) => {
    const scenario = libraryAlignmentScenarios[operation].find((item) => item.id === base.id)!;
    const userRepository = m.getRepository(Constructor('User'));
    userRepository.splice(0);
    const Service = m[`${spec.service}_AutoGenerated`] as new () => Entity;
    const service = new Service();
    if (operation === 'countDownSuspensionDay') {
      const status = (key: string) => (m.BorrowStatus as Entity)[key];
      const facts = scenario.users!;
      const users = facts.map((fact, i) =>
        create('User', {
          UserID: `dev-clock-${i}`,
          SuspensionDays: fact.days,
          BorrowStatus: status(fact.status),
          OverDueFee: fact.fee,
        })
      );
      userRepository.push(...users);
      const state = (): FiniteObservation[] => [
        {
          obligationId: 'Q01',
          passed: users.every(
            (u, i) => facts[i].days <= 0 || u.SuspensionDays === facts[i].afterDays
          ),
          expected: facts.map((f) => f.afterDays),
          observed: users.map((u) => u.SuspensionDays),
        },
        {
          obligationId: 'Q02',
          passed: users.every(
            (u, i) => facts[i].days <= 0 || u.BorrowStatus === status(facts[i].afterStatus)
          ),
          expected: facts.map((f) => f.afterStatus),
          observed: users.map((u) => u.BorrowStatus),
        },
        {
          obligationId: 'Q03',
          passed: users.every(
            (u, i) =>
              !(facts[i].days === 1 && facts[i].status === 'SUSPEND' && facts[i].fee > 0) ||
              u.BorrowStatus === status('SUSPEND')
          ),
          expected: 'outstanding debt preserves suspension at zero days',
          observed: users.map((u) => u.BorrowStatus),
        },
        {
          obligationId: 'Q04',
          passed: users.every(
            (u, i) =>
              facts[i].days !== 0 ||
              (u.SuspensionDays === 0 &&
                u.BorrowStatus === status(facts[i].status) &&
                u.OverDueFee === facts[i].fee)
          ),
          expected: 'already-zero users are not processed',
          observed: users.map((u) => ({
            days: u.SuspensionDays,
            status: u.BorrowStatus,
            fee: u.OverDueFee,
          })),
        },
      ];
      return {
        invoke: () => (service[operation] as () => unknown).call(service),
        observe: state,
        observeAfterPostcheckFailure: state,
      };
    }
    const reservation = operation === 'listReservationBook';
    const sourceName = reservation ? 'Reserve' : 'Loan',
      collectionName = reservation ? 'ReservedBook' : 'LoanedBook';
    const copyName = reservation ? 'ReservedCopy' : 'LoanedCopy';
    m.getRepository(Constructor('BookCopy')).splice(0);
    m.getRepository(Constructor(sourceName)).splice(0);
    const uid = scenario.emptyUid ? '' : 'dev-library-selected';
    const copies = new Map(
      (scenario.records ?? []).map((record) => [
        record.copy,
        create('BookCopy', {Barcode: 'equal-data', Location: 'same-location'}),
      ])
    );
    const records = (scenario.records ?? []).map((record) => ({
      owner: record.owner,
      closed: record.closed ?? false,
      value: create(sourceName, {
        [copyName]: copies.get(record.copy),
        IsReturned: record.returned ?? false,
        OverDueFee: record.fee ?? 0,
        IsReserveClosed: record.closed ?? false,
      }),
    }));
    const target = create('User', {
      UserID: uid,
      ...(scenario.missingCollection
        ? {}
        : {[collectionName]: records.filter((r) => r.owner === 'selected').map((r) => r.value)}),
    });
    const other = create('User', {
      UserID: 'dev-library-other',
      [collectionName]: records.filter((r) => r.owner === 'other').map((r) => r.value),
    });
    userRepository.push(other);
    if (!scenario.missingUser) userRepository.push(target);
    m.getRepository(Constructor(sourceName)).push(...records.map((r) => r.value));
    if (scenario.registerCopies !== false)
      m.getRepository(Constructor('BookCopy')).push(...copies.values());
    const wanted = scenario.expectedCopies!.map((key) => copies.get(key)!);
    return {
      invoke: () => (service[operation] as (id: string) => unknown).call(service, uid),
      observePrecondition: (id) => ({
        satisfied:
          id === 'P01'
            ? !scenario.missingUser
            : !scenario.missingUser && !scenario.missingCollection,
        expected: spec.obligations.find((item) => item.id === id)!.requirement,
        observed: id === 'P01' ? !scenario.missingUser : !scenario.missingCollection,
      }),
      observe: (result) => {
        const values = Array.isArray(result) ? result : [];
        return [
          {
            obligationId: 'P01',
            passed: true,
            expected: 'existing User accepted',
            observed: 'accepted',
          },
          {
            obligationId: 'P02',
            passed: true,
            expected: 'resolved collection accepted, including empty',
            observed: 'accepted',
          },
          {
            obligationId: 'Q01',
            passed:
              Array.isArray(result) &&
              values.every((value) => wanted.includes(value)) &&
              wanted.every((value) => values.includes(value)),
            expected: scenario.expectedCopies,
            observed: values.map(
              (v) => [...copies].find(([, value]) => value === v)?.[0] ?? 'unexpected-object'
            ),
          },
          {
            obligationId: 'Q02',
            passed: Array.isArray(result) && new Set(values).size === values.length,
            expected: 'one occurrence per copy identity',
            observed: values.length,
          },
          {
            obligationId: 'Q03',
            passed: Array.isArray(result) && wanted.every((value) => values.includes(value)),
            expected: 'all distinct expected identities, regardless of equal attributes',
            observed: values.length,
          },
          ...(reservation
            ? [
                {
                  obligationId: 'Q04',
                  passed:
                    Array.isArray(result) &&
                    records
                      .filter((r) => r.owner === 'selected' && r.closed)
                      .every((r) => values.includes(r.value[copyName])),
                  expected: 'closed records contribute their copy identities',
                  observed: values.length,
                },
              ]
            : []),
        ];
      },
    };
  });
}
export function libraryAlignmentRegistration(
  operation: LibraryAlignmentOperation
): DevelopmentRegistration {
  const spec = libraryAlignmentSpecifications[operation];
  return {
    id: spec.id,
    project: 'LibraryManagementSystem',
    useCase: spec.useCase,
    operation,
    schemaVersion: spec.schemaVersion,
    reviewStatus: 'pending-user-review',
    fixedClock: '2026-01-15T12:00:00+08:00',
    sources: spec.sources,
    requirementSourceId: 'adjudication',
    modelSourceId: 'upstream-model',
    obligations: spec.obligations,
    scenarios: libraryAlignmentScenarios[operation].map(({id, obligationIds}) => ({
      id,
      obligationIds,
    })),
    moduleExports: {
      User: 'function',
      ...(operation === 'countDownSuspensionDay'
        ? {BorrowStatus: 'object' as const}
        : {
            BookCopy: 'function' as const,
            [operation === 'listReservationBook' ? 'Reserve' : 'Loan']: 'function' as const,
          }),
      [`${spec.service}_AutoGenerated`]: 'function',
      getRepository: 'function',
    },
    run: (candidate, options) =>
      runLibraryAlignmentDevelopment(
        candidate as LibraryAlignmentModule,
        options.requirementText,
        operation
      ),
  };
}
