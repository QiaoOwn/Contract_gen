import {formatStructuredRequirement,getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios} from './finiteScenarioReport';
import {submittedRequestsSources} from './submittedLoanRequestsSpecification';
import type {DevelopmentRegistration,DevelopmentObligation} from './types';

type Request={RequestID:number;Status:unknown;AttachedApprovalLetter?:Document;AttachedLoanAgreement?:Document};
type Document={Content:string};
type Service={CurrentLoanRequest?:Request;genereateApprovalLetter:(id:number)=>unknown;generateLoanAgreement:()=>unknown};
type Module={LoanRequest:new()=>Request;ApprovalLetter:new()=>Document;LoanAgreement:new()=>Document;
  LoanRequestStatus:Record<string,unknown>;getRepository:(ctor:new()=>Request|Document)=>(Request|Document)[];
  GenerateLoanLetterAndAgreementModule_AutoGenerated:new()=>Service};
export function loanDocumentCreationRegistration(operation:'genereateApprovalLetter'|'generateLoanAgreement'):DevelopmentRegistration{
  const letter=operation==='genereateApprovalLetter',targetType=letter?'ApprovalLetter':'LoanAgreement';
  const field=letter?'AttachedApprovalLetter':'AttachedLoanAgreement';
  const content=letter?'ApprovalLetterContent':'Loan Agreement';
  const id='LoanProcessingSystem_generateLoanLetterAndAgreement_'+operation;
  const sourceLine=letter?2241:2366,modelPre=letter?664:715;
  const obligation=(code:string,clause:DevelopmentObligation['clause'],requirement:string,
    doc:number,model:number,features:string[]):DevelopmentObligation=>({id:code,clause,requirement,
    documentLine:doc,modelLines:[model,model],modelFeatures:features});
  const obligations=[
    obligation('P01','precondition',letter?'A request with the supplied ID exists.':'CurrentLoanRequest exists.',
      sourceLine,modelPre,letter?['LoanRequest.RequestID','$parameter.id']:['self.CurrentLoanRequest']),
    obligation('Q01','postcondition','Create and store one new '+targetType+'.',
      letter?2254:2378,letter?678:728,[targetType]),
    obligation('Q02','postcondition','The new document content is '+content+'.',
      letter?2255:2379,letter?679:729,[targetType+'.Content']),
    obligation('Q03','postcondition','Link the new document to the selected LoanRequest.',
      letter?2256:2380,letter?680:730,['LoanRequest.'+field,targetType]),
    ...(letter?[obligation('Q04','postcondition','Set CurrentLoanRequest to the selected request.',
      2257,681,['self.CurrentLoanRequest'])]:[]),
    obligation(letter?'Q05':'Q04','postcondition','Return true.',
      letter?2259:2382,letter?683:732,['$result']),
  ];
  const cases=letter?['first','second','absent-id']:['approved','submitted','no-current'];
  const scenarios=cases.map(key=>({id:'dev-loan-document-'+operation+'-'+key,
    rejectObligation:key==='absent-id'||key==='no-current'?'P01':undefined,
    obligationIds:key==='absent-id'||key==='no-current'?['P01']:obligations.map(item=>item.id)}));
  return {id,project:'LoanProcessingSystem',useCase:'generateLoanLetterAndAgreement',operation,
    schemaVersion:'development-loan-document-v1',reviewStatus:'pending-user-review',
    fixedClock:'2026-01-15T12:00:00+08:00',
    sources:submittedRequestsSources.map(source=>({...source,note:source.id==='requirement-document'
      ? 'Active '+operation+' contract at lines '+(letter?'2228-2259':'2360-2382')+'.'
      : 'Active '+operation+' model contract at lines '+(letter?'649-684':'708-733')+'.'})),
    requirementSourceId:'requirement-document',modelSourceId:'upstream-model',obligations,scenarios,
    moduleExports:{LoanRequest:'function',ApprovalLetter:'function',LoanAgreement:'function',
      LoanRequestStatus:'object',getRepository:'function',
      GenerateLoanLetterAndAgreementModule_AutoGenerated:'function'},
    run(candidate,{requirementText}){
      const expected=formatStructuredRequirement(getBenchmarkRequirement('LoanProcessingSystem',
        'generateLoanLetterAndAgreement',operation));
      if(requirementText.replaceAll('\r\n','\n').trim()!==expected.replaceAll('\r\n','\n').trim())
        throw new Error('Loan document input differs from frozen requirement');
      const m=candidate as Module;
      return runFiniteScenarios({id,schemaVersion:'development-loan-document-v1',obligations},scenarios,scenario=>{
        const key=cases.find(item=>scenario.id.endsWith('-'+item))!;
        const requests=m.getRepository(m.LoanRequest) as Request[];
        const documents=m.getRepository(m[targetType]) as Document[];
        requests.splice(0);documents.splice(0);
        const first=Object.assign(new m.LoanRequest(),{RequestID:11,Status:m.LoanRequestStatus.APPROVED});
        const second=Object.assign(new m.LoanRequest(),{RequestID:22,
          Status:key==='submitted'?m.LoanRequestStatus.SUBMITTED:m.LoanRequestStatus.APPROVED});
        requests.push(first,second);
        const service=new m.GenerateLoanLetterAndAgreementModule_AutoGenerated();
        if(key!=='no-current')service.CurrentLoanRequest=key==='first'?first:second;
        const target=key==='first'?first:second;
        const admitted=key!=='absent-id'&&key!=='no-current';
        const selectedDocument=()=>target[field];
        const state=()=>[
          {obligationId:'Q01',passed:documents.length===1&&documents[0]!==undefined&&
            documents[0]===selectedDocument(),expected:'one new linked '+targetType,
            observed:{count:documents.length,linked:documents.includes(selectedDocument() as Document)}},
          {obligationId:'Q02',passed:selectedDocument()?.Content===content,expected:content,
            observed:selectedDocument()?.Content},
          {obligationId:'Q03',passed:documents.includes(selectedDocument() as Document),expected:'linked stored document',
            observed:documents.includes(selectedDocument() as Document)},
          ...(letter?[{obligationId:'Q04',passed:service.CurrentLoanRequest===target,expected:target.RequestID,
            observed:service.CurrentLoanRequest?.RequestID}]:[]),
        ];
        return {invoke:()=>letter?service.genereateApprovalLetter(key==='absent-id'?99:target.RequestID)
          :service.generateLoanAgreement(),
          observePrecondition:()=>({satisfied:admitted,expected:obligations[0].requirement,observed:admitted}),
          observeAfterPostcheckFailure:state,
          observe:result=>[
            {obligationId:'P01',passed:admitted,expected:true,observed:admitted},
            ...state(),
            {obligationId:letter?'Q05':'Q04',passed:result===true,expected:true,observed:result},
          ]};
      });
    },
  };
}
