import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios} from './finiteScenarioReport';
import {narrativeDevelopmentProfile} from './narrativeDevelopmentProfiles';
import {librarySearchSources} from './librarySearchSpecification';
import type {DevelopmentRegistration, DevelopmentObligation} from './types';

type Copy = {Barcode?: string; Location?: string; Status?: unknown; IsReserved?: boolean; BookBelongs?: Book};
type Book = {CallNo: string; CopyNum: number; Copys: Copy[]};
type Module = {Book: new () => Book; BookCopy: new () => Copy; CopyStatus: {AVAILABLE: unknown};
  getRepository<T>(ctor: new () => T): T[];
  ManageBookCopyCRUDService_AutoGenerated: new () => {addBookCopy(n: string, code: string, location: string): unknown}};
const id = 'LibraryManagementSystem_manageBookCopy_addBookCopy';
const schemaVersion = 'development-library-addBookCopy-v1';
const rules = (clause: 'precondition' | 'postcondition', doc: number, model: number, rows: string[][]): DevelopmentObligation[] =>
  rows.map(([requirement, ...modelFeatures], i) => ({id: (clause === 'precondition' ? 'P' : 'Q') + String(i+1).padStart(2,'0'),
    clause, requirement, modelFeatures, documentLine: doc+i, modelLines: [model+i,model+i]}));
const obligations = [
  ...rules('precondition', 4927, 1726, [['The selected book exists.', 'Book.CallNo', '$parameter.callNo'],
    ['No linked copy has the supplied barcode.', 'Book.Copys', 'BookCopy.Barcode', '$parameter.barcode']]),
  ...rules('postcondition', 4945, 1745, [['Create a fresh BookCopy.', 'BookCopy'],
    ['Set the supplied barcode.', 'BookCopy.Barcode', '$parameter.barcode'], ['Set status AVAILABLE.', 'BookCopy.Status'],
    ['Set the supplied location.', 'BookCopy.Location', '$parameter.location'], ['Set the reserved flag to false.', 'BookCopy.IsReserved'],
    ['Include the copy in the selected book.', 'Book.Copys'], ['Link the copy back to the book.', 'BookCopy.BookBelongs'],
    ['Increment the entry copy count by one.', 'Book.CopyNum'], ['Store the new copy.', 'BookCopy'], ['Return true.', '$result']]),
];
const scenarios = ['ordinary','other-book-same-code','empty-strings','missing-book','linked-duplicate'].map(key => {
  const rejectObligation = key === 'missing-book' ? 'P01' : key === 'linked-duplicate' ? 'P02' : undefined;
  return {key, id: 'dev-addcopy-' + key, rejectObligation, obligationIds: rejectObligation ? [rejectObligation] : obligations.map(o => o.id)};
});
export const addBookCopyRegistration: DevelopmentRegistration = {
  id, schemaVersion, project: 'LibraryManagementSystem', useCase: 'manageBookCopy', operation: 'addBookCopy',
  reviewStatus: 'pending-user-review', fixedClock: '2026-01-15T12:00:00+08:00',
  sources: librarySearchSources.map(s => ({...s, note: 'Active addBookCopy clauses: book-local barcode lookup and entry count plus one.'})),
  requirementSourceId: 'requirement-document', modelSourceId: 'upstream-model', obligations, scenarios,
  moduleExports: {Book: 'function', BookCopy: 'function', CopyStatus: 'object', getRepository: 'function', ManageBookCopyCRUDService_AutoGenerated: 'function'},
  run(candidate, {requirementText}) {
    const expected = formatStructuredRequirement(getBenchmarkRequirement('LibraryManagementSystem','manageBookCopy','addBookCopy'));
    if (!narrativeDevelopmentProfile(id,requirementText)&&requirementText.replaceAll('\r\n','\n').trim() !== expected.replaceAll('\r\n','\n').trim()) throw new Error('addBookCopy input differs from registered requirement');
    const m = candidate as Module;
    return runFiniteScenarios({id,schemaVersion,obligations}, scenarios, base => {
      const {key} = scenarios.find(s => s.id === base.id)!;
      const books = m.getRepository(m.Book), copies = m.getRepository(m.BookCopy);
      books.splice(0); copies.splice(0);
      const [n, code, location] = key === 'empty-strings' ? ['', '', ''] : ['dev-book','dev-bar','dev-shelf'];
      const book = Object.assign(new m.Book(), {CallNo:n, CopyNum:key === 'ordinary' ? 0 : 7, Copys:[] as Copy[]});
      const other = Object.assign(new m.Book(), {CallNo:'neighbor', CopyNum:1, Copys:[] as Copy[]});
      const foreign = Object.assign(new m.BookCopy(), {Barcode:key === 'other-book-same-code' ? code : 'foreign', BookBelongs:other});
      other.Copys.push(foreign); copies.push(foreign); books.push(other);
      if (key !== 'missing-book') books.push(book);
      if (key === 'linked-duplicate') book.Copys.push(Object.assign(new m.BookCopy(), {Barcode:code, BookBelongs:book}));
      const prior = new Set([...copies,...book.Copys,...other.Copys]), count = book.CopyNum;
      const admission = [books.includes(book), !book.Copys.some(c => c.Barcode === code)];
      const state = () => {
        const effects = (c?: Copy) => [!!c, !!c && c.Barcode === code, !!c && c.Status === m.CopyStatus.AVAILABLE,
          !!c && c.Location === location, c?.IsReserved === false, !!c && book.Copys.includes(c), c?.BookBelongs === book,
          book.CopyNum === count+1, !!c && copies.includes(c)];
        const fresh = [...copies,...book.Copys].filter(c => c instanceof m.BookCopy && !prior.has(c));
        return effects(fresh.find(c => effects(c).every(Boolean)) ?? fresh[0]).map((passed,i) => ({
          obligationId: obligations[2+i].id, passed, expected: obligations[2+i].requirement, observed: passed}));
      };
      return {invoke: () => new m.ManageBookCopyCRUDService_AutoGenerated().addBookCopy(n,code,location),
        observePrecondition: code => ({satisfied: admission[Number(code.slice(1))-1], expected: obligations[Number(code.slice(1))-1].requirement, observed: admission[Number(code.slice(1))-1]}),
        observeAfterPostcheckFailure: state,
        observe: result => [...obligations.slice(0,2).map(o => ({obligationId:o.id, passed:true, expected:'accepted', observed:'completed'})),
          ...state(), {obligationId:'Q10', passed:result === true, expected:true, observed:result}]};
    });
  },
};
