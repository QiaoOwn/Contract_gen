import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios} from './finiteScenarioReport';
import {librarySearchSources} from './librarySearchSpecification';
import type {DevelopmentObligation, DevelopmentRegistration} from './types';

const operation = 'sendNotificationEmail';
const id = 'LibraryManagementSystem_sendNotificationEmail_sendNotificationEmail';
const schemaVersion = 'development-library-notification-v1';
const obligations: DevelopmentObligation[] = [
  {id: 'P01', clause: 'precondition', requirement: 'The supplied email string is not empty.',
    documentLine: 3959, modelLines: [1278, 1278], modelFeatures: ['$parameter.email']},
  {id: 'Q01', clause: 'postcondition', requirement: 'The operation returns Boolean true.',
    documentLine: 3965, modelLines: [1285, 1285], modelFeatures: ['$result']},
];
const facts = [
  {name: 'address', email: 'dev@example.test'}, {name: 'single-character', email: 'x'},
  {name: 'whitespace', email: '\t'}, {name: 'empty', email: ''},
].map(fact => ({...fact, id: 'dev-notification-' + fact.name,
  obligationIds: fact.email === '' ? ['P01'] : ['P01', 'Q01'],
  rejectObligation: fact.email === '' ? 'P01' : undefined}));

export const libraryNotificationRegistration: DevelopmentRegistration = {
  id, operation, schemaVersion, project: 'LibraryManagementSystem', useCase: operation,
  fixedClock: '2026-01-15T12:00:00+08:00', reviewStatus: 'pending-user-review',
  sources: librarySearchSources.map(source => ({...source, note:
    'OP25 active formal clauses specify a nonempty string and a true result; no address syntax or delivery oracle.'})),
  requirementSourceId: 'requirement-document', modelSourceId: 'upstream-model', obligations,
  scenarios: facts.map(({id, obligationIds}) => ({id, obligationIds})),
  moduleExports: {ThirdPartyServices_AutoGenerated: 'function'},
  run(candidate, {requirementText}) {
    const expected = formatStructuredRequirement(getBenchmarkRequirement('LibraryManagementSystem', operation, operation));
    if (requirementText.replaceAll('\r\n', '\n').trim() !== expected.replaceAll('\r\n', '\n').trim())
      throw new Error('Notification requirement differs from frozen input');
    const {ThirdPartyServices_AutoGenerated: Service} = candidate as {
      ThirdPartyServices_AutoGenerated: new () => {sendNotificationEmail(email: string): unknown}};
    return runFiniteScenarios({id, schemaVersion, obligations}, facts, scenario => {
      const {email} = facts.find(fact => fact.id === scenario.id)!;
      return {invoke: () => new Service().sendNotificationEmail(email),
        observePrecondition: () => ({satisfied: email.length > 0, expected: 'nonempty String', observed: {length: email.length}}),
        observe: result => [
          {obligationId: 'P01', passed: true, expected: 'accepted', observed: 'completed'},
          {obligationId: 'Q01', passed: result === true, expected: true, observed: result},
        ]};
    });
  },
};
