import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import type {DevelopmentBehaviorReport, DevelopmentDiagnostic} from './types';
import {narrativeDevelopmentProfile} from './narrativeDevelopmentProfiles';
import {
  ADD_LOAN_TERM_ID,
  ADD_LOAN_TERM_VERSION,
  addLoanTermObligations,
  addLoanTermScenarios,
} from './addLoanTermSpecification';

type Term = {ItemID?: number};
type Request = {AttachedLoanTerms?: Term[]};
export type AddLoanTermModule = {
  LoanTerm: new () => Term;
  LoanRequest: new () => Request;
  EvaluateLoanRequestModule_AutoGenerated: new () => {
    CurrentLoanRequest?: Request;
    addLoanTerm: (id: number) => unknown;
  };
  getRepository: (type: new () => object) => object[];
};
export function runAddLoanTermDevelopment(
  m: AddLoanTermModule,
  options: {requirementText: string}
): DevelopmentBehaviorReport {
  const expected = formatStructuredRequirement(
    getBenchmarkRequirement('LoanProcessingSystem', 'evaluateLoanRequest', 'addLoanTerm')
  );
  if (
    !narrativeDevelopmentProfile(ADD_LOAN_TERM_ID,options.requirementText)&&
    options.requirementText.replaceAll('\r\n', '\n').trim() !== expected.replaceAll('\r\n', '\n').trim()
  )
    throw new Error('addLoanTerm development input differs from the frozen requirement');
  const checks: DevelopmentBehaviorReport['checks'] = [];
  const diagnostics: DevelopmentDiagnostic[] = [];
  const executionObservations: DevelopmentBehaviorReport['executionObservations'] = [];
  for (const scenario of addLoanTermScenarios) {
    const termRepo = m.getRepository(m.LoanTerm),
      requestRepo = m.getRepository(m.LoanRequest);
    termRepo.splice(0);
    requestRepo.splice(0);
    const term = Object.assign(new m.LoanTerm(), {ItemID: 987011});
    const neighbor = Object.assign(new m.LoanTerm(), {ItemID: 987022});
    if (scenario.hasTerm) termRepo.push(term);
    if (scenario.neighbors) termRepo.push(neighbor);
    const request = Object.assign(new m.LoanRequest(), {
      AttachedLoanTerms: scenario.linked ? [term] : scenario.neighbors ? [neighbor] : [],
    });
    if (scenario.hasRequest) requestRepo.push(request);
    const service = new m.EvaluateLoanRequestModule_AutoGenerated();
    service.CurrentLoanRequest = scenario.hasRequest ? request : undefined;
    const admissionFacts=[{obligationId:'P01',satisfied:service.CurrentLoanRequest===request&&requestRepo.includes(request)},
      {obligationId:'P02',satisfied:termRepo.includes(term)}];
    const admissionEvidence=admissionFacts.every(f=>f.satisfied)?{basis:'independent-source-precondition-observation',
      timing:'before-invocation',allSatisfied:true,obligationIds:['P01','P02'],observations:admissionFacts}:undefined;
    const check = (id: string, passed: boolean | null, expected: unknown, observed: unknown) => {
      checks.push({scenarioId: scenario.id, obligationId: id, passed, expected, observed});
      if (passed === false)
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: 'OBLIGATION_MISMATCH',
          obligationIds: [id],
          expected,
          observed,
          message: addLoanTermObligations.find((item) => item.id === id)!.requirement,
        });
    };
    let result: unknown, failure: Error | undefined;
    try {
      result = service.addLoanTerm(987011);
    } catch (error) {
      failure = error instanceof Error ? error : new Error(String(error));
    }
    if (failure) {
      const origin=(failure as Error&{oclOrigin?:{clause?:string;phase?:string}}).oclOrigin;
      const witnessedAdmission=!!admissionEvidence&&origin?.clause==='precondition'&&origin.phase==='admission';
      const explicit =
        failure.name === 'PreconditionError' &&
        !failure.message.includes('definition binding could not be evaluated');
      executionObservations.push({
        scenarioId: scenario.id,
        classification: explicit ? 'explicit-rejection' : 'runtime-error',
        conventionStatus: explicit ? 'matched' : 'inconclusive',
      });
      if (scenario.rejectObligation && explicit)
        check(scenario.rejectObligation, true, 'request rejected', failure.name);
      else
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: explicit||witnessedAdmission ? 'UNEXPECTED_REJECTION' : 'EXECUTION_ERROR',
          obligationIds: scenario.rejectObligation ? [scenario.rejectObligation] : ['P01', 'P02'],
          expected: scenario.rejectObligation
            ? 'explicit rejection'
            : 'successful association update',
          observed: {name: failure.name, message: failure.message,oclOrigin:origin,...(admissionEvidence?{admissibilityEvidence:admissionEvidence}:{})},
          message:
            'Inspect execution; a runtime exception is not itself proof of an obligation mismatch.',
        });
      continue;
    }
    executionObservations.push({
      scenarioId: scenario.id,
      classification: scenario.rejectObligation ? 'return-without-rejection-signal' : 'completed',
      conventionStatus: scenario.rejectObligation ? 'mismatched' : 'matched',
    });
    if (scenario.rejectObligation) {
      check(
        scenario.rejectObligation,
        result === true ? false : null,
        'explicit rejection',
        result ?? null
      );
      if (result !== true)
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: 'REJECTION_UNRESOLVED',
          obligationIds: [scenario.rejectObligation],
          expected: 'explicit rejection',
          observed: result ?? null,
          message: 'A non-success return does not establish the rejection convention.',
        });
      continue;
    }
    check('P01', true, 'existing request accepted', 'accepted');
    check('P02', true, 'selected term accepted', 'accepted');
    check(
      'Q01',
      Array.isArray(request.AttachedLoanTerms) && request.AttachedLoanTerms.includes(term),
      'association contains the selected object',
      request.AttachedLoanTerms?.map((item) => item.ItemID)
    );
    check('Q02', result === true, true, result ?? null);
  }
  const unobserved = addLoanTermObligations
    .filter(
      (obligation) =>
        !checks.some((check) => check.obligationId === obligation.id && check.passed !== null)
    )
    .map((item) => item.id);
  const businessStatus = diagnostics.some((item) =>
    ['OBLIGATION_MISMATCH', 'SPECIFICATION_DETAIL_MISMATCH', 'UNEXPECTED_REJECTION'].includes(
      item.code
    )
  )
    ? 'mismatched'
    : diagnostics.length
      ? 'inconclusive'
      : 'matched';
  const conventionStatus = executionObservations.some(
    (item) => item.conventionStatus === 'mismatched'
  )
    ? 'mismatched'
    : executionObservations.some((item) => item.conventionStatus === 'inconclusive')
      ? 'inconclusive'
      : 'matched';
  return {
    schemaVersion: ADD_LOAN_TERM_VERSION,
    operationId: ADD_LOAN_TERM_ID,
    role: 'development_only',
    reviewStatus: 'pending-user-review',
    hiddenEvaluationUsed: false,
    dynamicRepairEnabled: false,
    coverageScope: 'finite-development-scenarios',
    businessAssessmentBasis: 'cited-upstream-operation-specification-and-aligned-current-input',
    businessStatus,
    executionConventionStatus: conventionStatus,
    scenarioCount: addLoanTermScenarios.length,
    scenarioResults: addLoanTermScenarios.map((scenario) => ({
      id: scenario.id,
      passed: !diagnostics.some((item) => item.scenarioId === scenario.id),
      checkCount: checks.filter((item) => item.scenarioId === scenario.id).length,
    })),
    checks,
    diagnostics,
    executionObservations,
    unobservedObligationIds: unobserved,
    passed: businessStatus === 'matched' && conventionStatus === 'matched' && checks.length > 0,
    assessmentPolicy: {
      frame:
        'Only the stated target association membership and return are asserted. No unstated inverse link, ordering, cascade or unrelated-object frame requirement is added.',
      rejection: 'PreconditionError is an execution convention, not a business requirement.',
    },
  };
}
