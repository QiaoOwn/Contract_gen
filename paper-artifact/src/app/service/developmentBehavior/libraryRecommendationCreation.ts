import dayjs from 'dayjs';
import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios} from './finiteScenarioReport';
import {librarySearchSources} from './librarySearchSpecification';
import type {DevelopmentRegistration, DevelopmentObligation} from './types';

type Row = Record<string, unknown>;
type User = {UserID:string; RecommendedBook:Row[]};
type Module = {User:new()=>User; RecommendBook:new()=>Row; getRepository<T>(ctor:new()=>T):T[];
  LibraryManagementSystemSystem_AutoGenerated:new()=>{recommendBook(...args:string[]):unknown}};
const operation = 'recommendBook', id = 'LibraryManagementSystem_recommendBook_recommendBook';
const schemaVersion = 'development-library-recommendation-creation-v1';
const fields = ['CallNo','Title','Edition','Author','Publisher','Description','ISBn'];
const params = ['callNo','title','edition','author','publisher','description','isbn'];
const rules = (prefix:'P'|'Q', doc:number, model:number, rows:string[][]):DevelopmentObligation[] =>
  rows.map(([requirement,...modelFeatures], i)=>({id:prefix+String(i+1).padStart(2,'0'),clause:prefix==='P'?'precondition':'postcondition',
    requirement,modelFeatures,documentLine:doc+i,modelLines:[model+i,model+i]}));
const obligations = [
  ...rules('P',3497,1015,[['The selected user exists.','User.UserID','$parameter.uid'],
    ['The call number is unused in registered recommendations.','RecommendBook','Book.CallNo','$parameter.callNo']]),
  ...rules('Q',3518,1037,[['Create a new recommendation.','RecommendBook'],
    ...fields.map((f,i)=>['Set '+f+' from '+params[i]+'.','Book.'+f,'$parameter.'+params[i]]),
    ['Record today as recommendation date.','RecommendBook.RecommendDate'],['Link to the selected user.','RecommendBook.RecommendUser'],
    ['Include it in the user recommendations.','User.RecommendedBook'],['Store the new record.','RecommendBook'],['Return true.','$result']]),
];
const scenarios = ['ordinary','empty-values','missing-user','same-user-duplicate','foreign-duplicate'].map(key=>{
  const rejectObligation = key==='missing-user'?'P01':key.endsWith('duplicate')?'P02':undefined;
  return {key,id:'dev-recommend-'+key,rejectObligation,obligationIds:rejectObligation?[rejectObligation]:obligations.map(o=>o.id)};
});
export const recommendationCreation:DevelopmentRegistration = {
  id,schemaVersion,project:'LibraryManagementSystem',operation,useCase:operation,reviewStatus:'pending-user-review',
  fixedClock:'2026-01-15T12:00:00+08:00',requirementSourceId:'requirement-document',modelSourceId:'upstream-model',
  sources:librarySearchSources.map(s=>({...s,note:'Active recommendation creation and global recommendation call number lookup.'})),
  obligations,scenarios,moduleExports:{User:'function',RecommendBook:'function',getRepository:'function',LibraryManagementSystemSystem_AutoGenerated:'function'},
  run(candidate,{requirementText}) {
    const expected = formatStructuredRequirement(getBenchmarkRequirement('LibraryManagementSystem',operation,operation));
    if (requirementText.replaceAll('\r\n','\n').trim()!==expected.replaceAll('\r\n','\n').trim()) throw new Error('Recommendation creation input differs from registered requirement');
    const m = candidate as Module;
    return runFiniteScenarios({id,schemaVersion,obligations},scenarios,base=>{
      const {key} = scenarios.find(s=>s.id===base.id)!;
      const users=m.getRepository(m.User), store=m.getRepository(m.RecommendBook);
      users.splice(0); store.splice(0);
      const u=Object.assign(new m.User(),{UserID:key==='empty-values'?'':'reader',RecommendedBook:[] as Row[]});
      const neighbor=Object.assign(new m.User(),{UserID:'neighbor',RecommendedBook:[] as Row[]});
      users.push(neighbor); if(key!=='missing-user') users.push(u);
      const values=params.map(p=>key==='empty-values'?'':'dev-'+p);
      const owner=key==='same-user-duplicate'?u:neighbor;
      const old=Object.assign(new m.RecommendBook(),{CallNo:key.endsWith('duplicate')?values[0]:'other',RecommendUser:owner});
      owner.RecommendedBook.push(old); store.push(old);
      const prior=new Set(store), today=dayjs(), admission=[users.includes(u),!store.some(r=>r.CallNo===values[0])];
      const state=()=>{
        const effects=(r?:Row)=>[!!r,...fields.map((f,i)=>!!r && r[f]===values[i]),
          !!r && dayjs.isDayjs(r.RecommendDate) && r.RecommendDate.isSame(today,'day'), r?.RecommendUser===u,
          !!r && u.RecommendedBook.includes(r),!!r && store.includes(r)];
        const fresh=[...store,...u.RecommendedBook].filter(r=>r instanceof m.RecommendBook && !prior.has(r));
        const witness=fresh.find(r=>effects(r).every(Boolean)) ?? fresh[0];
        return effects(witness).map((passed,i)=>({obligationId:obligations[i+2].id,passed,expected:obligations[i+2].requirement,observed:passed}));
      };
      return {invoke:()=>new m.LibraryManagementSystemSystem_AutoGenerated().recommendBook(u.UserID,...values),
        observePrecondition:code=>({satisfied:admission[Number(code.slice(1))-1],expected:obligations[Number(code.slice(1))-1].requirement,observed:admission[Number(code.slice(1))-1]}),
        observeAfterPostcheckFailure:state,
        observe:result=>[...obligations.slice(0,2).map(o=>({obligationId:o.id,passed:true,expected:'accepted',observed:'completed'})),
          ...state(),{obligationId:'Q13',passed:result===true,expected:true,observed:result}]};
    });
  },
};
