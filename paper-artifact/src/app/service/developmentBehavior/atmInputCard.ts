import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios, type FiniteObservation} from './finiteScenarioReport';
import {ATM_INPUT_CARD_VERSION, atmInputCardId, atmInputCardObligations, atmInputCardScenarios,
  atmInputCardSources, type AtmInputCardUseCase} from './atmInputCardSpecification';
import type {DevelopmentRegistration} from './types';

type Card = {CardID?: number; CardStatus?: unknown; BelongedUser?: object};
export type AtmInputCardModule = {
  BankCard: new () => Card;
  User: new () => object;
  CardStatus: Record<string, unknown>;
  AutomatedTellerMachineSystem_AutoGenerated: new () => {
    InputCard?: Card; CardIDValidated?: boolean; inputCard: (key: number) => unknown;
  };
  getRepository: (ctor: new () => object) => object[];
};
export function runAtmInputCardDevelopment(m: AtmInputCardModule, requirement: string, useCase: AtmInputCardUseCase) {
  const expected = formatStructuredRequirement(getBenchmarkRequirement('AutomatedTellerMachine', useCase, 'inputCard'));
  const normalize = (text: string) => text.replaceAll('\r\n', '\n').trim();
  if (normalize(requirement) !== normalize(expected)) throw new Error('ATM inputCard requirement differs from its source-aligned registration');
  return runFiniteScenarios({id: atmInputCardId(useCase), schemaVersion: ATM_INPUT_CARD_VERSION,
    obligations: atmInputCardObligations}, atmInputCardScenarios, finite => {
    const scenario = atmInputCardScenarios.find(item => item.id === finite.id)!;
    const cards = m.getRepository(m.BankCard);
    const users = m.getRepository(m.User);
    cards.splice(0); users.splice(0);
    const owner = new m.User();
    const target = Object.assign(new m.BankCard(), {CardID: scenario.key,
      CardStatus: scenario.suspended ? m.CardStatus.SUSPEND : m.CardStatus.NORMAL,
      ...(scenario.owner ? {BelongedUser: owner} : {})});
    const neighbor = Object.assign(new m.BankCard(), {CardID: scenario.key + 123, CardStatus: m.CardStatus.NORMAL});
    if (scenario.owner) users.push(owner);
    if (!scenario.emptyRepository) cards.push(neighbor);
    if (scenario.hasTarget) cards.push(target);
    const service = new m.AutomatedTellerMachineSystem_AutoGenerated();
    service.CardIDValidated = scenario.initialValidated;
    service.InputCard = neighbor;
    return {invoke: () => service.inputCard(scenario.key), observe: result => {
      const checks: FiniteObservation[] = [{obligationId: 'P01', passed: true, expected: 'normal completion', observed: 'completed'}];
      if (scenario.hasTarget) checks.push(
        {obligationId: 'Q01', passed: service.CardIDValidated === true, expected: true, observed: service.CardIDValidated},
        {obligationId: 'Q02', passed: service.InputCard === target, expected: 'exact referenced BankCard', observed: service.InputCard === target ? 'target' : 'other'},
        {obligationId: 'Q03', passed: result === true, expected: true, observed: result});
      else checks.push(
        {obligationId: 'Q04', passed: service.CardIDValidated === false, expected: false, observed: service.CardIDValidated},
        {obligationId: 'Q05', passed: result === false, expected: false, observed: result});
      // The absent-card branch does not specify InputCard; no frame condition is inferred.
      return checks;
    }};
  });
}
export function atmInputCardRegistration(useCase: AtmInputCardUseCase): DevelopmentRegistration {
  return {id: atmInputCardId(useCase), project: 'AutomatedTellerMachine', useCase, operation: 'inputCard',
    schemaVersion: ATM_INPUT_CARD_VERSION, reviewStatus: 'pending-user-review', fixedClock: '2026-01-15T12:00:00+08:00',
    sources: atmInputCardSources, requirementSourceId: 'requirement-document', modelSourceId: 'upstream-model',
    obligations: atmInputCardObligations, scenarios: atmInputCardScenarios.map(({id, obligationIds}) => ({id, obligationIds})),
    moduleExports: {BankCard: 'function', User: 'function', CardStatus: 'object', AutomatedTellerMachineSystem_AutoGenerated: 'function', getRepository: 'function'},
    run: (candidate, options) => runAtmInputCardDevelopment(candidate as AtmInputCardModule, options.requirementText, useCase)};
}
