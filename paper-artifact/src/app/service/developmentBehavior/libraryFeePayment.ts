import dayjs, {type Dayjs} from 'dayjs';
import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios} from './finiteScenarioReport';
import {narrativeDevelopmentProfile} from './narrativeDevelopmentProfiles';
import {librarySearchSources} from './librarySearchSpecification';
import type {DevelopmentRegistration, DevelopmentObligation} from './types';

type User = {UserID: string; OverDueFee: number};
type Loan = {LoanedUser: User; DueDate: Dayjs; ReturnDate?: Dayjs; IsReturned: boolean; OverDueFee: number};
type Module = {User: new () => User; Loan: new () => Loan; getRepository<T>(ctor: new () => T): T[];
  LibraryManagementSystemSystem_AutoGenerated: new () => {payOverDueFee(uid: string, fee: number): unknown}};
const operation = 'payOverDueFee', id = 'LibraryManagementSystem_payOverDueFee_payOverDueFee';
const schemaVersion = 'development-library-overdue-payment-v2';
const obligations: DevelopmentObligation[] = [
  {id:'P01', clause:'precondition', requirement:'The selected user exists.', documentLine:2804, modelLines:[682,682], modelFeatures:['User.UserID','$parameter.uid']},
  {id:'P02', clause:'precondition', requirement:'At least one registered Loan belongs to this user, is returned, is due before today and has a positive fee.',
    documentLine:2805, modelLines:[683,683], evidenceNote:'Loan selection: remodel 673, requirement document 2796.',
    modelFeatures:['Loan.LoanedUser','Loan.DueDate','Loan.IsReturned','Loan.OverDueFee']},
  {id:'P03', clause:'precondition', requirement:'Payment covers the selected user fee.', documentLine:2806, modelLines:[684,684], modelFeatures:['$parameter.fee','User.OverDueFee']},
  {id:'Q01', clause:'postcondition', requirement:'Clear the selected user fee.', documentLine:2815, modelLines:[694,694], modelFeatures:['User.OverDueFee']},
  {id:'Q02', clause:'postcondition', requirement:'Clear the fee of every qualifying Loan.', documentLine:2817, modelLines:[695,696], modelFeatures:['Loan.OverDueFee','Loan.LoanedUser','Loan.IsReturned','Loan.DueDate']},
  {id:'Q03', clause:'postcondition', requirement:'Return true.', documentLine:2819, modelLines:[698,698], modelFeatures:['$result']},
];
const cases: [string, string?][] = [
  ['equal'], ['overpay'], ['zero-user-total'], ['absent','P01'], ['empty','P02'], ['foreign','P02'],
  ['return-date-before-due'], ['return-date-after-due'],
  ['unreturned','P02'], ['today','P02'], ['future','P02'], ['zero-loan','P02'], ['negative-loan','P02'], ['underpay','P03'],
];
const scenarios = cases.map(([key,rejectObligation]) => ({key, id:'dev-payment-'+key, rejectObligation,
  obligationIds:rejectObligation ? [rejectObligation] : obligations.map(o=>o.id)}));
export const libraryFeePayment: DevelopmentRegistration = {
  id, schemaVersion, project:'LibraryManagementSystem', operation, useCase:operation, reviewStatus:'pending-user-review',
  fixedClock:'2026-01-15T12:00:00+08:00', requirementSourceId:'requirement-document', modelSourceId:'upstream-model',
  sources:librarySearchSources.map(s=>({...s,note:'Active payOverDueFee definition, admission conditions and postconditions.'})),
  obligations, scenarios, moduleExports:{User:'function',Loan:'function',getRepository:'function',LibraryManagementSystemSystem_AutoGenerated:'function'},
  run(candidate,{requirementText}) {
    const expected = formatStructuredRequirement(getBenchmarkRequirement('LibraryManagementSystem',operation,operation));
    if (!narrativeDevelopmentProfile(id,requirementText)&&requirementText.replaceAll('\r\n','\n').trim() !== expected.replaceAll('\r\n','\n').trim()) throw new Error('Fee payment requirement differs from frozen input');
    const m = candidate as Module;
    const report=runFiniteScenarios({id,schemaVersion,obligations}, scenarios, base => {
      const {key} = scenarios.find(s=>s.id === base.id)!;
      const users = m.getRepository(m.User), loans = m.getRepository(m.Loan);
      users.splice(0); loans.splice(0);
      const user = Object.assign(new m.User(), {UserID:'dev-pay', OverDueFee:key==='zero-user-total' ? 0 : 4.5});
      const other = Object.assign(new m.User(), {UserID:'dev-other', OverDueFee:50});
      users.push(other); if (key !== 'absent') users.push(user);
      const payment = user.OverDueFee + (key==='underpay' ? -0.25 : key==='overpay' ? 3 : 0);
      const today = dayjs().startOf('day');
      const loan = (owner:User, days:number, returned:boolean, fee:number) =>
        Object.assign(new m.Loan(), {LoanedUser:owner, DueDate:today.add(days,'day'), IsReturned:returned, OverDueFee:fee});
      const qualifying: Loan[] = [];
      if (['equal','overpay','zero-user-total','underpay','return-date-before-due','return-date-after-due'].includes(key)) {
        qualifying.push(loan(user,-1,true,8),loan(user,-3,true,1.75));
        // ReturnDate is not an admission variable in the cited source definition.
        // Vary it while keeping all source-required applicability facts unchanged.
        if(key==='return-date-before-due'||key==='return-date-after-due')
          qualifying.forEach(item=>{item.ReturnDate=item.DueDate.add(key==='return-date-before-due'?-2:2,'day');});
        loans.push(loan(other,-2,true,9), ...qualifying);
      } else if (key !== 'empty' && key !== 'absent') {
        loans.push(loan(key==='foreign' ? other : user, key==='today' ? 0 : key==='future' ? 2 : -2,
          key!=='unreturned', key==='zero-loan' ? 0 : key==='negative-loan' ? -2 : 5));
      }
      const admission = [users.includes(user),qualifying.length>0,payment>=user.OverDueFee];
      const state = () => [
        {obligationId:'Q01',passed:user.OverDueFee===0,expected:0,observed:user.OverDueFee},
        {obligationId:'Q02',passed:qualifying.every(l=>l.OverDueFee===0),expected:qualifying.map(()=>0),observed:qualifying.map(l=>l.OverDueFee)},
      ];
      return {invoke:()=>new m.LibraryManagementSystemSystem_AutoGenerated().payOverDueFee(user.UserID,payment),
        observePrecondition:code=>({satisfied:admission[Number(code.slice(1))-1],expected:obligations[Number(code.slice(1))-1].requirement,observed:admission[Number(code.slice(1))-1]}),
        observeAfterPostcheckFailure:state,
        observe:result=>[...obligations.slice(0,3).map(o=>({obligationId:o.id,passed:true,expected:'accepted',observed:'completed'})),
          ...state(),{obligationId:'Q03',passed:result===true,expected:true,observed:result}]};
    });
    return {...report,selectorCoverage:{sourceObligations:['P02','Q02'],
      variedContextField:'Loan.ReturnDate',unchangedApplicabilityFields:['Loan.LoanedUser','Loan.DueDate','Loan.IsReturned','Loan.OverDueFee'],
      basis:'The cited operation defines applicability using DueDate before Today, not ReturnDate. The additional positive scenarios vary an otherwise unconstrained field; no frame or positivity requirement is added.'}};
  },
};
