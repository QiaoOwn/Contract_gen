import {formatStructuredRequirement, getBenchmarkRequirement} from '@/rm2pt/benchmarkRequirements';
import {runFiniteScenarios, type FiniteObservation} from './finiteScenarioReport';
import {cocomeAggregationSpecifications, cocomeAggregationScenarios, type CocomeAggregation} from './cocomeAggregationSpecification';
import type {DevelopmentRegistration} from './types';
import {narrativeDevelopmentProfile} from './narrativeDevelopmentProfiles';

type Entity = Record<string, unknown>;
export type CocomeAggregationModule = Record<string, unknown> & {getRepository: (ctor: new () => object) => object[]};
export function runCocomeAggregationDevelopment(m: CocomeAggregationModule, requirement: string, operation: CocomeAggregation) {
  const spec = cocomeAggregationSpecifications[operation];
  const expected = formatStructuredRequirement(getBenchmarkRequirement('CoCoME', spec.useCase, operation));
  const normalize = (text: string) => text.replaceAll('\r\n', '\n').trim();
  if (!narrativeDevelopmentProfile(spec.id,requirement)&&normalize(requirement) !== normalize(expected)) throw new Error('CoCoME aggregation requirement differs from the adjudicated input');
  const Constructor = (name: string) => m[name] as new () => Entity;
  const create = (name: string, fields: Entity = {}) => Object.assign(new (Constructor(name))(), fields);
  const enumValue = (value: string) => (m.OrderStatus as Record<string, unknown>)[value];
  return runFiniteScenarios(spec, cocomeAggregationScenarios[operation], base => {
    const scenario = cocomeAggregationScenarios[operation].find(item => item.id === base.id)!;
    for (const name of ['OrderProduct', 'OrderEntry', 'Sale', 'SalesLineItem', 'Item']) m.getRepository(Constructor(name)).splice(0);
    const Service = m[`${spec.service}_AutoGenerated`] as new () => Record<string, unknown>;
    const service = new Service();
    const order = create('OrderProduct', {Id: 843017, Amount: scenario.beforeAmount ?? 0});
    const sale = create('Sale', {Amount: scenario.beforeAmount ?? 777, IsComplete: scenario.complete ?? false, IsReadytoPay: scenario.ready ?? false});
    const items = (scenario.stocks ?? []).map((stock, index) => create('Item', {Barcode: 843101 + index, StockNumber: stock}));
    const entries = operation === 'receiveOrderedProduct'
      ? (scenario.entries ?? []).map(entry => create('OrderEntry', {Item: items[entry.item], Quantity: entry.quantity}))
      : (scenario.subtotals ?? []).map(amount => create('OrderEntry', {SubAmount: amount}));
    order.ContainedEntries = entries;
    const lines = (scenario.subtotals ?? []).map(amount => create('SalesLineItem', {Subamount: amount}));
    sale.ContainedSalesLine = lines;
    if (!scenario.missing) {
      if (operation === 'placeOrder') service.CurrentOrderProduct = order;
      if (operation === 'endSale') service.CurrentSale = sale;
      m.getRepository(Constructor('OrderProduct')).push(order);
    }
    if (operation === 'receiveOrderedProduct') {
      const neighbor = create('OrderProduct', {Id: 843999, ContainedEntries: []});
      m.getRepository(Constructor('OrderProduct')).unshift(neighbor);
    }
    m.getRepository(Constructor('Item')).push(...items);
    m.getRepository(Constructor('OrderEntry')).push(...entries);
    m.getRepository(Constructor('SalesLineItem')).push(...lines);
    const preconditions: Record<string, boolean> = {P01: !scenario.missing,
      P02: !scenario.missing && !scenario.complete, P03: !scenario.missing && !scenario.ready};
    const stateObservations = (): FiniteObservation[] => {
      const profile=narrativeDevelopmentProfile(spec.id,requirement);
      const preserveCompletion=operation==='endSale'&&profile&&'laboratoryClarification' in profile&&
        profile.laboratoryClarification==="The operation does not change the current Sale's IsComplete value.";
      const status = operation === 'endSale' ? sale.IsReadytoPay === true&&(!preserveCompletion||sale.IsComplete===(scenario.complete??false))
        : order.OrderStatus === enumValue(operation === 'placeOrder' ? 'REQUESTED' : 'RECEIVED');
      const observed = operation === 'receiveOrderedProduct' ? items.map(item => item.StockNumber)
        : (operation === 'placeOrder' ? order.Amount : sale.Amount);
      const amountMatches = operation === 'receiveOrderedProduct'
        ? (scenario.expectedStocks ?? []).length === items.length && items.every((item, index) => Object.is(item.StockNumber, scenario.expectedStocks![index]))
        : Object.is(observed, scenario.expectedAmount);
      return [{obligationId: 'Q01', passed: status, expected: operation === 'endSale' ? 'ready for payment' : 'source-prescribed order status', observed: status},
        {obligationId: 'Q02', passed: amountMatches, expected: operation === 'receiveOrderedProduct' ? scenario.expectedStocks : scenario.expectedAmount, observed}];
    };
    return {invoke: () => {
      const method = service[operation] as (...args: unknown[]) => unknown;
      if (typeof method !== 'function') throw new Error('Missing aggregation candidate method');
      return method.apply(service, operation === 'receiveOrderedProduct' ? [order.Id] : []);
    }, observePrecondition: id => ({satisfied: preconditions[id], expected: spec.obligations.find(item => item.id === id)!.requirement, observed: preconditions[id]}),
    observeAfterPostcheckFailure: stateObservations,
    observe: result => [
      ...scenario.obligationIds.filter(id => id.startsWith('P')).map(id => ({obligationId: id, passed: true, expected: 'accept source-valid input', observed: 'accepted'})),
      ...stateObservations(),
      {obligationId: 'Q03', passed: operation === 'endSale' ? Object.is(result, scenario.expectedAmount) : result === true,
        expected: operation === 'endSale' ? scenario.expectedAmount : true, observed: result},
    ]};
  });
}
export function cocomeAggregationRegistration(operation: CocomeAggregation): DevelopmentRegistration {
  const spec = cocomeAggregationSpecifications[operation];
  return {id: spec.id, project: 'CoCoME', useCase: spec.useCase, operation, schemaVersion: spec.schemaVersion,
    reviewStatus: 'pending-user-review', fixedClock: '2026-01-15T12:00:00+08:00', sources: spec.sources,
    requirementSourceId: 'adjudication', modelSourceId: 'upstream-model', obligations: spec.obligations,
    scenarios: cocomeAggregationScenarios[operation].map(({id, obligationIds}) => ({id, obligationIds})),
    moduleExports: {OrderProduct: 'function', OrderEntry: 'function', Sale: 'function', SalesLineItem: 'function', Item: 'function',
      ...(operation === 'endSale' ? {} : {OrderStatus: 'object'}), [`${spec.service}_AutoGenerated`]: 'function', getRepository: 'function'},
    run: (candidate, options) => runCocomeAggregationDevelopment(candidate as CocomeAggregationModule, options.requirementText, operation)};
}
