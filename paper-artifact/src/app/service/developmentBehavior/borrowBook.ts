// Structural adapter for generated modules; this is not a replacement model or reference implementation.
// Generated entity modules expose operation-specific fields only at runtime.
// eslint-disable-next-line @typescript-eslint/no-explicit-any
type Entity = Record<string, any>;
export type BorrowBookModule = {
  User: new () => Entity;
  Student: new () => Entity;
  Faculty: new () => Entity;
  BookCopy: new () => Entity;
  Loan: new () => Entity;
  Reserve: new () => Entity;
  Programme: Record<string, unknown>;
  BorrowStatus: Record<string, unknown>;
  CopyStatus: Record<string, unknown>;
  LibraryManagementSystemSystem_AutoGenerated: new () => {
    borrowBook(uid: string, barcode: string): unknown;
  };
  getRepository: (entity: new () => Entity) => Entity[];
};

const seed = (m: BorrowBookModule, scenario: BorrowBookScenario) => {
  for (const type of [m.User, m.Student, m.Faculty, m.BookCopy, m.Loan, m.Reserve]) {
    m.getRepository(type).splice(0);
  }
  const user = scenario.kind === 'student' ? new m.Student() : new m.Faculty();
  Object.assign(user, {
    UserID: 'DEV-READER-42',
    BorrowStatus: m.BorrowStatus[scenario.suspended ? 'SUSPEND' : 'NORMAL'],
    SuspensionDays: scenario.suspensionDays ?? 0,
    LoanedNumber: scenario.loanCount,
    LoanedBook: [],
  });
  if (scenario.kind === 'student') user.Programme = m.Programme[scenario.programme ?? 'MASTER'];
  const copy: Entity = Object.assign(new m.BookCopy(), {
    Barcode: 'DEV-COPY-73',
    Status: m.CopyStatus[scenario.copy],
    IsReserved: Boolean(scenario.reservation),
    LoanedRecord: [],
  });
  if (scenario.missing !== 'user') {
    m.getRepository(m.User).push(user);
    m.getRepository(scenario.kind === 'student' ? m.Student : m.Faculty).push(user);
  }
  if (scenario.missing !== 'copy') m.getRepository(m.BookCopy).push(copy);
  let reservation: Entity | undefined;
  if (scenario.reservation) {
    const owner =
      scenario.reservation === 'foreign'
        ? Object.assign(new m.Student(), {UserID: 'DEV-OTHER-91'})
        : user;
    if (owner !== user) {
      m.getRepository(m.User).push(owner);
      m.getRepository(m.Student).push(owner);
    }
    reservation = Object.assign(new m.Reserve(), {
      ReservedCopy: copy,
      ReservedUser: owner,
      IsReserveClosed: false,
    });
    m.getRepository(m.Reserve).push(reservation);
  }
  return {user, copy, reservation, service: new m.LibraryManagementSystemSystem_AutoGenerated()};
};

export function runBorrowBookDevelopment(
  m: BorrowBookModule,
  options: {requirementText?: string} = {}
) {
  const inputAlignment = assessBorrowBookInputAlignment(
    options.requirementText ??
      formatStructuredRequirement(
        getBenchmarkRequirement('LibraryManagementSystem', 'borrowBook', 'borrowBook')
      )
  );
  const inputDetailIssues = inputAlignment.filter(
    (item) => item.status === 'not-explicit-in-generation-text'
  );
  const diagnostics: DevelopmentDiagnostic[] = [];
  const checks: {
    scenarioId: string;
    obligationId: string;
    passed: boolean | null;
    expected: unknown;
    observed: unknown;
  }[] = [];
  const executionObservations: {
    scenarioId: string;
    classification:
      | 'completed'
      | 'explicit-rejection'
      | 'definition-failure-unresolved'
      | 'runtime-error'
      | 'return-without-rejection-signal';
    conventionStatus: 'matched' | 'mismatched' | 'inconclusive';
  }[] = [];
  for (const scenario of borrowBookScenarios) {
    const {user, copy, reservation, service} = seed(m, scenario);
    const check = (id: string, passed: boolean | null, expected: unknown, observed: unknown) => {
      checks.push({scenarioId: scenario.id, obligationId: id, passed, expected, observed});
      if (passed === false)
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: inputDetailIssues.some((item) => item.obligationId === id)
            ? 'SPECIFICATION_DETAIL_MISMATCH'
            : 'OBLIGATION_MISMATCH',
          obligationIds: [id],
          expected,
          observed,
          message: borrowBookObligations.find((item) => item.id === id)!.requirement,
        });
    };
    let result: unknown;
    let failure: {name: string; message: string} | undefined;
    const today = dayjs();
    try {
      result = service.borrowBook(user.UserID, copy.Barcode);
    } catch (error) {
      const value = error as Error;
      failure = {name: value?.name ?? 'Error', message: value?.message ?? String(error)};
    }
    if (failure) {
      const definitionFailure =
        failure.name === 'PreconditionError' &&
        failure.message.includes('definition binding could not be evaluated');
      executionObservations.push({
        scenarioId: scenario.id,
        classification: definitionFailure
          ? 'definition-failure-unresolved'
          : failure.name === 'PreconditionError'
            ? 'explicit-rejection'
            : 'runtime-error',
        conventionStatus: definitionFailure
          ? 'inconclusive'
          : failure.name === 'PreconditionError'
            ? 'matched'
            : 'mismatched',
      });
      if (scenario.rejectObligation && failure.name === 'PreconditionError' && !definitionFailure) {
        check(scenario.rejectObligation, true, 'precondition rejection', failure.name);
      } else {
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: definitionFailure
            ? 'REJECTION_UNRESOLVED'
            : failure.name === 'PreconditionError' && !scenario.rejectObligation
              ? 'UNEXPECTED_REJECTION'
              : 'EXECUTION_ERROR',
          obligationIds:
            !definitionFailure && failure.name === 'PreconditionError' && !scenario.rejectObligation
              ? borrowBookObligations
                  .filter((item) => item.clause === 'precondition')
                  .map((item) => item.id)
              : [],
          expected: scenario.rejectObligation ? 'precondition rejection' : 'successful checkout',
          observed: failure,
          message: definitionFailure
            ? 'A definition binding failed under the rejection wrapper. Its intended-versus-accidental status needs analysis; this is not automatically a business violation or a correct rejection.'
            : 'Execution did not reach the expected outcome. A runtime failure alone does not identify a violated business obligation.',
        });
      }
      continue;
    }
    if (scenario.rejectObligation) {
      executionObservations.push({
        scenarioId: scenario.id,
        classification: 'return-without-rejection-signal',
        conventionStatus: 'mismatched',
      });
      if (result === true || m.getRepository(m.Loan).length > 0) {
        check(
          scenario.rejectObligation,
          false,
          'no successful checkout for this ineligible request',
          {result, registeredLoanCount: m.getRepository(m.Loan).length}
        );
      } else {
        check(scenario.rejectObligation, null, 'request is rejected', {result: result ?? null});
        diagnostics.push({
          kind: 'development-behavior',
          scenarioId: scenario.id,
          code: 'REJECTION_UNRESOLVED',
          obligationIds: [],
          expected: 'a recognized rejection outcome',
          observed: {result: result ?? null},
          message:
            'The operation returned without a recognized rejection signal. This violates the current adapter convention, but does not alone establish a business-requirement violation.',
        });
      }
      continue;
    }
    executionObservations.push({
      scenarioId: scenario.id,
      classification: 'completed',
      conventionStatus: 'matched',
    });
    for (const item of borrowBookObligations.filter((item) => item.clause === 'precondition')) {
      check(item.id, true, 'accept this eligible fixture', 'accepted');
    }
    const loan = m.getRepository(m.Loan)[0];
    check('Q01', Boolean(loan), 'a newly registered loan', Boolean(loan));
    // Missing creation is reported once; downstream obligations remain explicitly unobserved.
    if (loan) {
      check('Q02', loan.LoanedUser === user, 'requesting user', loan.LoanedUser?.UserID ?? null);
      check('Q03', loan.LoanedCopy === copy, 'requested copy', loan.LoanedCopy?.Barcode ?? null);
      check('Q04', loan.IsReturned === false, false, loan.IsReturned ?? null);
      check(
        'Q05',
        Boolean(loan.LoanDate?.isSame?.(today, 'day')),
        today.format('YYYY-MM-DD'),
        loan.LoanDate?.format?.('YYYY-MM-DD') ?? null
      );
      const userLinked = Array.isArray(user.LoanedBook) && user.LoanedBook.includes(loan);
      const copyLinked = Array.isArray(copy.LoanedRecord) && copy.LoanedRecord.includes(loan);
      check('Q07', userLinked, 'new loan is in user collection', userLinked);
      check('Q08', copyLinked, 'new loan is in copy collection', copyLinked);
      const due = today.add(scenario.kind === 'student' ? 30 : 60, 'day');
      check(
        'Q09',
        Boolean(loan.DueDate?.isSame?.(due, 'day')),
        due.format('YYYY-MM-DD'),
        loan.DueDate?.format?.('YYYY-MM-DD') ?? null
      );
      [3, 10, 17, 31].forEach((days, index) => {
        check(
          `Q${13 + index}`,
          loan[`OverDue${days}Days`] === false,
          false,
          loan[`OverDue${days}Days`] ?? null
        );
      });
    }
    check(
      'Q06',
      user.LoanedNumber === scenario.loanCount + 1,
      scenario.loanCount + 1,
      user.LoanedNumber
    );
    if (scenario.copy === 'ONHOLDSHELF') {
      check('Q10', copy.IsReserved === false, false, copy.IsReserved);
      check('Q11', reservation?.IsReserveClosed === true, true, reservation?.IsReserveClosed);
    }
    check('Q12', copy.Status === m.CopyStatus.LOANED, m.CopyStatus.LOANED, copy.Status);
    check('Q17', result === true, true, result ?? null);
  }
  const observed = new Set(
    checks.filter((item) => item.passed !== null).map((item) => item.obligationId)
  );
  const businessStatus = diagnostics.some((item) =>
    ['OBLIGATION_MISMATCH', 'SPECIFICATION_DETAIL_MISMATCH', 'UNEXPECTED_REJECTION'].includes(
      item.code
    )
  )
    ? 'mismatched'
    : diagnostics.length
      ? 'inconclusive'
      : 'matched';
  const executionConventionStatus = executionObservations.some(
    (item) => item.conventionStatus === 'mismatched'
  )
    ? 'mismatched'
    : executionObservations.some((item) => item.conventionStatus === 'inconclusive')
      ? 'inconclusive'
      : 'matched';
  return {
    schemaVersion: DEVELOPMENT_BEHAVIOR_VERSION,
    operationId: BORROW_BOOK_ID,
    role: 'development_only' as const,
    reviewStatus: 'pending-user-review' as const,
    assessmentPolicy: borrowBookAssessmentPolicy,
    inputAlignment,
    inputDetailIssues,
    businessAssessmentBasis: 'cited-upstream-operation-specification',
    businessStatus,
    executionConventionStatus,
    executionObservations,
    hiddenEvaluationUsed: false,
    dynamicRepairEnabled: false,
    coverageScope: 'finite-development-scenarios' as const,
    scenarioCount: borrowBookScenarios.length,
    scenarioResults: borrowBookScenarios.map((scenario) => ({
      id: scenario.id,
      passed: !diagnostics.some((diagnostic) => diagnostic.scenarioId === scenario.id),
      checkCount: checks.filter((check) => check.scenarioId === scenario.id).length,
    })),
    checks,
    diagnostics,
    passed:
      businessStatus === 'matched' && executionConventionStatus === 'matched' && checks.length > 0,
    unobservedObligationIds: borrowBookObligations
      .filter((item) => !observed.has(item.id))
      .map((item) => item.id),
  };
}

export function developmentCandidateScope(
  obligation: DevelopmentObligation,
  ocl: {
    definition: string;
    precondition: string;
    postcondition: string;
  }
) {
  return {
    resolution: 'clause-only' as const,
    clauses: ['definition', obligation.clause],
    expressions: {definition: ocl.definition, [obligation.clause]: ocl[obligation.clause]},
    note: 'Requirement/model dependencies identify a search scope, not a proven faulty expression or root cause.',
  };
}
